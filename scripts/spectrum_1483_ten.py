#!/usr/bin/env python3
"""Generate the order-ten specialization of the checked E1483 rank encoding.

The existing order-eleven implementation is the template. Besides the order,
this changes the rank thresholds from (3,6),(4,4),(6,3) to (3,5),(4,4),(5,3).
The exclusion of constant rows uses the new power-of-two theorem. Lean rechecks
all normalization and CNF soundness arguments after these substitutions.
"""
import argparse
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'equational_theories/Spectrum/Equation1483'
NS='Spectrum.E1483.OrderTen'


def render():
    sat=(ROOT/'equational_theories/Definability/Central1483SAT.lean').read_text()
    sat=sat.replace('Magma.Central1483',NS)
    sat=re.sub(r'\b(?:11|10|6)\b',lambda m:{'11':'10','10':'9','6':'5'}[m[0]],sat)
    norm=(ROOT/'equational_theories/Definability/Central1483Normalization.lean').read_text()
    norm=norm.replace('import equational_theories.Definability.Central1483SAT',
      'import equational_theories.Spectrum.Equation1483.TenSAT\nimport equational_theories.Spectrum.Equation1483.ConstantSpectrum')
    norm=norm.replace('Magma.Central1483',NS).replace('eleven-element','ten-element')
    norm=re.sub(r'\b(?:11|10)\b',lambda m:{'11':'10','10':'9'}[m[0]],norm)
    old='''  have hd := CentralConstant.even_card_of_constant_row he a b hb
    (CentralConstant.constant_values_ne he a b hb)
  norm_num [A, Nat.card_eq_fintype_card] at hd'''
    new='''  obtain ⟨k, hk⟩ := Spectrum.E1483.Constant.card_pow_two he a b hb
  have hk' : 10 = 2 ^ k := by simpa [A, Nat.card_eq_fintype_card] using hk
  have hlt : k < 4 := by
    by_contra hn
    have hp := Nat.pow_le_pow_right (by decide : 0 < (2 : ℕ)) (show 4 ≤ k by omega)
    norm_num at hp
    omega
  interval_cases k <;> norm_num at hk' '''.rstrip()
    assert old in norm
    norm=norm.replace(old,new).replace('code11_injective','code10_injective')
    banner='/- Generated by scripts/spectrum_1483_ten.py; see that script for the exact specialization. -/\n'
    return {'TenSAT.lean':banner+sat,'TenNormalization.lean':banner+norm}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write',action='store_true')
    a=p.parse_args()
    for name,text in render().items():
        path=DEST/name
        if a.write:path.write_text(text)
        else:assert path.read_text()==text,f'{path} is stale'

if __name__=='__main__':main()
