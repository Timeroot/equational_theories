#!/usr/bin/env python3
"""Emit the checked reversible-swap catalogue from its saved proof data.

The discovery search and ATP results are not proof oracles. Every emitted target
law and every inverse is checked by Lean; public declarations have axiom guards.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/definability_diagonal_swaps.json'
OUT = ROOT / 'equational_theories/Definability'


def emit(entries):
    imports = []
    for offset in range(0, len(entries), 32):
        name = f'DiagonalSwapCatalogue{offset // 32 + 1:02}'
        imports.append(f'import equational_theories.Definability.{name}')
        lines = ['import equational_theories.Definability.ComposedDiagonalSwaps',
                 'import equational_theories.Superposition', '',
                 '/-! Generated by `scripts/definability_diagonal_swaps.py`.',
                 'The source-only algebraic lemmas are replayed by superposition;',
                 'the target laws use finite case analysis, on arbitrary carriers. -/', '',
                 'open Law Law.MagmaLaw DiagonalOutputSwap',
                 'set_option maxHeartbeats 500000', 'set_option maxRecDepth 10000',
                 '-- Generated orientation alternatives may become redundant after elaboration.',
                 'set_option linter.unusedTactic false',
                 'set_option linter.unreachableTactic false', '']
        for r in entries[offset:offset + 32]:
            a, b, o = r['source'], r['target'], str(r['opposite']).lower()
            target = 'M'
            for n, (i, j) in enumerate(r['swaps']):
                target = f'((forward {i} {j} {o if n == 0 else "false"}).magma {target})'
            i, j = r['swaps'][0]
            if len(r['swaps']) == 1:
                helper = f'structuralFrom_diagonalOutputSwap {i} {j} {o}'
            elif len(r['swaps']) == 2:
                k, l = r['swaps'][1]
                helper = f'structuralFrom_twoDiagonalSwaps {i} {j} {k} {l} {o}'
            elif len(r['swaps']) == 3:
                k, l = r['swaps'][1]
                u, v = r['swaps'][2]
                helper = f'structuralFrom_threeDiagonalSwaps {i} {j} {k} {l} {u} {v} {o}'
            else:
                raise ValueError('Unsupported sequence length')
            name = r['theorem']
            lines += [f'private theorem target_{a}_{b} {{G : Type}} (M : Magma G) (h : @Equation{a} G M) :',
                      f'    @Equation{b} G {target} := by', r['lean_proof'].rstrip(), '',
                      f'theorem {name} : Law{b}.StructuralFrom Law{a} :=',
                      f'  {helper} fun {{G}} M hM =>',
                      f'    (@Law{b}.models_iff G {target}).mpr',
                      f'      (target_{a}_{b} M ((@Law{a}.models_iff G M).mp hM))', '',
                      f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
                      '#guard_msgs (whitespace := lax) in', f'#print axioms {name}', '']
        (OUT / f'DiagonalSwapCatalogue{offset // 32 + 1:02}.lean').write_text('\n'.join(lines))
    (OUT / 'DiagonalSwapCatalogue.lean').write_text('\n'.join(imports) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit-lean', action='store_true')
    args = parser.parse_args()
    entries = json.loads(DATA.read_text())['certificates']
    assert len({(r['source'], r['target']) for r in entries}) == len(entries)
    assert all(1 <= r['source'] <= 4694 and 1 <= r['target'] <= 4694 for r in entries)
    assert all(all(0 <= i < 6 for pair in r['swaps'] for i in pair) for r in entries)
    if args.emit_lean:
        emit(entries)
    print(f'{len(entries)} saved, Lean-checked generators')


if __name__ == '__main__':
    main()
