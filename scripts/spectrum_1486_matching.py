#!/usr/bin/env python3
"""Construct E1486 matching expansions and generate small Lean certificates.

No solver is used. The model is independently checked on all law instances
before writing a certificate. The Lean proof checks the smaller factorization
certificate with kernel reduction; no native computation axioms are used.
"""
from itertools import product
from pathlib import Path
import argparse
import json

ROOT=Path(__file__).resolve().parents[1]
ORDERS=[19,23,28,30,32,34,41,43,45,47,62]


def model(n,edges):
    size={}
    occupied=set()
    for (a,b),(k,l) in edges.items():
        assert 0<=a<b<n and not ({a,b}&occupied)
        occupied.update((a,b))
        assert 2<=k<n and 2<=l<n
        size[a,b]=k;size[b,a]=l
    points=[(a,b,t) for a in range(n) for b in range(n)
            for t in (range(size[a,b]) if(a,b)in size else [-1])]
    fallback={}; normaltype={}
    for b in range(n):
        required=max([v for(a,c),v in size.items() if a==b]+[1])
        ordinary=[a for a in range(n) if(a,b)not in size]
        assert len(ordinary)>=required
        for i,a in enumerate(ordinary):normaltype[a,b]=i%required
        for t in range(required):fallback[b,t]=(ordinary[t],b,-1)
    def kind(x):
        a,b,t=x
        if t==-1:return normaltype[a,b]
        return int(t==1) if a<b else int(t==0)
    def select(a,b,t):
        if(a,b)not in size:return(a,b,-1)
        assert t<size[a,b]
        return(a,b,t)
    def op(x,y):
        a,b,u=x;c,d,t=y
        w=select(b,c,kind(x))
        return w if t==-1 or kind(w)==t else fallback[c,t]
    ids={p:i for i,p in enumerate(points)}
    table=[[ids[op(a,b)] for b in points] for a in points]
    squares={table[i][i] for i in range(len(table))}
    assert all(points[s][2]==-1 for s in squares)
    for x,y,s in product(range(len(table)),range(len(table)),squares):
        assert table[table[y][x]][table[x][s]]==x
    right=[[ids[select(p[1],c,kind(p))] for c in range(n)]for p in points]
    coord=[points[table[z][z]][0] for z in range(len(table))]
    N=len(table)
    assert all(table[x][table[z][z]]==right[x][coord[z]]for x,z in product(range(N),repeat=2))
    assert all(table[table[y][x]][right[x][c]]==x for x,y,c in product(range(N),range(N),range(n)))
    return table,right,coord


def recipe(N):
    for n in range(4,N):
        extra=N-n*n
        if not 2<=extra<=4*n-8:continue
        k=2 if extra<=2*(n-2) else 4
        units=[1]*k;todo=extra-k
        for i in range(k):
            inc=min(todo,n-3);units[i]+=inc;todo-=inc
        assert todo==0
        edges={(0,1):(units[0]+1,units[1]+1)}
        if k==4:edges[2,3]=(units[2]+1,units[3]+1)
        return n,edges
    raise ValueError(N)


def packed(values,width):
    return sum(v<<(i*width)for i,v in enumerate(values))


def lean_source(N,n,table,right,coord):
    w=(N-1).bit_length();c=(n-1).bit_length()
    def array(name,vals,width,out,shape):
        exp=('x.val * '+str(shape[1])+' + y.val') if len(shape)==2 else 'x.val'
        args=f'(x : Fin {shape[0]})'+(f' (y : Fin {shape[1]})'if len(shape)==2 else '')
        return f'''private def {name}Data : Nat := {hex(packed(vals,width))}
private def {name} {args} : Fin {out} :=
  ⟨(({name}Data >>> (({exp}) * {width})) % {2**width}) % {out}, Nat.mod_lt _ (by decide)⟩
'''
    return f'''import equational_theories.Spectrum.Equation1486.Certificate

/-! Generated by scripts/spectrum_1486_matching.py.
Order {N}, from a matching expansion of the {n}² coordinate system.
The table and its factorization certificate are checked by kernel reduction. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1486.Witness{N}

'''+array('table',sum(table,[]),w,N,[N,N])+array('right',sum(right,[]),w,N,[N,n])+array('coord',coord,c,n,[N])+f'''
private theorem inner : ∀ x z, table x (table z z) = right x (coord z) := by decide +kernel
private theorem outer : ∀ x y i, table (table y x) (right x i) = x := by decide +kernel

theorem hasModel : Law1486.HasModel {N} :=
  ⟨⟨table⟩, (@Law1486.models_iff _ ⟨table⟩).mpr
    (law_of_factor table right coord inner outer)⟩

/-- info: 'Spectrum.E1486.Witness{N}.hasModel' depends on axioms: [propext, Quot.sound] -/
#guard_msgs in
#print axioms hasModel

end Spectrum.E1486.Witness{N}
'''


def main():
    p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');a=p.parse_args()
    report={}
    for N in ORDERS:
        n,edges=recipe(N);t,r,c=model(n,edges);assert len(t)==N
        report[str(N)]={'base_order':n,'edges':[[i,j,k,l]for(i,j),(k,l)in edges.items()],
                        'table':t,'square_coordinate':c,'right_factor':r}
        out=ROOT/f'equational_theories/Spectrum/Equation1486/Witnesses/N{N}.lean'
        s=lean_source(N,n,t,r,c)
        if a.write:out.write_text(s)
        else:assert out.read_text()==s,out
    out=ROOT/'data/spectrum/1486_matching_witnesses.json'
    s=json.dumps(report,indent=2)+'\n'
    if a.write:out.write_text(s)
    else:assert out.read_text()==s
    print('Checked',len(ORDERS),'models and generated Lean certificates.')

if __name__=='__main__':main()
