#!/usr/bin/env python3
"""Reconstruct a finite relation-preservation obstruction for E1480 → E1482.

The source and eight compatible relations are checked independently. Search
produces an exhaustive tree; its generated Lean proof verifies each step using
ground law instances, finite relation implications, and complete case splits.
No external solver or historical model bank is needed.
"""

import argparse
from collections import Counter
from itertools import product
from pathlib import Path

from spectrum_generate import load_equations, satisfies

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "equational_theories/Definability/Generated/Relation1482.lean"
SOURCE = (
    (2, 6, 6, 6, 2, 3, 6, 1),
    (7, 3, 7, 7, 2, 3, 0, 7),
    (4, 4, 0, 4, 4, 3, 0, 1),
    (5, 5, 5, 1, 2, 5, 0, 1),
    (4, 4, 0, 4, 4, 3, 0, 1),
    (5, 5, 5, 1, 2, 5, 0, 1),
    (2, 6, 6, 6, 2, 3, 6, 1),
    (7, 3, 7, 7, 2, 3, 0, 7),
)
RELATIONS = (
    ((7, 7),),
    ((4, 6),),
    ((5, 7),),
    ((4, 1), (4, 3), (4, 5), (4, 7)),
    ((0, 3), (2, 1), (4, 7), (6, 5)),
    ((0, 0), (1, 3), (2, 2), (3, 1), (4, 4), (5, 7), (6, 6), (7, 5)),
    ((0, 1), (1, 0), (2, 3), (3, 2), (4, 5), (5, 4), (6, 7), (7, 6)),
    ((1, 0), (1, 4), (3, 2), (3, 4), (5, 4), (7, 0), (7, 2), (7, 4), (7, 6)),
)
RULES = [(x, y, ((y, x), (x, (y, y)))) for x, y in product(range(8), repeat=2)]
CONSTRAINTS = [(i, (a, c), (b, d)) for i, relation in enumerate(RELATIONS)
               for (a, b), (c, d) in product(relation, repeat=2)]


def search():
    def visit(table):
        forced = []
        while True:
            needed = Counter()

            def evaluate(term):
                if isinstance(term, int):
                    return term
                a, b = map(evaluate, term)
                if a is None or b is None:
                    return None
                if (a, b) not in table:
                    needed[a, b] += 1
                return table.get((a, b))

            force = None
            for index, (x, _, rhs) in enumerate(RULES):
                a, b = map(evaluate, rhs)
                if a is None or b is None:
                    continue
                if (a, b) in table:
                    if table[a, b] != x:
                        return dict(forced=forced, fail_law=index)
                else:
                    force = ("law", index, (a, b), x)
                    break
            if force is None:
                for index, (ri, c1, c2) in enumerate(CONSTRAINTS):
                    v1, v2 = table.get(c1), table.get(c2)
                    relation = RELATIONS[ri]
                    if v1 is not None and v2 is not None:
                        if (v1, v2) not in relation:
                            return dict(forced=forced, fail_rel=index)
                    elif v1 is not None or v2 is not None or c1 == c2:
                        possible = [(a, b) for a, b in relation
                                    if (v1 is None or a == v1) and (v2 is None or b == v2)
                                    and (c1 != c2 or a == b)]
                        if not possible:
                            return dict(forced=forced, fail_rel=index)
                        for cell, values in ((c1, {a for a, _ in possible}),
                                             (c2, {b for _, b in possible})):
                            if cell not in table:
                                if len(values) == 1:
                                    force = ("rel", index, cell, next(iter(values)))
                                    break
                                needed[cell] += 8 - len(values)
                        if force:
                            break
                    elif len(relation) == 1:
                        force = ("rel", index, c1, relation[0][0])
                        break
            if force is None:
                break
            forced.append(force)
            table[force[2]] = force[3]
        if not needed:
            raise RuntimeError(f"Found a target model: {table}")
        cell = max(needed, key=needed.get)
        branches = []
        for value in range(8):
            child = table.copy()
            child[cell] = value
            branches.append(visit(child))
        return dict(forced=forced, split=cell, branches=branches)

    return visit({})


def render(tree):
    relation_text = ",\n     ".join(
        "fun x y => " + " || ".join(f"(x == {a} && y == {b})" for a, b in relation)
        for relation in RELATIONS)
    lines = [
        "import Mathlib.Data.Fin.VecNotation",
        "import Mathlib.Data.Fintype.Fin", "",
        "/-! Generated by `scripts/definability_relation_check.py`.",
        "All relation implications and every case branch are checked in the Lean kernel.",
        "There are no native evaluation or solver axioms. -/", "",
        "set_option maxHeartbeats 8000000", "set_option maxRecDepth 10000", "",
        "namespace Definability.Relation1482", "",
        "def Preserves (R : Fin 8 → Fin 8 → Prop) (f : Fin 8 → Fin 8 → Fin 8) : Prop :=",
        "  ∀ a b c d, R a b → R c d → R (f a c) (f b d)", "",
        "def relation (i : Fin 8) (x y : Fin 8) : Prop :=",
        "  (![" + relation_text + "] : Fin 8 → Fin 8 → Fin 8 → Bool) i x y = true", "",
        "instance (i x y : Fin 8) : Decidable (relation i x y) := by",
        "  unfold relation", "  infer_instance", "",
        "theorem refute (f : Fin 8 → Fin 8 → Fin 8)",
        "    (h : ∀ x y, f (f y x) (f x (f y y)) = x)",
        "    (hr : ∀ i, Preserves (relation i) f) : False := by",
        "  have split (x y : Fin 8) : f x y = 0 ∨ f x y = 1 ∨ f x y = 2 ∨ f x y = 3 ∨",
        "      f x y = 4 ∨ f x y = 5 ∨ f x y = 6 ∨ f x y = 7 :=",
        "    (by decide : ∀ z : Fin 8, z = 0 ∨ z = 1 ∨ z = 2 ∨ z = 3 ∨",
        "      z = 4 ∨ z = 5 ∨ z = 6 ∨ z = 7) (f x y)",
    ]
    serial = 0

    def fresh():
        nonlocal serial
        serial += 1
        return f"e{serial}"

    def evaluate(term, context, used):
        if isinstance(term, int):
            return term
        a, b = (evaluate(child, context, used) for child in term)
        value, name = context[a, b]
        if name not in used:
            used.append(name)
        return value

    def relation_step(index, context, indent, cell=None, value=None, name=None):
        ri, c1, c2 = CONSTRAINTS[index]
        unknown, used, expressions = [], [], []
        for entry in (c1, c2):
            if entry in context:
                val, hypothesis = context[entry]
                expressions.append(str(val))
                used.append(hypothesis)
            else:
                if entry not in unknown:
                    unknown.append(entry)
                expressions.append("ab"[unknown.index(entry)])
        binders = ("∀ " + " ".join("ab"[j] for j in range(len(unknown))) + " : Fin 8, "
                   if unknown else "")
        arguments = " ".join(f"(f {a} {b})" for a, b in unknown)
        prop = f"relation {ri} {expressions[0]} {expressions[1]}"
        instance = f"hr {ri} {c1[0]} {c2[0]} {c1[1]} {c2[1]} (by decide) (by decide)"
        if cell is None:
            lines.append(indent + f"exact (by decide : {binders}¬ {prop}) {arguments}".rstrip())
        else:
            target = "ab"[unknown.index(cell)]
            lines.append(indent + f"have {name} : f {cell[0]} {cell[1]} = {value} :=")
            lines.append(indent + f"  (by decide : {binders}{prop} → {target} = {value}) {arguments}")
        lines.append(indent + f"  (by simpa only [{', '.join(dict.fromkeys(used))}] using {instance})")

    def emit(node, context, indent):
        for kind, index, cell, value in node["forced"]:
            name = fresh()
            if kind == "law":
                x, y, rhs = RULES[index]
                used = []
                assert evaluate(rhs[0], context, used) == cell[0]
                assert evaluate(rhs[1], context, used) == cell[1]
                lines.append(indent + f"have {name} : f {cell[0]} {cell[1]} = {value} := "
                             f"by simpa only [{', '.join(used)}] using h {x} {y}")
            else:
                relation_step(index, context, indent, cell, value, name)
            context[cell] = (value, name)
        if "fail_law" in node:
            x, y, rhs = RULES[node["fail_law"]]
            used = []
            value = evaluate(rhs, context, used)
            lines.append(indent + f"exact (by decide : ({value} : Fin 8) ≠ {x}) "
                         f"(by simpa only [{', '.join(used)}] using h {x} {y})")
            return
        if "fail_rel" in node:
            relation_step(node["fail_rel"], context, indent)
            return
        i, j = node["split"]
        name = fresh()
        lines.append(indent + f"rcases split {i} {j} with " + " | ".join([name] * 8))
        for value, branch in enumerate(node["branches"]):
            start = len(lines)
            child = context.copy()
            child[i, j] = (value, name)
            emit(branch, child, indent + "  ")
            lines[start] = indent + "· " + lines[start].lstrip()

    emit(tree, {}, "  ")
    lines += ["", "end Definability.Relation1482", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args()
    equations = load_equations()
    assert equations[1481] == ("x", (("y", "x"), ("x", ("y", "y"))))
    assert satisfies(*equations[1479], sum(SOURCE, ()), 8)
    for relation in RELATIONS:
        assert all((SOURCE[a][c], SOURCE[b][d]) in relation
                   for (a, b), (c, d) in product(relation, repeat=2))
    tree = search()
    proof = render(tree)
    if args.write:
        OUTPUT.write_text(proof)
    elif args.check and OUTPUT.read_text() != proof:
        raise SystemExit(f"Stale generated proof: {OUTPUT.relative_to(ROOT)}")

    def stats(node):
        children = [stats(child) for child in node.get("branches", [])]
        return (1 + sum(c[0] for c in children),
                int(bool(children)) + sum(c[1] for c in children),
                0 if not children else 1 + max(c[2] for c in children))

    nodes, splits, depth = stats(tree)
    print(f"Source and all eight compatible relations checked; complete refutation: "
          f"{nodes} nodes, {splits} splits, maximum split depth {depth}.")
    print("Lean must check the generated proof before this counts as a theorem.")


if __name__ == "__main__":
    main()
