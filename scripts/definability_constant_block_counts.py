#!/usr/bin/env python3
"""Reproduce the second pointed-block counting round and its Lean catalogue.

The saved gaps are verified independently in Lean. Python enumeration selects
and checks the arithmetic data but is not a proof oracle.
"""
import argparse
import json
from pathlib import Path

import numpy as np

from definability_counting_upgrades_check import model_indices
from definability_pointed_identity_counts import counts, local_tables
from spectrum_generate import load_equations, variables

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/definability_constant_block_counts.json'


def constant_counts(equations, group, sources, targets):
    params, tables = local_tables(group)
    n = tables.shape[1] - 1
    row = np.arange(len(params))
    cache = {}

    def evaluate(t):
        if t not in cache:
            cache[t] = (np.zeros(len(params), dtype=int) if isinstance(t, str)
                        else tables[row, evaluate(t[0]), evaluate(t[1])])
        return cache[t]

    lower = {}
    for a in sources:
        l, r = equations[a - 1]
        assert variables(l) == {'x'} and variables(r) == {'y'}
        lower[a] = int(((evaluate(l) == n) & (evaluate(r) == n)).sum())
    upper = {b: len(model_indices(equations, tables, b)) for b in targets}
    return lower, upper


def emit(equations, entries):
    out = ROOT / 'equational_theories/Definability'
    groups = sorted({(x['kind'], x['group']) for x in entries})
    catalogue = []
    for kind, group in groups:
        base = 'ConstantTermBlock' if kind == 'constant' else 'PointedIdentity'
        catalogue.append(f'import equational_theories.Definability.{base}Counts{group}')
    catalogue += ['', '/-! Unrestricted FO-structural negatives from constant unary terms and',
                  'five-point local groups. The amplification to arbitrarily many blocks',
                  'uses compactness; these are not finite FO-structural counterexamples. -/',
                  '', 'open Law Law.MagmaLaw', '',
                  'local instance : Fact (1 < 4) := ⟨by decide⟩',
                  'local instance : Fact (1 < 5) := ⟨by decide⟩', '']
    target_names = {}

    def term(t):
        return '(.Leaf 0)' if isinstance(t, str) else f'(.Fork {term(t[0])} {term(t[1])})'

    for kind, group in groups:
        selected = [x for x in entries if (x['kind'], x['group']) == (kind, group)]
        sources = {x['source']: x['source_count'] for x in selected}
        targets = {x['target']: x['target_count'] for x in selected}
        base = 'ConstantTermBlock' if kind == 'constant' else 'PointedIdentity'
        namespace = ('ConstantTermBlockCounting' if kind == 'constant' else 'PointedIdentityCounting')
        imports = [f'import equational_theories.Definability.{namespace}']
        if group == 'C5':
            imports += ['import equational_theories.Definability.LocalCountNormalization']
        previous = out / f'PointedIdentityCounts{group}.lean'
        old = previous.read_text() if kind == 'constant' and previous.exists() else ''
        if old:
            imports += [f'import equational_theories.Definability.PointedIdentityCounts{group}']
        lines = imports + ['', '/-! Generated by `scripts/definability_constant_block_counts.py`.',
                            'C2 arithmetic uses kernel evaluation; larger groups use native_decide. -/',
                            'set_option maxRecDepth 100000', 'set_option maxHeartbeats 40000000',
                            '', 'open Law Law.MagmaLaw', f'namespace {namespace}.{group}', '']
        if group == 'C5':
            lines += ['set_option linter.unusedSimpArgs false', '']
        if group in ['C4', 'C5']:
            lines += [f'local instance : Fact (1 < {group[1:]}) := ⟨by decide⟩', '']
        h = f'Multiplicative (ZMod {group[1:]})' if group.startswith('C') else 'Multiplicative (ZMod 2 × ZMod 2)'
        lines += [f'abbrev H := {h}', '']
        tactic = 'decide +kernel' if group == 'C2' else 'native_decide'
        for a, count in sorted(sources.items()):
            l, r = equations[a - 1]
            if kind == 'constant':
                lines += [f'abbrev left{a} : FreeMagma ℕ := {term(l)}',
                          f'abbrev right{a} : FreeMagma ℕ := {term(r)}',
                          f'theorem source{a} : sourceCount (H := H) left{a} right{a} = {count} := by {tactic}', '']
            else:
                lines += [f'abbrev term{a} : FreeMagma ℕ := {term(r[1])}',
                          f'theorem source{a} : sourceCount (H := H) term{a} = {count} := by {tactic}', '']
        for b, count in sorted(targets.items()):
            if f'theorem target{b} :' in old:
                target_names[kind, group, b] = f'PointedIdentityCounting.{group}.target{b}'
            else:
                proof = " " + tactic
                if group == 'C5':
                    proof = (f'\n  rw [LocalCountNormalization.targetCount_eq]\n'
                             f'  simp only [LocalCountNormalization.Normalized, LocalCountNormalization.Test, '
                             f'Law{b}, satisfiesPhi, FreeMagma.evalInMagma, if_true, if_false, '
                             'Nat.zero_ne_one, Nat.one_ne_zero, forall_const]\n  native_decide')
                lines += [f'theorem target{b} : PointedIdentityCounting.targetCount (H := H) Law{b} = {count} := by{proof}', '']
                target_names[kind, group, b] = f'{namespace}.{group}.target{b}'
        lines += [f'end {namespace}.{group}', '']
        (out / f'{base}Counts{group}.lean').write_text('\n'.join(lines))
    for x in entries:
        a, b, group, kind = x['source'], x['target'], x['group'], x['kind']
        namespace = 'ConstantTermBlockCounting' if kind == 'constant' else 'PointedIdentityCounting'
        ns = f'{namespace}.{group}'
        suffix = 'constantBlocks' if kind == 'constant' else 'pointedIdentity'
        name = f'Equation{b}_not_StructuralFrom_Equation{a}_{suffix}{group}'
        terms = f'(s := {ns}.left{a}) (t := {ns}.right{a})' if kind == 'constant' else f'(t := {ns}.term{a})'
        target = target_names[kind, group, b]
        catalogue += [f'theorem {name} :', f'    ¬ Law{b}.StructuralFrom Law{a} :=',
                      f'  {namespace}.not_structural (H := {ns}.H) {terms}',
                      f'    (by rw [{target}]; decide)',
                      f'    (by rw [{target}, {ns}.source{a}]; decide)', '']
        if group == 'C2':
            catalogue += [f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
                          '#guard_msgs (whitespace := lax) in', f'#print axioms {name}', '']
    (out / 'BlockCountingRoundTwoCatalogue.lean').write_text('\n'.join(catalogue))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit-lean', action='store_true')
    args = parser.parse_args()
    equations = load_equations()
    entries = json.loads(DATA.read_text())['certificates']
    if args.emit_lean:
        emit(equations, entries)
        return
    for kind, group in sorted({(x['kind'], x['group']) for x in entries}):
        selected = [x for x in entries if (x['kind'], x['group']) == (kind, group)]
        sources = sorted({x['source'] for x in selected})
        targets = sorted({x['target'] for x in selected})
        assert all((variables(equations[b-1][0]) | variables(equations[b-1][1])) <= {'x', 'y', 'z'} for b in targets)
        lower, upper = (constant_counts if kind == 'constant' else counts)(equations, group, sources, targets)
        for x in selected:
            assert lower[x['source']] == x['source_count'], x
            assert upper[x['target']] == x['target_count'], x
            assert 0 < x['target_count'] < x['source_count'], x
        print(f'{kind}/{group}: verified {len(selected)} gaps')


if __name__ == '__main__':
    main()
