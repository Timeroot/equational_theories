#include <array>
#include <vector>
#include <set>
#include <algorithm>
#include <iostream>
using P=std::array<int,10>;
P mul(const P&a,const P&b){P c;for(int x=0;x<10;x++)c[x]=a[b[x]];return c;}
P inv(const P&a){P c;for(int x=0;x<10;x++)c[a[x]]=x;return c;}
int main(){
 P id,b;for(int i=0;i<10;i++){id[i]=i;b[i]=5*(i/5)+(i+1)%5;}
 std::vector<P> normals;
 for(int k=2;k<=4;k++){P a;for(int x=0;x<10;x++)a[x]=5*(x/5)+(x+k)%5;normals.push_back(a);}
 for(int k=0;k<5;k++){P a;for(int x=0;x<10;x++)a[x]=x<5?5+x:(x-5+k)%5;normals.push_back(a);}
 P a;for(int x=0;x<10;x++)a[x]=(x<5?5:0)+(10-x)%5;normals.push_back(a);
 std::set<P> expected;
 // All relabelings preserving b, obtained by independently rotating its
 // cycles and optionally swapping them. No assumed classification theorem.
 for(int r=0;r<5;r++)for(int s=0;s<5;s++)for(int swap=0;swap<2;swap++){
  P t;for(int x=0;x<10;x++)t[x]=5*((x/5)^swap)+(x+(x<5?r:s))%5;
  for(P a:normals)expected.insert(mul(mul(t,a),inv(t)));
 }
 int count=0,checked=0; a=id;
 do{
  checked++;
  bool bad=false;for(int x=0;x<10;x++)if(a[x]==x||a[x]==b[x]){bad=true;break;}
  if(bad)continue;
  // Enumerate the monoid generated by a,b; on finite permutations it is
  // the generated group. A free action has at most ten elements, and
  // agreement at zero forces equality of the permutations.
  std::array<bool,10> seen{};std::array<P,10> value{};
  std::vector<P> group{id}; seen[0]=true;value[0]=id;
  for(unsigned i=0;i<group.size()&&!bad;i++)for(const P &g:{a,b}){
   P t=mul(g,group[i]);int j=t[0];
   if(seen[j]){if(t!=value[j]){bad=true;break;}}
   else{
    for(int x=0;x<10;x++)if(t[x]==x){bad=true;break;}
    if(bad)break;
    seen[j]=true;value[j]=t;group.push_back(t);
   }
  }
  if(!bad){count++;if(!expected.erase(a)){std::cerr<<"Unexpected permutation\n";return 1;}}
 }while(std::next_permutation(a.begin(),a.end()));
 std::cout<<checked<<" permutations examined; "<<count<<" free generating pairs; "
  <<expected.size()<<" expected pairs unaccounted for; "<<normals.size()<<" normal forms.\n";
 return expected.empty()?0:1;
}
