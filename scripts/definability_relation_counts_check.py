#!/usr/bin/env python3
"""Recount operations preserving small relations and reproduce Lean certificates."""
import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from definability_matrix_counts_check import table_counts
from spectrum_generate import load_equations

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_relation_counts.json"
GENERATED = ROOT / "equational_theories/Definability/Generated"


def relation_tables(code, tables=None):
    relation = np.array([(code >> i) & 1 for i in range(9)], dtype=bool).reshape(3, 3)
    if tables is None:
        tables = np.array(
            list(itertools.product(range(3), repeat=9)), dtype=np.uint8
        ).reshape(-1, 3, 3)
    edges = np.argwhere(relation)
    for x, y in edges:
        for z, w in edges:
            tables = tables[relation[tables[:, x, z], tables[:, y, w]]]
    return tables


def render(entries):
    lines = [
        "import equational_theories.Definability.RelationCounting",
        "",
        "/-! Generated by scripts/definability_relation_counts_check.py. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    if any("relation_codes" in e for e in entries):
        lines.insert(
            0, "import equational_theories.Definability.RelationFamilyCounting"
        )
    for e in entries:
        s, t, code = e["source"], e["target"], e.get("relation_code")
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_relationCount"
        lines += [
            f"/-- {e['source_count']} compatible source operations, but only {e['target_count']} targets. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
        ]
        if code is not None:
            ns, explicit = "RelationCounting", "(Fin 3) R"
            lines += [
                f"  let R : Fin 3 → Fin 3 → Prop := fun x y => Nat.testBit {code} (3 * x.val + y.val) = true"
            ]
        else:
            size = len(e["relation_codes"])
            ns, explicit = "RelationFamilyCounting", f"(Fin 3) (Fin {size}) R"
            codes = ", ".join(map(str, e["relation_codes"]))
            lines += [
                f"  let codes : Fin {size} → Nat := ![{codes}]",
                f"  let R : Fin {size} → Fin 3 → Fin 3 → Prop := fun i x y => Nat.testBit (codes i) (3 * x.val + y.val) = true",
            ]
        lines += [
            f"  apply not_termStructuralFromFin_of_cloneFamily_count (@{ns}.op {explicit})",
            f"    ({ns}.op_injective R) ({ns}.fst R) ({ns}.snd R)",
            f"    {ns}.comp ({ns}.op_fst R) ({ns}.op_snd R) {ns}.op_comp",
            f"    (fun p : {ns}.P R => @Equation{s} (Fin 3) ⟨{ns}.op p⟩)",
            f"    (fun p : {ns}.P R => @Equation{t} (Fin 3) ⟨{ns}.op p⟩)",
            "  · intro p hp",
            f"    exact (@Law{s}.models_iff (Fin 3) ⟨{ns}.op p⟩).mpr hp",
            "  · intro p hp",
            f"    exact (@Law{t}.models_iff (Fin 3) ⟨{ns}.op p⟩).mp hp",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    entries = data["candidates"]
    equations = load_equations()

    def codes(e):
        return tuple(e.get("relation_codes", [e.get("relation_code")]))

    for family in sorted({codes(e) for e in entries}):
        batch = [e for e in entries if codes(e) == family]
        tables = None
        for code in family:
            tables = relation_tables(code, tables)
        ids = sorted({e[k] for e in batch for k in ("source", "target")})
        counts = table_counts(equations, ids, tables)
        for e in batch:
            if "edges" in e:
                code = e["relation_code"]
                assert e["edges"] == [
                    [x, y]
                    for x in range(3)
                    for y in range(3)
                    if code & (1 << (3 * x + y))
                ]
            assert e["family_count"] == len(tables)
            assert counts[e["source"]] == e["source_count"]
            assert counts[e["target"]] == e["target_count"]
            assert e["source_count"] > e["target_count"]
        print(
            f"Checked relations {family}: {len(tables):,} compatible tables, {len(batch)} inequalities."
        )
    selected = data["selected_indices"]
    assert len(set(selected)) == len(selected)
    assert sorted(i for part in data["parts"] for i in part) == sorted(selected)
    assert set().union(*(set(c) for _, c in data["coverage"])) == set(
        range(len(entries))
    )
    for part, indices in enumerate(data["parts"]):
        path = GENERATED / f"RelationCount{part}.lean"
        text = render([entries[i] for i in indices])
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f"regenerate {path} with --write"
    print(
        f"Reproduced {len(selected)} certificates covering {len(entries)} candidate cells."
    )


if __name__ == "__main__":
    main()
