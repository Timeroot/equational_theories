#!/usr/bin/env python3
"""Bounded exploration of E1485 -> E1483 on the twisted Boolean model of order 32.

These Python checks are not Lean proofs and do not change the definability board.
Term enumeration is exhaustive only through the requested leaf bound.
"""

import argparse
from collections import Counter
from importlib import import_module
from itertools import combinations_with_replacement

import numpy as np


def holds_1483(table):
    x, y, z = np.indices((len(table),) * 3)
    return np.array_equal(table[table[y, x], table[x, table[y, z]]], x)


def generated_subalgebra(table, seeds):
    members = set(seeds)
    while True:
        enlarged = members | {int(table[x, y]) for x in members for y in members}
        if enlarged == members:
            return tuple(sorted(members))
        members = enlarged


def binary_clone(table):
    """Complete closure, used only on the two- and four-element submagmas."""
    n = len(table)
    x = np.broadcast_to(np.arange(n, dtype=np.uint8)[:, None], (n, n))
    operations = [x.copy(), x.T.copy()]
    seen = {op.tobytes() for op in operations}
    position = 0
    while position < len(operations):
        a = operations[position]
        for b in operations[:position + 1]:
            for op in (table[a, b], table[b, a]):
                if op.tobytes() not in seen:
                    seen.add(op.tobytes())
                    operations.append(op)
        position += 1
    return operations


def search_terms(table, max_leaves):
    n = len(table)
    x = np.broadcast_to(np.arange(n, dtype=np.uint8)[:, None], (n, n))
    operations = [x.copy(), x.T.copy()]
    terms = ['x', 'y']
    seen = {op.tobytes() for op in operations}
    by_size = {1: [0, 1]}
    # A failing sample is an actual counterexample; every survivor is checked
    # on all triples. This filter never promotes a sample-only candidate.
    sample = np.random.default_rng(1485).integers(0, n, size=(64, 3))
    sx, sy, sz = sample.T
    hits = []

    def render(i):
        term = terms[i]
        return term if isinstance(term, str) else f'({render(term[0])} * {render(term[1])})'

    assert not any(holds_1483(op) for op in operations)
    for size in range(2, max_leaves + 1):
        level = []
        for left_size in range(1, size):
            for a in by_size[left_size]:
                for b in by_size[size - left_size]:
                    op = table[operations[a], operations[b]]
                    key = op.tobytes()
                    if key in seen:
                        continue
                    seen.add(key)
                    index = len(operations)
                    level.append(index)
                    operations.append(op)
                    terms.append((a, b))
                    if (np.array_equal(op[op[sy, sx], op[sx, op[sy, sz]]], sx)
                            and holds_1483(op)):
                        hits.append(render(index))
        by_size[size] = level
        print(f'{size} leaves: {len(level)} new operations, {len(operations)} total')
    print(f'E1483 terms within the bound: {hits}')
    print('An empty list is not a term-definability refutation.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--max-leaves', type=int, choices=range(1, 9), default=8)
    args = parser.parse_args()
    table = np.array(import_module('1485_structure_check').twisted32(), dtype=np.uint8)
    n = len(table)
    x, y, z = np.indices((n,) * 3)
    assert np.array_equal(table[table[y, x], table[x, table[z, y]]], x)
    assert not holds_1483(table)
    rotation = np.array([((a << 1) & 31) | (a >> 4) for a in range(n)])
    assert np.array_equal(table[np.ix_(rotation, rotation)], rotation[table])
    idempotents = [a for a in range(n) if table[a, a] == a]
    print(f'Checked E1485 and its rotation automorphism; idempotents: {idempotents}')
    subs = sorted({generated_subalgebra(table, pair)
                   for pair in combinations_with_replacement(range(n), 2)},
                  key=lambda sub: (len(sub), sub))
    print(f'Subalgebras generated by at most two elements, by size: {dict(Counter(map(len, subs)))}')
    for sub in subs:
        if len(sub) not in (2, 4):
            continue
        positions = {a: i for i, a in enumerate(sub)}
        small = np.array([[positions[int(table[a, b])] for b in sub] for a in sub], dtype=np.uint8)
        clone = binary_clone(small)
        targets = [op for op in clone if holds_1483(op)]
        assert len(clone) == 16 and len(targets) == 2
        if len(sub) == 4:
            assert {op.tobytes() for op in targets} == {small.tobytes(), small.T.tobytes()}
        print(f'{sub}: {len(clone)} binary term operations, {len(targets)} satisfy E1483')
    search_terms(table, args.max_leaves)


if __name__ == '__main__':
    main()
