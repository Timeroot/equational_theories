#!/usr/bin/env python3
"""Reproduce five normalized order-ten refutations for E1486.

Without --solve, verify the saved formula/certificate hashes and regenerate
Lean wrappers. The solver and compact-data packer are untrusted; Lean proves
the reduction and checks each reconstructed LRAT refutation.
"""
import argparse
import concurrent.futures
import json
import lzma
from itertools import combinations, product
from pathlib import Path
import subprocess
import time

from spectrum_63_ten_certificate import ROOT, TRIM, sha

DATA = ROOT / "data/spectrum/1486_order10.json"
DEST = ROOT / "equational_theories/Spectrum/Equation1486/OrderTen/Certificates"
CASES = {
    "RankTwoInside": ("small true", 2, True, False),
    "RankTwoOutside": ("small false", 2, False, False),
    "NoIdemInside": ("noIdem true", 3, True, True),
    "NoIdemOutside": ("noIdem false", 3, False, True),
    "Idempotent": ("idem", 3, True, False),
}


def clauses(case):
    _, k, inside, nonidem = CASES[case]
    r = range(10)
    p = lambda x, y, z: 1 + (x * 10 + y) * 10 + z
    sq = lambda s: 1001 + s
    col = lambda x, a: 1011 + x * 10 + a
    row = lambda x, b: 1111 + x * 10 + b
    cs = []
    for x, y in product(r, repeat=2):
        vs = [p(x, y, z) for z in r]
        cs.append(vs)
        cs.extend([-a, -b] for a, b in combinations(vs, 2))
    for z, s in product(r, repeat=2):
        cs.append([-p(z, z, s), sq(s)])
    for s in r:
        cs.append([-sq(s)] + [p(z, z, s) for z in r])
    for x, s, b in product(r, repeat=3):
        cs.append([-sq(s), -p(x, s, b), row(x, b)])
    for x, y, a in product(r, repeat=3):
        cs.append([-p(y, x, a), col(x, a)])
    for x, a, b in product(r, repeat=3):
        cs.append([-row(x, b), -col(x, a), p(a, b, x)])
    for x, a, b, u in product(r, repeat=4):
        if a < b:
            cs.append([-row(x, a), -row(x, b), -row(a, u), -row(b, u)])
    for x, a in product(r, repeat=2):
        cs.append([row(x, b) for b in r if b != a])
    for x, y, u in product(r, repeat=3):
        cs.append([-row(x, y), -row(y, u), p(x, u, y)])
    for s, t in product(r, repeat=2):
        cs.append([-sq(s), -p(s, s, t), p(t, t, s)])

    def normalize(x, allowed):
        cs.extend([row(x, b) if b in allowed else -row(x, b)] for b in r)

    normalize(0, set(range(k)) if inside else set(range(1, k + 1)))
    if k == 3:
        for x in r:
            for a, b in combinations(r, 2):
                cs.append([row(x, c) for c in r if c not in (a, b)])
    if nonidem:
        cs.append([sq(0)])
        cs.extend([-p(x, x, x)] for x in r)
        cs.extend([[p(0, 0, 1)], [p(1, 1, 0)]])
    if case == "Idempotent":
        cs.append([p(0, 0, 0)])
        normalize(1, {3, 4, 5})
        normalize(2, {6, 7, 8})
    return [c for c in cs if not any(-v in c for v in c)]


def cnf_bytes(case):
    cs = clauses(case)
    return (
        f"p cnf 1210 {len(cs)}\n" + "".join(" ".join(map(str, c)) + " 0\n" for c in cs)
    ).encode()


def render(rec):
    case = rec["case"]
    module = rec.get("lean_module", case)
    return f"""import equational_theories.Spectrum.Equation1486.OrderTen.Encoding
import SpectrumCertificateData
import equational_theories.Spectrum.Status

/- Generated by scripts/spectrum_1486_ten.py.
CNF SHA-256: {rec['cnf_sha256']}
Compact payload SHA-256: {rec['proof_sha256']} -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1486.OrderTen.Certificates.{module}
open Std.Sat Std.Tactic.BVDecide LRAT

private def proof : Array IntAction :=
  Spectrum.CertificateData.CompactRup.reconstruct
    (include_binary_xz "../../../../../{rec['certificate']}")
    (Encoding.toNat (Encoding.{CASES[case][0]}))

@[spectrum_native]
theorem checked : check proof (Encoding.toNat (Encoding.{CASES[case][0]})) = true := by
  native_decide

theorem unsat : (Encoding.toNat (Encoding.{CASES[case][0]})).Unsat :=
  check_sound proof _ checked
end Spectrum.E1486.OrderTen.Certificates.{module}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--solve", action="store_true")
    ap.add_argument("--seconds", type=int, default=600)
    args = ap.parse_args()
    if args.seconds <= 0:
        ap.error("--seconds must be positive")
    DEST.mkdir(parents=True, exist_ok=True)
    if args.solve:
        work = ROOT / ".cache/1486-order10"
        work.mkdir(parents=True, exist_ok=True)
        trim = work / "TrimBinary.lean"
        trim.write_text(TRIM.replace("trimmed false", "trimmed true"))
        packer = work / "compact-rup"
        subprocess.run(
            [
                "g++",
                "-O3",
                "-std=c++17",
                str(ROOT / "scripts/spectrum_compact_rup.cpp"),
                "-o",
                str(packer),
            ],
            check=True,
        )

        def solve(case):
            module = "RankTwoOutsideSmall" if case == "RankTwoOutside" else case
            stem = work / case
            cnf = cnf_bytes(case)
            stem.with_suffix(".cnf").write_bytes(cnf)
            start = time.monotonic()
            with stem.with_suffix(".log").open("w") as log:
                out = subprocess.run(
                    [
                        "cadical",
                        *([] if case == "RankTwoOutside" else ["--shrink=0"]),
                        "--lrat",
                        "--no-binary",
                        "-t",
                        str(args.seconds),
                        str(stem.with_suffix(".cnf")),
                        str(stem.with_suffix(".lrat")),
                    ],
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    timeout=args.seconds + 15,
                )
            if out.returncode != 20:
                raise RuntimeError(
                    f"{case}: no refutation; return code {out.returncode}"
                )
            elapsed = time.monotonic() - start
            subprocess.run(
                [
                    "lake",
                    "env",
                    "lean",
                    "--run",
                    str(trim),
                    str(stem.with_suffix(".lrat")),
                ],
                cwd=ROOT,
                check=True,
            )
            with Path(str(stem.with_suffix(".lrat")) + ".trimmed").open("rb") as inp:
                subprocess.run(
                    [str(packer), "--input-mask", str(stem.with_suffix(".rup"))],
                    stdin=inp,
                    check=True,
                )
            payload = stem.with_suffix(".rup").read_bytes()
            zipped = lzma.compress(payload, preset=6)
            dest = ROOT / f"data/spectrum/order_ten_rup/e1486_{module}.rup.xz"
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(zipped)
            print(
                f"{case}: {elapsed:.3f}s; {len(zipped):,} compressed bytes", flush=True
            )
            return dict(
                case=case,
                lean_module=module,
                variables=1210,
                clauses=len(clauses(case)),
                cnf_sha256=sha(cnf),
                proof_sha256=sha(payload),
                compressed_sha256=sha(zipped),
                proof_bytes=len(payload),
                compressed_bytes=len(zipped),
                certificate=str(dest.relative_to(ROOT)),
                search_seconds=round(elapsed, 3),
                format="compact-rup-xz",
            )

        with concurrent.futures.ThreadPoolExecutor(max_workers=2) as ex:
            records = list(ex.map(solve, CASES))
        DATA.write_text(json.dumps(records, indent=2) + "\n")
    else:
        records = json.loads(DATA.read_text())
        assert [r["case"] for r in records] == list(CASES)
        for rec in records:
            zipped = (ROOT / rec["certificate"]).read_bytes()
            assert sha(cnf_bytes(rec["case"])) == rec["cnf_sha256"]
            assert sha(zipped) == rec["compressed_sha256"]
            assert sha(lzma.decompress(zipped)) == rec["proof_sha256"]
    for rec in records:
        (DEST / (rec.get("lean_module", rec["case"]) + ".lean")).write_text(render(rec))
    print(f"Verified {len(records)} E1486 encodings and saved certificate hashes.")


if __name__ == "__main__":
    main()
