#!/usr/bin/env python3
"""Specialize the checked E1483 rank encoding to order seven.

No order-eleven-specific rank-threshold clauses are retained. The generic
source/dual/regularity constraints, rank normalization, and sorted tail suffice.
All resulting mathematical arguments are rechecked by Lean.
"""
import argparse
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'equational_theories/Spectrum/Equation1483'
NS='Spectrum.E1483.OrderSeven'


def render():
    sat=(ROOT/'equational_theories/Definability/Central1483SAT.lean').read_text()
    sat=sat.replace('Magma.Central1483',NS)
    sat=sat.replace('abbrev Atom (n : Nat) := Fin 11', 'abbrev Atom (n : Nat) := Fin ATOMCOUNT')
    sat=sat.replace('Fin.ofNat 11', 'Fin.ofNat ATOMCOUNT')
    sat=re.sub(r'\b11\b','7',sat).replace('ATOMCOUNT','11')
    sat=sat.replace('y.val < 10','y.val < 6')
    sat=sat.replace('f x x = x → 4 ≤ rowSize f x','f x x = x → 3 ≤ rowSize f x')
    sat=sat.replace('  (if k=3 then rankThreeExtras else .empty) ++ sortedRow k ++ thresholdExtras','  sortedRow k')
    a=sat.index('lemma rank_threshold_disjunction')
    b=sat.index('end '+NS+'.CNF',a)
    replacement='''lemma model_rankFormula (f : Fin 7 → Fin 7 → Fin 7) (k : Nat) (zero : Bool)
    (h : RankAssumptions f k zero) : CNF.Sat (meaning f) (rankFormula 7 k zero) := by
  have hc : CNF.Sat (meaning f) (cardUpper (col 0) k) := by
    apply sat_cardUpper _ _ _ (colSet f 0) (meaning_col f 0)
    rw [h.cardEq, h.rankZero]
  simp only [rankFormula, CNF.Sat, CNF.eval_append, Bool.and_eq_true]
  exact ⟨⟨⟨⟨⟨⟨⟨⟨model_formula f h.source h.dual,
    model_exactImages f⟩, model_regularImages f h.leftRegular h.rightRegular⟩,
    model_nonfullImages f k zero h⟩, model_minimumImages f k zero h⟩,
    model_normalizedImage f k zero h⟩, hc⟩, model_firstCell f k zero h⟩,
    model_sortedRow f k zero h⟩

'''
    sat=sat[:a]+replacement+sat[b:]
    norm=(ROOT/'equational_theories/Definability/Central1483Normalization.lean').read_text()
    norm=norm.replace('import equational_theories.Definability.Central1483SAT',
                      'import equational_theories.Spectrum.Equation1483.SevenSAT')
    norm=norm.replace('Magma.Central1483',NS).replace('eleven-element','seven-element')
    norm=re.sub(r'\b(?:11|10)\b',lambda m:{'11':'7','10':'6'}[m[0]],norm)
    norm=norm.replace('4 ≤ rank f a','3 ≤ rank f a').replace('(hk : k ≤ 3)','(hk : k ≤ 2)')
    norm=norm.replace('code11_injective','code7_injective')
    banner='/- Generated by scripts/spectrum_1483_seven.py; all specialized proofs are checked by Lean. -/\n'
    return {'SevenSAT.lean':banner+sat,'SevenNormalization.lean':banner+norm}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');a=p.parse_args()
    for name,text in render().items():
        path=DEST/name
        if a.write:path.write_text(text)
        else:assert path.read_text()==text,f'{path} is stale'

if __name__=='__main__':main()
