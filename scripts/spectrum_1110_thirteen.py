#!/usr/bin/env python3
"""Reproduce/audit E1110 order-thirteen certificates after diagonal conjugacy.

The 101 canonical permutations are certified to cover every cycle type in Lean.
Those with a two-cycle are excluded algebraically. The remaining 45 cases use
compact RUP data and Lean's verified LRAT checker. No restricted search timeout
is an exclusion. Input generation is independent of the Lean CNF definition.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import lzma
from pathlib import Path
import re
import resource
import subprocess
import time
from spectrum_small_orders import clauses
from spectrum_63_ten_certificate import TRIM

ROOT=Path(__file__).resolve().parents[1]
META=ROOT/'data/spectrum/1110_order13.json'
WORK=ROOT/'.cache/e1110-order13-final'
DEST=ROOT/'equational_theories/Spectrum/Equation1110/OrderThirteen/Certificates'
SLACK_CASES={4: 2, 6: 3, 9: 4, 10: 4, 13: 5, 14: 5, 20: 6, 21: 6, 26: 7, 27: 7, 37: 8, 40: 8, 68: 10, 72: 10}

def sha(b): return hashlib.sha256(b).hexdigest()

def representatives():
    text=(ROOT/'equational_theories/Spectrum/Equation1110/CycleRepresentatives.lean').read_text()
    body=text.split('def dataRows13 :',1)[1].split('def data13',1)[0]
    rows=[list(map(int,re.findall(r'\d+',row))) for row in re.findall(r'#\[([\d, ]+)\]',body)]
    assert len(rows)==101 and all(sorted(d)==list(range(13)) for d in rows)
    return rows

def eligible(d): return not any(d[x]!=x and d[d[x]]==x for x in range(13))

def cnf(d):
    n=13
    p=lambda x,y,z:1+(x*n+y)*n+z
    if d == [1,2,0] + list(range(3,n)):
        cs=clauses(1110,n)+[[p(x,x,y)] for x,y in enumerate(d)]+[[p(x,d[x],x)] for x in range(n)]
        return (f'p cnf {2*n**3} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode(),len(cs)
    if (slack := SLACK_CASES.get(representatives().index(d))) is not None:
        old={-p(0,y,z) for y in range(n) for z in range(y+2,n)}
        cs=[c for c in clauses(1110,n) if not(len(c)==1 and c[0] in old)]
        cs += [[p(x,x,y)] for x,y in enumerate(d)] + [[p(x,d[x],x)] for x in range(n)]
        cs += [[-p(0,y,z)] for y in range(n) for z in range(y+slack+1,n)]
        return (f'p cnf {2*n**3} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode(),len(cs)
    if d == list(range(n)):
        cs=clauses(1110,n)+[[p(0,0,0)]]
        return (f'p cnf {2*n**3} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode(),len(cs)
    old={-p(0,y,z) for y in range(n) for z in range(y+2,n)}
    cs=[c for c in clauses(1110,n) if not(len(c)==1 and c[0] in old)]
    cs += [[p(x,x,y)] for x,y in enumerate(d)]
    return (f'p cnf {2*n**3} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode(),len(cs)

def render(r):
    formula = ('OrderThirteen.natFormula 13' if r['index']==0 else
               f'ForwardEncoding.rowChainNat (CycleRepresentatives.data13 {r["index"]})' if r.get('row_chain_forward') else
               f'ForwardEncoding.slackNat (CycleRepresentatives.data13 {r["index"]}) {r["row_slack"]}' if r.get('row_slack') else
               f'SquareEncoding.fixedNat (CycleRepresentatives.data13 {r["index"]})')
    return f'''import equational_theories.Spectrum.Equation1110.{'ForwardEncoding' if r.get('row_chain_forward') or r.get('row_slack') else 'SquareEncoding'}
import equational_theories.Spectrum.Equation1110.OrderThirteenEncoding
import equational_theories.Spectrum.Equation1110.CycleRepresentatives
import equational_theories.Spectrum.Status
import SpectrumCertificateData

/- Generated by scripts/spectrum_1110_thirteen.py.
CNF SHA-256: {r['cnf_sha256']}
Compact payload SHA-256: {r['proof_sha256']} -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1110.OrderThirteen.Certificates.C{r['index']}
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData
private def refutation : Array IntAction := CompactRup.reconstruct
  (include_binary_xz "../../../../../{r['certificate']}")
  ({formula})
@[spectrum_native]
theorem checked : check refutation
    ({formula}) = true := by native_decide
theorem unsat : ({formula}).Unsat :=
  check_sound refutation _ checked
spectrum_assert unsat complete
end Spectrum.E1110.OrderThirteen.Certificates.C{r['index']}
'''

def solve(i,d,seconds):
    data,count=cnf(d);stem=WORK/f'C{i}';stem.with_suffix('.cnf').write_bytes(data)
    proof=stem.with_suffix('.lrat')
    def limits():resource.setrlimit(resource.RLIMIT_FSIZE,(256*1024**2,256*1024**2))
    start=time.monotonic()
    with stem.with_suffix('.log').open('w') as out:
        proc=subprocess.run(['cadical','--lrat','-t',str(seconds),str(stem.with_suffix('.cnf')),str(proof)],stdout=out,stderr=subprocess.STDOUT,timeout=seconds+30,preexec_fn=limits)
    assert proc.returncode==20,(i,proc.returncode)
    elapsed=time.monotonic()-start
    subprocess.run(['lake','env','lean','--run',str(WORK/'TrimBinary.lean'),str(proof)],check=True,cwd=ROOT,stdout=subprocess.DEVNULL)
    compact=stem.with_suffix('.rup')
    with Path(str(proof)+'.trimmed.bin').open('rb') as src:
        subprocess.run([str(WORK/'compact-rup'),'--input-mask',str(compact)],stdin=src,check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    payload=compact.read_bytes();packed=lzma.compress(payload,preset=6)
    assert len(packed)<=32*1024**2,(i,len(packed))
    path=ROOT/('data/spectrum/1110_order13_rup/idempotent.rup.xz' if i == 0 else f'data/spectrum/1110_order13_rup/C{i}.rup.xz');path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(packed)
    r=dict(index=i,diagonal=d,clauses=count,cnf_sha256=sha(data),proof_sha256=sha(payload),compressed_sha256=sha(packed),proof_bytes=len(payload),compressed_bytes=len(packed),search_seconds=round(elapsed,3),certificate=str(path.relative_to(ROOT)))
    if i == 2: r['row_chain_forward']=True
    if i in SLACK_CASES: r['row_slack']=SLACK_CASES[i]
    print(f'C{i}: {len(packed):,} bytes, {elapsed:.2f}s solver',flush=True)
    return r

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--solve',action='store_true');ap.add_argument('--write',action='store_true');ap.add_argument('--seconds',type=int,default=600);ap.add_argument('--export-cnf',type=Path);ap.add_argument('--check-lean-cnf',type=Path);args=ap.parse_args()
    ds=representatives();cases=[(i,d) for i,d in enumerate(ds) if eligible(d)];assert len(cases)==45
    if args.solve:
        WORK.mkdir(parents=True,exist_ok=True)
        (WORK/'TrimBinary.lean').write_text(TRIM.replace('".trimmed"','".trimmed.bin"').replace('trimmed false','trimmed true'))
        subprocess.run(['g++','-O3','-std=c++17',str(ROOT/'scripts/spectrum_compact_rup.cpp'),'-o',str(WORK/'compact-rup')],check=True)
        with ThreadPoolExecutor(max_workers=4) as pool:rs=list(pool.map(lambda t:solve(*t,args.seconds),cases))
        META.write_text(json.dumps(dict(law=1110,order=13,cases=rs),indent=2)+'\n')
    rs=json.loads(META.read_text())['cases'];assert [r['index'] for r in rs]==[i for i,d in cases]
    for r in rs:
        i=r['index'];assert r['diagonal']==ds[i];data,count=cnf(ds[i]);assert sha(data)==r['cnf_sha256'] and count==r['clauses']
        packed=(ROOT/r['certificate']).read_bytes();payload=lzma.decompress(packed)
        assert sha(packed)==r['compressed_sha256'] and len(packed)==r['compressed_bytes']
        assert sha(payload)==r['proof_sha256'] and len(payload)==r['proof_bytes']
        if args.export_cnf:
            args.export_cnf.mkdir(parents=True,exist_ok=True);(args.export_cnf/f'C{i}.cnf').write_bytes(data)
        if args.check_lean_cnf:assert (args.check_lean_cnf/f'C{i}.cnf').read_bytes()==data
        if i == 0: continue  # The idempotent branch has a hand-written public wrapper.
        path=DEST/f'C{i}.lean'
        if args.write or args.solve:DEST.mkdir(parents=True,exist_ok=True);path.write_text(render(r))
        else:assert path.read_text()==render(r)
    print(f'Checked {len(rs)} cases, {sum(r["compressed_bytes"] for r in rs):,} bytes.')
if __name__=='__main__':main()
