#!/usr/bin/env python3
"""Render the positive quartic-tail certificate as ordinary Lean proofs."""
import argparse
import json
from pathlib import Path
from spectrum_quartic_tail import OUTPUT, ROOT, check, factors

OUT = ROOT / 'equational_theories/Spectrum/QuarticTail'
CHECK = False
HEADER = '''/-! Generated by scripts/spectrum_quartic_tail_lean.py.
All finite checks use the Lean kernel, and all model entries use proved
algebraic or design constructions. No model-search refutations are used. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
'''


def tree(xs, render=str):
    if len(xs) == 1:
        return f'(.leaf {render(xs[0])})'
    m = len(xs)//2
    return f'(.branch {m} {tree(xs[:m], render)} {tree(xs[m:], render)})'


def proof_tree(xs):
    if len(xs) == 1:
        return f'c{xs[0]} S'
    m = len(xs)//2
    return f'⟨{proof_tree(xs[:m])}, {proof_tree(xs[m:])}⟩'


def design_proof(k, q):
    fs = factors(q)
    leaves = [f'(HasTD.primePower (k := {k}) (p := {p}) (e := {e}) '
              '(by norm_num) (by decide) (by decide))' for p, e in fs]
    out = leaves[0]
    for leaf in leaves[1:]:
        out = f'({out}.mul {leaf})'
    return out


def write(name, content):
    path = OUT / name
    if CHECK:
        if path.read_text() != content+'\n':
            raise SystemExit(f'Stale generated file: {path}')
    else:
        path.write_text(content+'\n')


def generate():
    cert = json.loads(OUTPUT.read_text())
    check(cert)
    models = {int(n): r for n, r in cert['models'].items()}
    nums = sorted(models)
    indices = {n: i for i, n in enumerate(nums)}
    designs = set()
    for n, r in models.items():
        if r[0] in ('one_hole', 'two_holes'):
            designs.add((17 if r[0] == 'one_hole' else 81, r[1]))
    designs.update((81, row[0]) for row in cert['intervals'])
    lines = ['import equational_theories.Spectrum.PBD.Transversal', HEADER,
             'namespace Spectrum.QuarticTail.Generated', 'open PBD']
    for k, q in sorted(designs):
        lines.append(f'theorem td{k}_{q} : HasTD {k} {q} :=\n  {design_proof(k, q)}\n')
    lines.append('end Spectrum.QuarticTail.Generated')
    write('Designs.lean', '\n'.join(lines))

    lines = ['import equational_theories.Spectrum.QuarticTail.Seeds',
             'import equational_theories.Spectrum.QuarticTail.Designs',
             'import equational_theories.Spectrum.PBD.NatTable', HEADER,
             'namespace Spectrum.QuarticTail.Generated', 'open PBD',
             'variable {L : BinaryLaw} (S : Seeds L)', 'include S',
             '''private theorem prod {a b : ℕ}
    (h : Nonempty (Model L (Fin a))) (g : Nonempty (Model L (Fin b))) :
    Nonempty (Model L (Fin (a*b))) := by
  obtain ⟨M⟩ := h
  obtain ⟨N⟩ := g
  exact ⟨M.mul N⟩
''']
    for n, r in sorted(models.items()):
        tag = r[0]
        if tag == 'empty':
            proof = '⟨Model.empty⟩'
        elif tag == 'one':
            proof = '⟨Model.one⟩'
        elif tag == 'scalar':
            proof = f'S.scalar {n} {r[1]} (by decide) (by decide)'
        elif tag == 'quartic':
            proof = f'S.quartic {r[1]}'
        elif tag == 'product':
            proof = f'prod S (c{r[1]} S) (c{r[2]} S)'
        elif tag == 'one_hole':
            q, a, e = r[1:]
            proof = (f'(td17_{q}).oneHole (L := L) (k := 16) (r := {a}) (e := {e}) '
                     f'(by decide) (by decide) (c{q+e} S) (c{a+e} S) (small16 S)')
        else:
            q, a, b, e = r[1:]
            proof = (f'(td81_{q}).twoHoles (L := L) (k := 79) (r := {a}) (s := {b}) (e := {e}) '
                     f'(by decide) (by decide) (by decide) (c{q+e} S) (c{a+e} S) '
                     f'(c{b+e} S) (small79 S)')
        lines.append(f'private theorem c{n} : Nonempty (Model L (Fin {n})) :=\n  {proof}\n')
        if n in (17, 81):
            a, b = (16, 17) if n == 17 else (79, 81)
            proofs = '\n'.join(f'  · exact c{i} S' for i in range(a, b+1))
            lines.append(f'''theorem small{a} (n : ℕ) (hl : {a} ≤ n) (hh : n ≤ {b}) :
    Nonempty (Model L (Fin n)) := by
  interval_cases n
{proofs}
''')
    lines += [f'def orders : NatTable := {tree(nums)}\n',
              f'private theorem models : orders.All (fun n => Nonempty (Model L (Fin n))) :=\n  {proof_tree(nums)}\n',
              '''theorem model (i : ℕ) : Nonempty (Model L (Fin (orders.get i))) :=
  NatTable.all_get (models S) i
\ntheorem model_mem {n : ℕ} (hn : n ∈ orders.values) : Nonempty (Model L (Fin n)) :=
  NatTable.all_mem (models S) hn
''', 'end Spectrum.QuarticTail.Generated']
    write('Basis.lean', '\n'.join(lines))

    small_lines = ['import equational_theories.Spectrum.QuarticTail.Basis', HEADER,
                   'namespace Spectrum.QuarticTail', 'open PBD Law Law.MagmaLaw']
    for law in (1076, 1313):
        small_lines.append(f"""private theorem seed_{law} (i : ℕ) : Law{law}.HasModel (Generated.orders.get i) := by
  obtain ⟨M⟩ := Generated.model seeds{law} i
  exact ⟨⟨M.op⟩, (@Law{law}.models_iff _ ⟨M.op⟩).mpr M.law⟩
""")
        for n in (13, 16, 17, 23, 25, 31, 43, 47, 53, 59, 67, 71, 73, 79, 80, 81):
            small_lines.append(f"theorem small_{law}_{n} : Law{law}.HasModel {n} := seed_{law} {indices[n]}")
            small_lines.append(f"spectrum_assert small_{law}_{n} complete")
    small_lines.append('end Spectrum.QuarticTail')
    write('SmallModels.lean', '\n'.join(small_lines))

    lines = ['import equational_theories.Spectrum.QuarticTail.Basis', HEADER,
             'namespace Spectrum.QuarticTail.Generated', 'open PBD',
             '''def Split (L : BinaryLaw) (B t : ℕ) : Prop :=
  ∃ r s : ℕ, r ≤ B ∧ s ≤ B ∧ Nonempty (Model L (Fin r)) ∧
    Nonempty (Model L (Fin s)) ∧ r+s=t

theorem split_mono {L : BinaryLaw} {B C t : ℕ} (h : B ≤ C) (g : Split L B t) :
    Split L C t := by
  obtain ⟨r,s,hr,hs,M,N,he⟩ := g
  exact ⟨r,s,hr.trans h,hs.trans h,M,N,he⟩
''', 'variable {L : BinaryLaw} (S : Seeds L)', 'include S']
    prev_B, prev_hi = None, None
    chunk_id = 0
    for block in cert['splits']:
        B, lo, hi = block['bound'], block['lo'], block['hi']
        entries = [indices[r]+8192*indices[t-r]
                   for t, r in enumerate(block['left'], lo)]
        cover = None
        if prev_B is not None:
            cover = f'start{B}'
            lines.append(f'''private theorem {cover} : ∀ t, 254 ≤ t → t ≤ {prev_hi} → Split L {B} t :=
  fun t hl hh => split_mono (by decide) (split{prev_B} S t hl hh)
''')
        for off in range(0, len(entries), 128):
            es = entries[off:off+128]
            start, end = lo+off, lo+off+len(es)-1
            j = chunk_id
            chunk_id += 1
            lines += [f'private def data{j} : NatTable := {tree(es)}\n',
                      f'''omit S in
private theorem check{j} : ∀ i : Fin {len(es)},
    let v := data{j}.get i.val
    let a := orders.get (v % 8192)
    let b := orders.get (v / 8192)
    a ≤ {B} ∧ b ≤ {B} ∧ a+b={start}+i.val := by decide +kernel

private theorem chunk{j} (t : ℕ) (hl : {start} ≤ t) (hh : t ≤ {end}) : Split L {B} t := by
  let i : Fin {len(es)} := ⟨t-{start},by omega⟩
  let v := data{j}.get i.val
  have h := check{j} i
  refine ⟨orders.get (v % 8192), orders.get (v / 8192), h.1, h.2.1,
    model S _, model S _, ?_⟩
  exact h.2.2.trans (by dsimp [i]; omega)
''']
            if cover is None:
                cover = f'chunk{j}'
            else:
                name = f'joined{j}'
                lines.append(f'''private theorem {name} : ∀ t, 254 ≤ t → t ≤ {end} → Split L {B} t :=
  interval_extend ({cover} S) (chunk{j} S) (by decide)
''')
                cover = name
        lines.append(f'''theorem split{B} : ∀ t, 254 ≤ t → t ≤ {hi} → Split L {B} t := {cover} S
''')
        prev_B, prev_hi = B, hi
    lines.append('end Spectrum.QuarticTail.Generated')
    write('Splits.lean', '\n'.join(lines))

    lines = ['import equational_theories.Spectrum.QuarticTail.Splits', HEADER,
             'namespace Spectrum.QuarticTail.Generated', 'open PBD',
             'variable {L : BinaryLaw} (S : Seeds L)', 'include S']
    end = None
    for j, (q, B, lo, hi) in enumerate(cert['intervals']):
        t_hi = hi-79*q
        lines.append(f'''private theorem interval{j} (n : ℕ) (hl : {lo} ≤ n) (hh : n ≤ {hi}) :
    Nonempty (Model L (Fin n)) := by
  obtain ⟨r,s,hr,hs,M,N,he⟩ := split{B} S (n-79*{q}) (by omega) (by omega)
  have H := (td81_{q}).twoHoles (L := L) (k := 79) (r := r) (s := s) (e := 0)
    (by decide) (by omega) (by omega) (model S {indices[q]}) M N (small79 S)
  have hn : 79*{q}+r+s+0=n := by omega
  rw [hn] at H
  exact H
''')
        if j == 0:
            cover = 'interval0'
        else:
            name = f'covered{j}'
            lines.append(f'''private theorem {name} : ∀ n, {cert['cutoff']} ≤ n → n ≤ {hi} →
    Nonempty (Model L (Fin n)) :=
  interval_extend ({cover} S) (interval{j} S) (by decide)
''')
            cover = name
        end = hi
    lines.append(f'''theorem base (n : ℕ) (hl : {cert['cutoff']} ≤ n) (hh : n ≤ {cert['base_end']}) :
    Nonempty (Model L (Fin n)) := {cover} S n hl (by omega)

end Spectrum.QuarticTail.Generated''')
    write('Coverage.lean', '\n'.join(lines))
    print(f'Generated {len(designs)} designs, {len(nums)} model proofs, '
          f'{chunk_id} split checks, {len(cert["intervals"])} interval proofs.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated Lean files are current')
    CHECK = parser.parse_args().check
    generate()
