#!/usr/bin/env python3
"""Generate improved E667/E883 bounds from extended transversal designs."""
import argparse
from math import isqrt
from pathlib import Path
from spectrum_667_883_field_bounds import constructions, prime
from spectrum_63_idempotent_bounds import ORDINARY_EXCEPTIONS, CUTOFF
from spectrum_667_883_bounds import positive_recipes
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'equational_theories/Spectrum'

def extended_constructions():
    old,designs,basis=constructions()
    known={n:('existing',n) for n in basis}
    strength={}
    for q in range(2,CUTOFF):
        p=next((p for p in range(2,isqrt(q)+1) if q%p==0),q)
        power=q
        while power%p==0:power//=p
        strength[q]=q if power==1 else p
        if power!=1:
            for a in range(2,isqrt(q)+1):
                if q%a==0:strength[q]=max(strength[q],min(strength[a],strength[q//a]))
        if q==36:strength[q]=max(strength[q],7)
    for q in [40,50,76]:strength[q]=max(strength[q],7)
    strength[100]=max(strength[100],7)
    strength[160]=max(strength[160],7)
    for n in range(2,CUTOFF):
        if n in known:continue
        if (n-1)%26==0:
            m=(n-1)//26
            if 2*m+1 in known and m not in ORDINARY_EXCEPTIONS:
                known[n]=('frame13',m)
                continue
        for a in range(2,isqrt(n)+1):
            if n%a==0 and a in known and n//a in known:
                known[n]=('product',a,n//a);break
        if n in known:continue
        for a in range(2,isqrt(n-1)+1):
            if (n-1)%a==0:
                for k in [a,(n-1)//a]:
                    q=(n-1)//k+1
                    if k in known and q in known and q-1 not in ORDINARY_EXCEPTIONS:
                        known[n]=('singular',k,q);break
            if n in known:break
        if n in known:continue
        for h in (0,1):
            for k in range(2,isqrt(n)+2):
                if k not in known or k+1 not in known:continue
                for q in range((n-h+k)//(k+1),(n-h)//k+1):
                    r=n-h-k*q
                    if q<2 or not 0<=r<=q:continue
                    if strength[q]<k or q+h not in known or r+h not in known:continue
                    known[n]=('td',k,q,r,h);break
                if n in known:break
            if n in known:break
    return old,designs,basis,known

def generate():
    old,designs,basis,known=extended_constructions()
    new=sorted(known.keys()-basis.keys())
    def ref(n):
        if n in old:return f'(IdempotentFiniteBasis.model_of_bit (n := {n}) (by decide))'
        if n in basis:return f'(FieldBounds.extra_model (n := {n}) (by decide))'
        return f'c{n}'
    def td(q,k=7):
        if q==40:return 'TD40.exists_td'
        if q==50:return 'Design50.hasTD'
        if q==76:return 'Design76.hasTD'
        if q==100:return 'Design100.hasTD'
        if q==160:return 'TD160.exists_td'
        tag,*args=designs[q]
        if tag=='field':p,e=args
        elif tag=='cyclic' and prime(q):p,e=q,1
        elif tag=='product':return f'({td(args[0])}.mul {td(args[1])})'
        else:raise AssertionError((q,k,designs[q]))
        if k==7:return f'(prime_power_td (p := {p}) (e := {e}) (by decide) (by decide) (by decide))'
        return f'(wide_prime_power_td (k := {k}) (p := {p}) (e := {e}) (by decide) (by decide) (by decide))'
    def proof(n):
        tag,*xs=known[n]
        if tag=='frame13':return f'ProjectiveFrame13.models (m := {xs[0]}) {ref(2*xs[0]+1)} (FiniteBasis.model (by decide) (by decide))'
        if tag=='product':return f'{ref(xs[0])}.mul {ref(xs[1])}'
        if tag=='singular':return f'singular_idempotent_model {ref(xs[0])} {ref(xs[1])} (FiniteBasis.model (by decide) (by decide))'
        if tag=='td':
            k,q,r,h=xs
            if h:return f'{td(q,k)}.pointed_models (by decide) {ref(q+1)} {ref(r+1)}'
            out=f'{td(q,k)}.idempotent_models (by decide) {ref(q)} {ref(r)}'
            if k!=7:out+=f' {ref(k)} {ref(k+1)}'
            return out
        raise AssertionError((n,known[n]))
    fs=lambda xs:'{'+', '.join(map(str,xs))+'}'
    lines=['import equational_theories.Spectrum.Equation63.PointedDesign',
           'import equational_theories.Spectrum.Equation63.ProjectiveFrame13',
           'import equational_theories.Spectrum.Equation63.Designs.N50',
           'import equational_theories.Spectrum.Equation63.Designs.N76',
           'import equational_theories.Spectrum.Equation63.Designs.N100',
           'import equational_theories.Spectrum.Equation63.TD40',
           'import equational_theories.Spectrum.Equation63.TD160',
           'import equational_theories.Spectrum.Equation63.FieldTail','',
           '/-! Generated by scripts/spectrum_667_extended_bounds.py.',
           f'Transversal designs and partial-algebra frames fill {len(new)} further',
           'idempotent E63 orders. The design certificates are checked in Lean. -/',
           'set_option maxRecDepth 65536','set_option maxHeartbeats 0',
           'namespace Spectrum.E63.ExtendedBounds','',
           'def extraOrders : Finset ℕ := '+fs(new),'']
    for n in new:lines.extend([f'private theorem c{n} : Model (Fin {n}) true :=',f'  {proof(n)}',''])
    lines.extend(['theorem extra_model {n : ℕ} (hn : n ∈ extraOrders) : Model (Fin n) true := by',
                  '  simp only [extraOrders, Finset.mem_insert, Finset.mem_singleton] at hn',
                  '  rcases hn with '+' | '.join(['rfl']*len(new))])
    lines += [f'  · exact c{n}' for n in new]
    idem_cutoff=max(set(range(CUTOFF))-known.keys())+1
    lines += ['', 'def remaining : Finset ℕ := FieldBounds.remaining \\ extraOrders','',
              'theorem model {n : ℕ} (hn : n ∉ remaining) : Model (Fin n) true := by',
              '  by_cases he : n ∈ extraOrders','  · exact extra_model he',
              '  · apply FieldBounds.model','    intro h',
              '    exact hn (Finset.mem_sdiff.mpr ⟨h,he⟩)','',
              f'private theorem bound : ∀ n ∈ remaining, n < {idem_cutoff} := by decide +kernel','',
              f'theorem all_large {{n : ℕ}} (hn : {idem_cutoff} ≤ n) : Model (Fin n) true := by',
              '  apply model','  intro h','  have := bound n h','  omega','',
              'spectrum_assert extra_model complete','spectrum_assert all_large complete','',
              'end Spectrum.E63.ExtendedBounds','']
    outputs={DEST/'Equation63/ExtendedBounds.lean':'\n'.join(lines)}
    lines=['import equational_theories.Spectrum.Equation63.ExtendedBounds',
           'import equational_theories.Spectrum.Equation667883FieldBounds','',
           '/-! Generated by scripts/spectrum_667_extended_bounds.py.',
           'Constructive E667/E883 tails using the extended transversal designs. -/',
           'set_option maxRecDepth 65536','set_option maxHeartbeats 0',
           'namespace Spectrum','open Law Law.MagmaLaw','']
    for law in (667,883):
        positives=positive_recipes(law,known)
        remaining=sorted(set(range(1,CUTOFF))-positives.keys())
        assert positives.keys()-positive_recipes(law,basis).keys()<=set(new)
        cutoff=max(remaining)+1
        lines += [f'namespace E{law}.ExtendedBounds','',
                  'def remaining : Finset ℕ := '+fs(remaining),'',
                  f'private theorem coverage : ∀ n ∈ E{law}.FieldBounds.remaining,',
                  '    n ∉ remaining → n ∈ E63.ExtendedBounds.extraOrders := by decide +kernel','',
                  f'theorem lower : positiveExcept remaining ⊆ Law{law}.spectrum := by',
                  '  rintro n ⟨hn,he⟩',f'  by_cases hold : n ∈ E{law}.FieldBounds.remaining',
                  f'  · exact ⟨hn,(E63.ExtendedBounds.extra_model (coverage n hold he)).hasModel{law}⟩',
                  f'  · exact E{law}.FieldBounds.lower ⟨hn,hold⟩','',
                  f'private theorem bound : ∀ n ∈ remaining, n < {cutoff} := by decide +kernel','',
                  f'theorem all_large {{n : ℕ}} (hn : {cutoff} ≤ n) : Law{law}.HasModel n := by',
                  '  apply (lower ⟨by omega,?_⟩).2','  intro h',
                  '  have := bound n h','  omega','',
                  f'theorem cofinite : CofiniteSpectrum Law{law} :=',
                  f'  ⟨{cutoff},fun _ hn => ⟨by omega,all_large hn⟩⟩','',
                  'spectrum_assert lower complete','spectrum_assert all_large complete',
                  'spectrum_assert cofinite complete','',f'end E{law}.ExtendedBounds','']
    lines+=['end Spectrum','']
    outputs[DEST/'Equation667883ExtendedBounds.lean']='\n'.join(lines)
    return outputs

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,text in generate().items():
        if args.check:assert path.read_text()==text,f'Stale generated file: {path}'
        else:path.write_text(text)
