#!/usr/bin/env python3
"""Reproduce the subalgebra obstruction E3352 → E4408.

Every eligible target preserves either the complement of {3} or {0, 3}.
The source preserves neither. This script checks the finite source and relation
instances, replays the minimized SMT refutation, and emits its Lean certificate.
"""

import argparse
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data/definability_subset_3352.json"
OUTPUT = ROOT / "equational_theories/Definability/Generated/Subset3352.lean"
D = json.loads(DATA.read_text())
args = " ".join("abcdefgh")
app = lambda x, y: f"(app {args} {x} {y})"
lines = [
    "/- Generated by `scripts/definability_subset_check.py`. The finite refutation uses",
    "Lean’s standard `bv_decide` LRAT checker with compiled evaluation. -/",
    "import Std.Tactic.BVDecide",
    "import Mathlib.Data.BitVec",
    "import Mathlib.Data.Fintype.OfMap",
    "import Mathlib.Data.Fin.VecNotation",
    "import Mathlib.Tactic.FinCases",
    "",
    "set_option maxHeartbeats 8000000",
    "set_option maxRecDepth 100000",
    "",
    "namespace Definability.Subset3352",
    "",
    "local instance : Fintype (BitVec 3) := Fintype.ofEquiv (Fin 8) (BitVec.equivFin (m := 3)).symm.toEquiv",
    "",
    "def Preserves (R : BitVec 3 → BitVec 3 → Prop) (f : BitVec 3 → BitVec 3 → BitVec 3) : Prop :=",
    "  ∀ a b c d, R a b → R c d → R (f a c) (f b d)",
    "",
    "def relation (i : Fin 6) (x y : BitVec 3) : Prop :=",
    "  (!["
    + ",\n     ".join(
        "fun x y => " + " || ".join(f"(x == {a} && y == {b})" for a, b in R)
        for R in D["forward"]
    )
    + "] : Fin 6 → BitVec 3 → BitVec 3 → Bool) i x y = true",
    "",
    "instance (i x y) : Decidable (relation i x y) := by unfold relation; infer_instance",
    "",
    f"def app ({args} : BitVec 24) (x y : BitVec 3) : BitVec 3 :=",
    "  ((if x = 0 then a else if x = 1 then b else if x = 2 then c else if x = 3 then d else if x = 4 then e else if x = 5 then f else if x = 6 then g else h) >>> (y.zeroExtend 24 * 3)).extractLsb' 0 3",
    "",
]
cs = []
proofs = []
for c in D["core"]:
    if c[0] == "law":
        _, x, y = c
        x = str(x)
        y = str(y)
        cs.append(app(x, app(x, y)) + " = " + app(app(y, y), x))
        proofs.append(f"hl {x} {y}")
    if c[0] == "id":
        _, x = c
        cs.append(app(str(x), str(x)) + (" = " if x == 3 else " ≠ ") + str(x))
        proofs.append(f"hi{x}")
    if c[0] == "rel":
        _, k, a, b, c, d = c
        cs.append(f"relation {k} {app(str(a),str(b))} {app(str(c),str(d))}")
        proofs.append(f"hr {k} {a} {c} {b} {d} (by decide) (by decide)")
cs += ["x ≠ 3", "y ≠ 3", app("x", "y") + " = 3"]
proofs += ["hx", "hy", "hxy"]
cs += [
    "("
    + " ∨ ".join(
        f"({app(str(x),str(y))} ≠ 0 ∧ {app(str(x),str(y))} ≠ 3)"
        for x in [0, 3]
        for y in [0, 3]
    )
    + ")"
]
proofs += ["hbad"]
inline_cs = cs.copy()
for i, item in enumerate(D["core"]):
    if item[0] == "rel":
        _, k, a, b, c, d = item
        v, w = app(str(a), str(b)), app(str(c), str(d))
        inline_cs[i] = (
            "("
            + " || ".join(f"({v} == {u} && {w} == {z})" for u, z in D["forward"][k])
            + ") = true"
        )

lines += [
    f"def constraints ({args} : BitVec 24) (x y : BitVec 3) : Prop :=",
    "  " + " ∧\n  ".join(cs),
    "",
    f"theorem refute ({args} : BitVec 24) (x y : BitVec 3) : ¬ constraints {args} x y := by",
    "  change ¬ (" + " ∧\n    ".join(inline_cs) + ")",
    "  unfold app",
    "  bv_decide (config := { timeout := 120 })",
    "",
    "def pack (f : BitVec 3 → BitVec 3) : BitVec 24 :=",
    "  f 7 ++ f 6 ++ f 5 ++ f 4 ++ f 3 ++ f 2 ++ f 1 ++ f 0",
    "",
    "theorem app_pack (f : BitVec 3 → BitVec 3 → BitVec 3) (x y : BitVec 3) :",
    "    app " + " ".join(f"(pack (f {i}))" for i in range(8)) + " x y = f x y := by",
    "  have cases8 : ∀ z : BitVec 3, z = 0 ∨ z = 1 ∨ z = 2 ∨ z = 3 ∨",
    "      z = 4 ∨ z = 5 ∨ z = 6 ∨ z = 7 := by decide",
    "  rcases cases8 x with rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl <;>",
    "    rcases cases8 y with rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl <;>",
    "    unfold app pack <;> bv_normalize",
    "",
    "def Closed (S : BitVec 3 → Prop) (f : BitVec 3 → BitVec 3 → BitVec 3) : Prop :=",
    "  ∀ x y, S x → S y → S (f x y)",
    "",
    "theorem cover (f : BitVec 3 → BitVec 3 → BitVec 3)",
    "    (hl : ∀ x y, f x (f x y) = f (f y y) x)",
    "    (hr : ∀ i, Preserves (relation i) f)",
    "    (hi0 : f 0 0 ≠ 0) (hi3 : f 3 3 = 3) (hi5 : f 5 5 ≠ 5) (hi6 : f 6 6 ≠ 6) :",
    "    Closed (fun x => x ≠ 3) f ∨ Closed (fun x => x = 0 ∨ x = 3) f := by",
    "  classical",
    "  by_contra hn",
    "  simp only [not_or, Closed, not_forall, not_not] at hn",
    "  obtain ⟨⟨x, y, hx, hy, hxy⟩, hb⟩ := hn",
    "  have hbad : (f 0 0 ≠ 0 ∧ f 0 0 ≠ 3) ∨ (f 0 3 ≠ 0 ∧ f 0 3 ≠ 3) ∨",
    "      (f 3 0 ≠ 0 ∧ f 3 0 ≠ 3) ∨ (f 3 3 ≠ 0 ∧ f 3 3 ≠ 3) := by",
    "    obtain ⟨a, b, ha, hb, hab⟩ := hb",
    "    rcases ha with rfl | rfl <;> rcases hb with rfl | rfl <;> tauto",
    "  apply refute " + " ".join(f"(pack (f {i}))" for i in range(8)) + " x y",
    "  unfold constraints",
    "  simp only [app_pack]",
    "  exact ⟨" + ",\n    ".join(proofs) + "⟩",
    "",
    "end Definability.Subset3352",
    "",
]
proof = "\n".join(lines)


def check():
    import z3
    from spectrum_generate import load_equations, satisfies

    table = D["source"]
    assert satisfies(*load_equations()[3351], sum(table, []), 8)
    for relation in D["forward"]:
        rows = set(map(tuple, relation))
        assert all(
            (table[a][c], table[b][d]) in rows
            for (a, b), (c, d) in itertools.product(rows, repeat=2)
        )
    assert table[0][1] == 3 and table[0][0] not in (0, 3)
    assert [i for i in range(8) if table[i][i] == i] == [3]
    sort, elements = z3.EnumSort("Subset3352", [f"e{i}" for i in range(8)])
    operation = z3.Function("target", sort, sort, sort)
    solver = z3.Solver()
    solver.set(timeout=120000)
    for item in D["core"]:
        if item[0] == "law":
            _, x, y = item
            x, y = elements[x], elements[y]
            solver.add(operation(x, operation(x, y)) == operation(operation(y, y), x))
        elif item[0] == "id":
            _, x = item
            solver.add((operation(elements[x], elements[x]) == elements[x]) == (x == 3))
        else:
            _, k, a, b, c, d = item
            relation = D["forward"][k]
            assert [a, c] in relation and [b, d] in relation
            solver.add(
                z3.Or(
                    [
                        z3.And(
                            operation(elements[a], elements[b]) == elements[u],
                            operation(elements[c], elements[d]) == elements[v],
                        )
                        for u, v in relation
                    ]
                )
            )
    for subset in ([0, 1, 2, 4, 5, 6, 7], [0, 3]):
        solver.add(
            z3.Or(
                [
                    z3.And(
                        [
                            operation(elements[x], elements[y]) != elements[z]
                            for z in subset
                        ]
                    )
                    for x, y in itertools.product(subset, repeat=2)
                ]
            )
        )
    result = str(solver.check())
    if result != "unsat":
        raise RuntimeError(f"Subset coverage replay returned {result}")
    print(
        f"Source, six compatible relations and {len(D['core'])} core constraints checked; Z3: unsat."
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    options = parser.parse_args()
    check()
    if options.write:
        OUTPUT.write_text(proof)
    elif options.check and OUTPUT.read_text() != proof:
        raise SystemExit(f"Stale generated proof: {OUTPUT.relative_to(ROOT)}")
    print("The generated Lean theorem must compile before this is a board fact.")


if __name__ == "__main__":
    main()
