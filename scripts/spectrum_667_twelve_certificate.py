#!/usr/bin/env python3
"""Prepare/audit the bijective-square portion of the E667 order-12 proof.

The full order-12 theorem also requires the three noninjective-square cases.
Preparation does not establish a Lean theorem: build the replay modules.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

from spectrum_667_fixed_square import encode, permutation, centralizer_first_use
from spectrum_667_incremental import partitions

ROOT=Path(__file__).resolve().parent.parent
DATA=ROOT/'data/spectrum/667_twelve_square_rup'
META=ROOT/'data/spectrum/667_order12_square_refutations.json'
LEAN=ROOT/'equational_theories/Spectrum/Equation667FixedSquare'
CASES=list(partitions(12))
NORMALIZED={7,15,30,56}


def sha(data):return hashlib.sha256(data).hexdigest()


def cnf(i):
    d=permutation(CASES[i]);top,cs=encode(d)
    if i in NORMALIZED:cs+=centralizer_first_use(d)
    return (f'p cnf {top} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode()


def prepare(work):
    DATA.mkdir(exist_ok=True,parents=True);rows=[]
    for i,c in enumerate(CASES):
        sub='involution-first-use-proofs' if i in NORMALIZED else 'fixed-square-proofs'
        stem=work/sub/('-'.join(map(str,c)))
        original=json.loads(stem.with_suffix('.json').read_text())
        assert original['status']=='UNSAT'
        source=stem.with_suffix('.cnf').read_bytes()
        assert sha(source)==original['cnf_sha256']==sha(cnf(i))
        payload=stem.with_suffix('.rup.gz').read_bytes()
        name=f'{i:03d}.rup.gz';(DATA/name).write_bytes(payload)
        rows.append(dict(index=i,cycles=c,normalized=i in NORMALIZED,
            cnf_sha256=sha(source),compact_sha256=sha(gzip.decompress(payload)),
            compressed_sha256=sha(payload),compressed_bytes=len(payload),
            certificate=str((DATA/name).relative_to(ROOT))))
    META.write_text(json.dumps(dict(law=667,order=12,
        scope='bijective square maps only; 77 conjugacy classes',
        trust='Lean CompactRup reconstruction, LRAT.check_sound, explicit spectrum_native checks',
        cases=rows),indent=2)+'\n')


def audit():
    rows=json.loads(META.read_text())['cases']
    assert len(rows)==77 and [r['index'] for r in rows]==list(range(77))
    for r in rows:
        i=r['index'];data=(ROOT/r['certificate']).read_bytes()
        assert r['cycles']==CASES[i] and r['normalized']==(i in NORMALIZED)
        assert sha(cnf(i))==r['cnf_sha256']
        assert len(data)==r['compressed_bytes'] and sha(data)==r['compressed_sha256']
        assert sha(gzip.decompress(data))==r['compact_sha256']
    return rows


def render(rows):
    batches=[[i for i in range(77) if i not in NORMALIZED and i%4==b] for b in range(4)]
    batches += [[i] for i in sorted(NORMALIZED)]
    (LEAN/'Certificates').mkdir(exist_ok=True)
    for batch,ids in enumerate(batches):
        s='''import equational_theories.Spectrum.Equation667FixedSquare.Completeness
import SpectrumCertificateData
import SpectrumCertificateData.Replay

/- Generated by scripts/spectrum_667_twelve_certificate.py.
Untrusted compact data is reconstructed and checked by Lean's proved LRAT
checker. No solver runs during the build. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
'''
        for i in ids:
            row=rows[i];case=f'{i:03d}';normal=str(i in NORMALIZED).lower()
            s+=f'''
namespace Spectrum.E667.FixedSquare.Certificates.C{case}
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData

private def refutation : Array IntAction :=
  CompactRup.reconstruct (include_binary_gzip "../../../../{row['certificate']}")
    (natNormalized (Cases.table {i}) {normal})

@[spectrum_native]
theorem checked : check refutation (natNormalized (Cases.table {i}) {normal}) = true := by
  native_decide

theorem unsat : (natNormalized (Cases.table {i}) {normal}).Unsat :=
  check_sound refutation _ checked

spectrum_assert unsat complete
end Spectrum.E667.FixedSquare.Certificates.C{case}
'''
        (LEAN/f'Certificates/Batch{batch:02d}.lean').write_text(s)
    s=''.join(f'import equational_theories.Spectrum.Equation667FixedSquare.Certificates.Batch{b:02d}\n' for b in range(len(batches)))
    s+='''
namespace Spectrum.E667.FixedSquare
theorem all_refuted : ∀ i, (natNormalized (Cases.table i) (normalizeCase i)).Unsat := by
  intro i
  fin_cases i
'''+''.join(f'  · exact Certificates.C{i:03d}.unsat\n' for i in range(77))
    s+='''
theorem not_injective_square (f : Fin 12 → Fin 12 → Fin 12)
    (h : RightIdentityTwelve.Holds f) : ¬ Function.Injective (fun x => f x x) :=
  no_injective_of_refuted all_refuted f h

spectrum_assert not_injective_square complete
end Spectrum.E667.FixedSquare
'''
    (LEAN/'Certificates.lean').write_text(s)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--prepare',type=Path,help='directory containing the captured, compacted searches')
    ap.add_argument('--write-lean',action='store_true')
    args=ap.parse_args()
    if args.prepare:prepare(args.prepare)
    rows=audit()
    if args.write_lean:render(rows)
    print('Audited 77 bijective-square certificates:',sum(r['compressed_bytes'] for r in rows),'compressed bytes')
