#!/usr/bin/env python3
"""Generate a small ordinary Lean linear-algebra proof for binary extensions.

The Python row reduction only selects combinations. Lean checks every resulting
identity by ring arithmetic in F2. No solver certificate or native axiom is used.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'equational_theories/Spectrum/Equation667BinaryFiveCompleteness.lean'


def generate():
    rows = []
    names = []
    declarations = []
    for i in range(5):
        for j in range(5):
            if i == j:
                continue
            t = 3*(i+j) % 5
            u = 3*(i+t) % 5
            mask = (1 << (5*i+j)) ^ (1 << (5*i+t)) ^ (1 << (5*j+u))
            rows.append(mask)
            names.append(f'h{i}{j}')
            declarations.append(f'  have h{i}{j} : C {i} {j} + C {i} {t} + C {j} {u} = 0 := H {i} {j}')
    for i in range(5):
        rows.append(1 << (6*i))
        names.append(f'hd {i}')
    # Reuse proved entries and prefer short sums over a dense elimination
    # certificate. After one longer seed deduction, short substitutions
    # determine the remaining entries.
    import itertools
    targets = {(i,j): ((1 << (5*i+j)) ^ (1 << (3*i % 5)) ^
                         (1 << (3*(2*j-i) % 5))) for i in range(5) for j in range(5)}
    entries = []
    while targets:
        found = None
        for size in range(1,4):
            combinations = {}
            for indices in itertools.combinations(range(len(rows)),size):
                mask = 0
                for k in indices:
                    mask ^= rows[k]
                combinations.setdefault(mask,indices)
            for ij,mask in targets.items():
                if mask in combinations:
                    found = ij,combinations[mask]
                    break
            if found:
                break
        if found is None:
            pivots, nulls = {}, []
            for k,row in enumerate(rows):
                proof = 1 << k
                while row:
                    bit = row.bit_length()-1
                    if bit not in pivots:
                        pivots[bit] = row,proof
                        break
                    r,p = pivots[bit]
                    row ^= r
                    proof ^= p
                if not row:
                    nulls.append(proof)
            choices = []
            for ij,row in targets.items():
                proof = 0
                while row:
                    r,p = pivots[row.bit_length()-1]
                    row ^= r
                    proof ^= p
                while True:
                    better = min([proof]+[proof^p for p in nulls],key=int.bit_count)
                    if better.bit_count() >= proof.bit_count():
                        break
                    proof = better
                choices.append((proof.bit_count(),ij,proof))
            _,ij,proof = min(choices)
            found = ij,tuple(k for k in range(len(rows)) if proof >> k & 1)
        (i,j),indices = found
        a,b = 3*i % 5,3*(2*j-i) % 5
        combination = ' + '.join(f'({names[k]})' for k in indices)
        entries.append(f'  have e{i}{j} : C {i} {j} = C 0 {a} + C 0 {b} := by')
        if i == 0:
            entries.append('    simp only [hd, zero_add]')
        elif i == j:
            entries.append('    rw [hd, double_zero]')
        else:
            entries.extend(['    linear_combination (norm := skip) '+combination,
                            '    ring_nf', '    reduce_mod_char'])
        rows.append(targets.pop((i,j)))
        names.append(f'e{i}{j}')
    cases = ['  fin_cases i <;> fin_cases j']
    for i in range(5):
        for j in range(5):
            cases.append(f'  · exact e{i}{j}')
    return '''import equational_theories.Spectrum.Equation667BinaryFive
import equational_theories.Spectrum.Equation667BinaryExtensions

/-! Completeness of the binary five-point formula. The 25 coordinate cases
below are small linear combinations of the cocycle identities, checked by
ordinary ring arithmetic. Generated by spectrum_667_binary_classification.py. -/
namespace Spectrum.E667.BinaryFive

set_option maxHeartbeats 500000 in
/-- Every normalized binary cocycle over the five-point mean algebra has the
explicit form v(i)+v(2j-i), with v recovered from the first row. -/
theorem normalized_complete (C : ZMod 5 → ZMod 5 → ZMod 2)
    (hd : ∀ i, C i i = 0) (hc : BinaryExtensions.Cocycle base C) (i j : ZMod 5) :
    C i j = cocycle (fun k => C 0 (3 * k)) i j := by
  have H (i j : ZMod 5) : C i j + C i (base i j) + C j (base i (base i j)) = 0 := by
    simpa only [base_idem, hd, zero_add] using hc i j
  have double_zero (a : ZMod 2) : a+a=0 := by ring_nf; reduce_mod_char
'''+ '\n'.join(declarations+entries+cases)+'''

spectrum_assert normalized_complete complete
end Spectrum.E667.BinaryFive
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write',action='store_true')
    args = p.parse_args()
    text = generate()
    if args.write:
        TARGET.write_text(text)
    else:
        assert TARGET.read_text() == text, 'Generated Lean source differs'
        print('Binary classification proof source matches the generator.')


if __name__ == '__main__':
    main()
