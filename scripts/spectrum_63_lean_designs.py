#!/usr/bin/env python3
"""Emit the four small difference matrices required by the E63 Lean construction."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def tuple_term(xs):
    if len(xs) == 1:
        return str(xs[0])
    return "(" + ", ".join(map(str, xs)) + ")"


def project(i, l):
    return "x." + "2." * i + "1" if i < l - 1 else "x." + "2." * (i - 1) + "2"


def main():
    dest = ROOT / "equational_theories/Spectrum/Equation63/Designs"
    dest.mkdir(exist_ok=True)
    for q, p, e, poly in [
        (9, 3, 2, [1, 0]),
        (25, 5, 2, [2, 0]),
        (27, 3, 3, [1, 2, 0]),
        (36, None, None, None),
    ]:
        if q == 36:
            ent = json.loads(
                (ROOT / "data/spectrum/63_difference_matrices.json").read_text()
            )["matrices"]["36"]
            mods = ent["group_moduli"]
            rows = [r[:7] for r in ent["rows"]]
        else:
            mods = [p] * e

            def digs(x):
                return [(x // p**i) % p for i in range(e)]

            def mul(a, b):
                a, b = digs(a), digs(b)
                c = [0] * (2 * e - 1)
                for i in range(e):
                    for j in range(e):
                        c[i + j] += a[i] * b[j]
                for k in range(2 * e - 2, e - 1, -1):
                    for i in range(e):
                        c[k - e + i] -= c[k] * poly[i]
                return [t % p for t in c[:e]]

            rows = [[mul(x, i) for i in range(7)] for x in range(q)]
        Q = " × ".join(f"ZMod {m}" for m in mods)
        projections = [project(i, len(mods)) for i in range(len(mods))]
        factors = [1]
        for m in mods[:-1]:
            factors.append(factors[-1] * m)
        index = " + ".join(f"{f} * {pr}.val" for f, pr in zip(factors, projections))
        bounds = "\n    ".join(
            f"have h{i} := ZMod.val_lt {pr}" for i, pr in enumerate(projections)
        )
        body = ",\n    ".join(
            "![" + ", ".join(tuple_term(v) for v in row) + "]" for row in rows
        )
        text = f"""import equational_theories.Spectrum.Equation63.DifferenceMatrix
import Mathlib.Data.Fin.VecNotation

/-! Generated by scripts/spectrum_63_lean_designs.py. All difference conditions
are checked by the Lean kernel; the generator and source tables are untrusted. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E63.Design{q}

abbrev Q := {Q}
def matrix (x : Q) (i : Fin 7) : Q :=
  ![{body}]
    ⟨{index}, by
    {bounds}
    omega⟩ i

theorem differences : ∀ i j, i ≠ j → Function.Injective (fun x => matrix x i - matrix x j) :=
  by decide +kernel

noncomputable def design : Transversal Groups (Fin {q}) (Q × Q) :=
  (differenceDesign matrix differences).relabel (Fintype.equivFinOfCardEq (by simp [Q]))

end Spectrum.E63.Design{q}
"""
        (dest / f"N{q}.lean").write_text(text)


if __name__ == "__main__":
    main()
