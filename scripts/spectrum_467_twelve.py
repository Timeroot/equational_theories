#!/usr/bin/env python3
"""Reproduce/audit E467 order-twelve certificates after diagonal conjugacy.

The 77 canonical permutations are certified to cover every cycle type in Lean.
Those with a two- or three-cycle are excluded algebraically. The remaining 20 cases use
compact RUP data and Lean's verified LRAT checker. No restricted search timeout
is an exclusion. Input generation is independent of the Lean CNF definition.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import lzma
from pathlib import Path
import resource
import subprocess
import time
from spectrum_467_square_search import clauses
from spectrum_1110_twelve import representatives
from spectrum_63_ten_certificate import TRIM

ROOT=Path(__file__).resolve().parents[1]
META=ROOT/'data/spectrum/467_order12.json'
WORK=ROOT/'.cache/e467-order12-final'
DEST=ROOT/'equational_theories/Spectrum/Equation467/OrderTwelve/Certificates'
def sha(b): return hashlib.sha256(b).hexdigest()

def eligible(d):
    return all((d[d[x]] != x or d[x] == x) and
               (d[d[d[x]]] != x or d[x] == x) for x in range(12))

def slack(d):
    support=max([x+1 for x in range(12) if d[x]!=x],default=0)
    return max(1,support-2)

def cnf(d):
    n=12;p=lambda x,y,z:1+(x*n+y)*n+z
    cs=clauses(d,first_use=False)
    cs += [[-p(0,y,z)] for y in range(n) for z in range(y+slack(d)+1,n)]
    return (f'p cnf {n**3} {len(cs)}\n'+''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode(),len(cs)

def render(r):
    formula = f'FixedEncoding.natFormula (E1110.CycleRepresentatives.representative12 {r["index"]}) {slack(r["diagonal"])}'
    return f'''import equational_theories.Spectrum.Equation467.OrderTwelve.Encoding
import equational_theories.Spectrum.Equation1110.CycleRepresentatives
import equational_theories.Spectrum.Status
import SpectrumCertificateData

/- Generated by scripts/spectrum_467_twelve.py.
CNF SHA-256: {r['cnf_sha256']}
Compact payload SHA-256: {r['proof_sha256']} -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E467.OrderTwelve.Certificates.C{r['index']}
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData
private def refutation : Array IntAction := CompactRup.reconstruct
  (include_binary_xz "../../../../../{r['certificate']}")
  ({formula})
@[spectrum_native]
theorem checked : check refutation
    ({formula}) = true := by native_decide
theorem unsat : ({formula}).Unsat :=
  check_sound refutation _ checked
spectrum_assert unsat complete
end Spectrum.E467.OrderTwelve.Certificates.C{r['index']}
'''

def solve(i,d,seconds):
    data,count=cnf(d);stem=WORK/f'C{i}';stem.with_suffix('.cnf').write_bytes(data)
    proof=stem.with_suffix('.lrat')
    def limits():resource.setrlimit(resource.RLIMIT_FSIZE,(1024**3,1024**3))
    start=time.monotonic()
    with stem.with_suffix('.log').open('w') as out:
        proc=subprocess.run(['cadical','--lrat','-t',str(seconds),str(stem.with_suffix('.cnf')),str(proof)],stdout=out,stderr=subprocess.STDOUT,timeout=seconds+30,preexec_fn=limits)
    assert proc.returncode==20,(i,proc.returncode)
    elapsed=time.monotonic()-start
    subprocess.run(['lake','env','lean','--run',str(WORK/'TrimBinary.lean'),str(proof)],check=True,cwd=ROOT,stdout=subprocess.DEVNULL)
    compact=stem.with_suffix('.rup')
    with Path(str(proof)+'.trimmed.bin').open('rb') as src:
        subprocess.run([str(WORK/'compact-rup'),'--input-mask',str(compact)],stdin=src,check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    payload=compact.read_bytes();packed=lzma.compress(payload,preset=6)
    assert len(packed)<=10*1024**2,(i,len(packed))
    path=ROOT/f'data/spectrum/467_order12_rup/C{i}.rup.xz';path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(packed)
    r=dict(index=i,diagonal=d,clauses=count,cnf_sha256=sha(data),proof_sha256=sha(payload),compressed_sha256=sha(packed),proof_bytes=len(payload),compressed_bytes=len(packed),search_seconds=round(elapsed,3),certificate=str(path.relative_to(ROOT)))
    print(f'C{i}: {len(packed):,} bytes, {elapsed:.2f}s solver',flush=True)
    return r

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--solve',action='store_true');ap.add_argument('--only',nargs='+',type=int,help='Regenerate only these case indices');ap.add_argument('--write',action='store_true');ap.add_argument('--seconds',type=int,default=600);ap.add_argument('--export-cnf',type=Path);ap.add_argument('--check-lean-cnf',type=Path);args=ap.parse_args()
    ds=representatives();cases=[(i,d) for i,d in enumerate(ds) if eligible(d)];assert len(cases)==20
    if args.only and not args.solve:ap.error('--only requires --solve')
    if args.only and not set(args.only)<={i for i,d in cases}:ap.error('--only contains an ineligible case')
    if args.solve:
        WORK.mkdir(parents=True,exist_ok=True)
        (WORK/'TrimBinary.lean').write_text(TRIM.replace('".trimmed"','".trimmed.bin"').replace('trimmed false','trimmed true'))
        subprocess.run(['g++','-O3','-std=c++17',str(ROOT/'scripts/spectrum_compact_rup.cpp'),'-o',str(WORK/'compact-rup')],check=True)
        selected=[t for t in cases if not args.only or t[0] in args.only]
        previous={r['index']:r for r in json.loads(META.read_text())['cases']} if args.only else {}
        with ThreadPoolExecutor(max_workers=4) as pool:new_rs=list(pool.map(lambda t:solve(*t,args.seconds),selected))
        previous.update({r['index']:r for r in new_rs})
        rs=[previous[i] for i,d in cases]
        META.write_text(json.dumps(dict(law=467,order=12,cases=rs),indent=2)+'\n')
    rs=json.loads(META.read_text())['cases'];assert [r['index'] for r in rs]==[i for i,d in cases]
    for r in rs:
        i=r['index'];assert r['diagonal']==ds[i];data,count=cnf(ds[i]);assert sha(data)==r['cnf_sha256'] and count==r['clauses']
        packed=(ROOT/r['certificate']).read_bytes();payload=lzma.decompress(packed)
        assert sha(packed)==r['compressed_sha256'] and len(packed)==r['compressed_bytes']
        assert sha(payload)==r['proof_sha256'] and len(payload)==r['proof_bytes']
        if args.export_cnf:
            args.export_cnf.mkdir(parents=True,exist_ok=True);(args.export_cnf/f'C{i}.cnf').write_bytes(data)
        if args.check_lean_cnf:assert (args.check_lean_cnf/f'C{i}.cnf').read_bytes()==data
        path=DEST/f'C{i}.lean'
        if args.write or (args.solve and (not args.only or i in args.only)):DEST.mkdir(parents=True,exist_ok=True);path.write_text(render(r))
        else:assert path.read_text()==render(r)
    print(f'Checked {len(rs)} cases, {sum(r["compressed_bytes"] for r in rs):,} bytes.')
if __name__=='__main__':main()
