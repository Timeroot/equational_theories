#!/usr/bin/env python3
"""Generate the six E63 table certificates retained by the Lean construction.

Each table is packed into a natural-number literal, with consecutive cells in
little-endian fixed-width fields. Lean's kernel checks the decoded operation;
neither the Python generator nor native_decide is trusted. Packing avoids the
large reduction cost of nested vector lookup. All other witnesses use proved
construction rules rather than saved multiplication tables.
"""
from pathlib import Path
from spectrum_63_bennett import build
from spectrum_63_atp import validate

ROOT = Path(__file__).resolve().parent.parent
ORDERS = [46, 47, 62, 74, 114, 118]


def main():
    tables = build()
    dest = ROOT / "equational_theories/Spectrum/Equation63/Witnesses"
    dest.mkdir(exist_ok=True)
    for n in ORDERS:
        table = [[row.index(y) for y in range(n)] for row in tables[n]]
        validate(table, n)
        width = (n - 1).bit_length()
        flat = sum(table, [])
        packed = sum(z << (width * i) for i, z in enumerate(flat))
        assert all((packed >> (width * i)) % 2**width == z for i, z in enumerate(flat))
        text = f"""import equational_theories.Spectrum.Equation63.Gluing

/-! Generated by scripts/spectrum_63_lean_witnesses.py from Bennett's construction.
A {n}×{n} table, packed row-major into {width}-bit fields, least significant first.
Every law instance is checked by kernel reduction, without native_decide. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E63

private def packed{n} : Nat := 0x{packed:x}

def table{n} (x y : Fin {n}) : Fin {n} :=
  ⟨((packed{n} >>> ((x.val*{n}+y.val)*{width})) % {2**width}) % {n},
    Nat.mod_lt _ (by decide)⟩

theorem law{n} : Lawful table{n} := by decide +kernel

theorem model{n} : Law63.HasModel {n} :=
  (show Model (Fin {n}) from ⟨table{n}, law{n}, by simp⟩).hasModel

end Spectrum.E63
"""
        (dest / f"N{n}.lean").write_text(text)


if __name__ == "__main__":
    main()
