#!/usr/bin/env python3
"""Audit/reproduce the small direct-table certificates excluding E1279 at12.

Squaring is a permutation without two-cycles. The 35 remaining cycle types
are covered by a Lean permutation-conjugacy theorem, and support-preserving
row normalization justifies every extra constraint. No solver is needed for
ordinary Lean builds.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import lzma
from pathlib import Path
import re
import resource
import subprocess
import time
from spectrum_63_ten_certificate import TRIM

ROOT = Path(__file__).resolve().parents[1]
META = ROOT / 'data/spectrum/1279_order12.json'
DEST = ROOT / 'equational_theories/Spectrum/Equation1279/OrderTwelve'
WORK = ROOT / '.cache/e1279-twelve-reproduce'

def sha(b):
    return hashlib.sha256(b).hexdigest()

def representatives():
    s = (ROOT / 'equational_theories/Spectrum/Equation1110/CycleRepresentatives.lean').read_text()
    s = s.split('def dataRows12 :', 1)[1].split('def data12', 1)[0]
    ds = [list(map(int, re.findall(r'\d+', row))) for row in re.findall(r'#\[([\d, ]+)\]', s)]
    assert len(ds) == 77 and all(sorted(d) == list(range(12)) for d in ds)
    return ds

def candidates():
    return [(i,d) for i,d in enumerate(representatives())
            if not any(d[d[x]] == x and d[x] != x for x in range(12))]

def support(d):
    return max([x+1 for x,y in enumerate(d) if x != y] or [0])

def cnf(d):
    n = 12
    p = lambda x,y,z: 1+(x*n+y)*n+z
    def exactly(vs):
        return [vs] + [[-vs[i], -vs[j]] for i in range(n) for j in range(i+1,n)]
    cs = []
    for x in range(n):
        for y in range(n):
            cs += exactly([p(x,y,z) for z in range(n)])
            cs += exactly([p(x,z,y) for z in range(n)])
            cs += exactly([p(z,x,y) for z in range(n)])
    for x in range(n):
        for y in range(n):
            for a in range(n):
                for b in range(n):
                    cs += [[-p(d[x],y,a),-p(a,y,b),p(y,b,x)],
                           [-p(d[x],y,a),p(a,y,b),-p(y,b,x)],
                           [p(d[x],y,a),-p(a,y,b),-p(y,b,x)]]
    k = max(support(d)-1, 1)
    cs += [[p(x,x,y)] for x,y in enumerate(d)]
    cs += [[-p(0,y,z)] for y in range(n) for z in range(y+k+1,n)]
    cs = [c for c in cs if not any(-v in c for v in c)]
    data = (f'p cnf {n**3} {len(cs)}\n' +
            ''.join(' '.join(map(str,c))+' 0\n' for c in cs)).encode()
    return data, len(cs)

def batches(rs):
    # Seven cases per module; greedily balance their compact proof sizes.
    out = [[] for _ in range(5)]
    for j in sorted(range(35), key=lambda j: -rs[j]['compressed_bytes']):
        b = min((b for b in range(5) if len(out[b]) < 7),
                key=lambda b: sum(rs[k]['compressed_bytes'] for k in out[b]))
        out[b].append(j)
    return [sorted(b) for b in out]

def rendered(rs):
    pre = '''import equational_theories.Spectrum.Equation1279.DirectEncoding
import equational_theories.Spectrum.Equation1110.CycleRepresentatives

/-! Generated by scripts/spectrum_1279_twelve.py. The indices omit exactly
those canonical diagonal permutations containing a nontrivial two-cycle. -/
namespace Spectrum.E1279.OrderTwelve
open Std.Sat
'''
    pre += 'private def indices : Array Nat := #[' + ', '.join(str(r['index']) for r in rs) + ']\n'
    pre += 'private def allowances : Array Nat := #[' + ', '.join(str(r['allowance']) for r in rs) + ']\n'
    pre += '''def sourceIndex (i : Fin 35) : Fin 77 :=
  ⟨indices[i.val]! % 77, Nat.mod_lt _ (by decide)⟩
def allowance (i : Fin 35) : Nat := allowances[i.val]!
def natFormula (i : Fin 35) : CNF Nat :=
  DirectEncoding.natFormula (E1110.CycleRepresentatives.data12 (sourceIndex i)) (allowance i)
end Spectrum.E1279.OrderTwelve
'''
    result = {'Core.lean': pre}
    groups = batches(rs)
    for b, js in enumerate(groups):
        s = f'''import equational_theories.Spectrum.Equation1279.OrderTwelve.Core
import equational_theories.Spectrum.Status
import SpectrumCertificateData

/-! Generated by scripts/spectrum_1279_twelve.py. Seven compact refutations;
exact CNF and payload hashes are recorded in data/spectrum/1279_order12.json. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1279.OrderTwelve.Batch{b}
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData
'''
        s += 'private def indices : Array Nat := #[' + ', '.join(map(str,js)) + ']\n'
        s += '''def caseIndex (i : Fin 7) : Fin 35 :=
  ⟨indices[i.val]! % 35, Nat.mod_lt _ (by decide)⟩
private def payloads : Array ByteArray := #[
'''
        s += ',\n'.join('  include_binary_xz "../../../../'+rs[j]['certificate']+'"' for j in js)
        s += '''
]
private def refutation (i : Fin 7) : Array IntAction :=
  CompactRup.reconstruct payloads[i.val]! (natFormula (caseIndex i))
@[spectrum_native]
theorem checked : ∀ i : Fin 7,
    check (refutation i) (natFormula (caseIndex i)) = true := by native_decide

theorem unsat (i : Fin 7) : (natFormula (caseIndex i)).Unsat :=
  check_sound (refutation i) _ (checked i)
spectrum_assert unsat complete
'''
        s += f'end Spectrum.E1279.OrderTwelve.Batch{b}\n'
        result[f'Batch{b}.lean'] = s
    s = ''.join(f'import equational_theories.Spectrum.Equation1279.OrderTwelve.Batch{b}\n' for b in range(5))
    s += '''
namespace Spectrum.E1279.OrderTwelve
set_option maxRecDepth 65536
set_option maxHeartbeats 0

theorem unsat (i : Fin 35) : (natFormula i).Unsat := by
  fin_cases i
'''
    for j in range(35):
        b = next(b for b,js in enumerate(groups) if j in js)
        s += f'  · exact Batch{b}.unsat {groups[b].index(j)}\n'
    s += 'spectrum_assert unsat complete\nend Spectrum.E1279.OrderTwelve\n'
    result['Certificates.lean'] = s
    return result

def solve(item, seconds):
    i,d = item
    data,count = cnf(d)
    stem = WORK / f'C{i}'
    stem.with_suffix('.cnf').write_bytes(data)
    def limit():
        resource.setrlimit(resource.RLIMIT_FSIZE, (256*1024**2,256*1024**2))
    start = time.monotonic()
    with stem.with_suffix('.log').open('w') as log:
        p = subprocess.run(['cadical','--lrat','-t',str(seconds),str(stem.with_suffix('.cnf')),str(stem.with_suffix('.lrat'))],
                           stdout=log,stderr=subprocess.STDOUT,timeout=seconds+20,preexec_fn=limit)
    assert p.returncode == 20, (i,p.returncode)
    elapsed = time.monotonic()-start
    subprocess.run(['lake','env','lean','--run',str(WORK/'TrimBinary.lean'),str(stem.with_suffix('.lrat'))],check=True,stdout=subprocess.DEVNULL,cwd=ROOT)
    with Path(str(stem.with_suffix('.lrat'))+'.trimmed.bin').open('rb') as src:
        subprocess.run([str(WORK/'compact-rup'),'--input-mask',str(stem.with_suffix('.rup'))],stdin=src,check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    payload = stem.with_suffix('.rup').read_bytes()
    packed = lzma.compress(payload,preset=6)
    assert len(packed) < 5*1024**2
    path = ROOT/f'data/spectrum/1279_order12_rup/C{i}.rup.xz'
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_bytes(packed)
    return dict(index=i,diagonal=d,support=support(d),allowance=max(support(d)-1,1),status='UNSAT',seconds=round(elapsed,3),
                certificate=str(path.relative_to(ROOT)),compressed_bytes=len(packed),proof_bytes=len(payload),
                cnf_sha256=sha(data),proof_sha256=sha(payload),compressed_sha256=sha(packed),clauses=count,format='direct-table-compact-rup-xz')

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--solve',action='store_true')
    ap.add_argument('--write',action='store_true')
    ap.add_argument('--seconds',type=int,default=60)
    ap.add_argument('--jobs',type=int,default=3)
    ap.add_argument('--check-lean-cnf',type=Path)
    args = ap.parse_args()
    cs = candidates()
    assert len(cs) == 35
    if args.solve:
        WORK.mkdir(parents=True,exist_ok=True)
        (WORK/'TrimBinary.lean').write_text(TRIM.replace('".trimmed"','".trimmed.bin"').replace('trimmed false','trimmed true'))
        subprocess.run(['g++','-O3','-std=c++17',str(ROOT/'scripts/spectrum_compact_rup.cpp'),'-o',str(WORK/'compact-rup')],check=True)
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            rs = list(pool.map(lambda c: solve(c,args.seconds),cs))
        META.write_text(json.dumps(dict(law=1279,order=12,cases=rs),indent=2)+'\n')
    rs = json.loads(META.read_text())['cases']
    assert [r['index'] for r in rs] == [i for i,d in cs]
    for r,(i,d) in zip(rs,cs):
        assert r['diagonal'] == d and r['support'] == support(d)
        assert r['allowance'] == max(support(d)-1,1)
        data,count = cnf(d)
        assert r['clauses'] == count and r['cnf_sha256'] == sha(data)
        packed = (ROOT/r['certificate']).read_bytes()
        payload = lzma.decompress(packed)
        assert r['compressed_sha256'] == sha(packed) and r['compressed_bytes'] == len(packed)
        assert r['proof_sha256'] == sha(payload) and r['proof_bytes'] == len(payload)
        if args.check_lean_cnf:
            assert (args.check_lean_cnf/f'C{i}.cnf').read_bytes() == data
    for name,source in rendered(rs).items():
        path = DEST/name
        if args.write or args.solve:
            path.write_text(source)
        else:
            assert path.read_text() == source, f'Stale generated source: {path}'
    print(f'Checked {len(rs)} direct-table certificates, {sum(r["compressed_bytes"] for r in rs):,} bytes.')
if __name__ == '__main__':
    main()
