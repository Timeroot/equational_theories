#!/usr/bin/env python3
"""Audit the tiny coverage certificate for E1483's idempotent rank-four rows.

The five representative row certificates and four other head shapes use the
main spectrum_1483_twelve.py inventory. This supplements them with coverage of
the twenty-one sorted rows, avoiding an assumed exhaustive enumeration.
"""
import argparse
import itertools
import json
import lzma
from pathlib import Path
import spectrum_1483_twelve as main

DATA = main.ROOT / 'data/spectrum/1483_order12_inside_four_coverage.json'
DEST = main.DEST / 'InsideFourCoverage.lean'


def cnf_bytes():
    rec = dict(encoding='headlex', rank=4, zero_in_image=True,
               fixed_cells=[[0, 0, 0], [0, 2, 0], [0, 3, 0]])
    clauses = main.clauses(rec)
    for tail in itertools.combinations_with_replacement((1, 2, 3), 5):
        row = (0, 0, 0, 0, 1, 2, 3) + tail
        clauses.append([-(1 + 12 * i + v) for i, v in enumerate(row)])
    return (f'p cnf 22464 {len(clauses)}\n' + ''.join(
        ' '.join(map(str, c)) + ' 0\n' for c in clauses)).encode()


def render(rec):
    return f'''import equational_theories.Spectrum.Equation1483.OrderTwelve.InsideFourRows
import equational_theories.Spectrum.Status
import SpectrumCertificateData

/- Generated by scripts/spectrum_1483_twelve_inside_four.py.
Coverage CNF SHA-256: {rec['cnf_sha256']}. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1483.OrderTwelve.Certificates.InsideFourCoverage
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData InsideFourRows

private def refutation : Array IntAction := CompactRup.reconstruct
  (include_binary_xz "../../../../../{rec['certificate']}") coverage

@[spectrum_native]
theorem checked : check refutation coverage = true := by native_decide

theorem unsat : coverage.Unsat := check_sound refutation _ checked
spectrum_assert unsat complete
end Spectrum.E1483.OrderTwelve.Certificates.InsideFourCoverage
'''


def run():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check-lean-cnf', type=Path)
    args = ap.parse_args()
    rec = json.loads(DATA.read_text())
    cnf = cnf_bytes()
    assert main.sha(cnf) == rec['cnf_sha256']
    assert len(cnf.splitlines()) - 1 == rec['clauses']
    packed = (main.ROOT / rec['certificate']).read_bytes()
    raw = lzma.decompress(packed)
    assert len(packed) == rec['compressed_bytes'] and main.sha(packed) == rec['compressed_sha256']
    assert len(raw) == rec['proof_bytes'] and main.sha(raw) == rec['proof_sha256']
    if args.check_lean_cnf:
        assert args.check_lean_cnf.read_bytes() == cnf
    if args.write:
        DEST.write_text(render(rec))
    else:
        assert DEST.read_text() == render(rec)
    print(f'Inside-four row coverage: {len(packed):,} bytes; hashes and CNF checked.')


if __name__ == '__main__':
    run()
