#!/usr/bin/env python3
"""Generate an ordinary Lean refutation of E1485 with a fixed idempotent orbit.

The search only proposes case splits and ground instances of E1485 or its dual.
The generated proof checks every branch in Lean; no search result is an axiom.
No external solver, model bank, or saved search tree is required.
"""

import argparse
from itertools import product
from pathlib import Path

from spectrum_generate import load_equations, satisfies

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "equational_theories/Definability/Generated/Idempotent1485.lean"
CYCLE = (1, 2, 0, 5, 4, 7, 6, 3)
SOURCE = (
    (0, 3, 1, 0, 3, 1, 4, 4),
    (2, 1, 5, 4, 5, 1, 4, 2),
    (7, 0, 2, 0, 7, 4, 4, 2),
    (4, 1, 1, 4, 1, 1, 4, 4),
    (7, 3, 5, 0, 6, 1, 4, 2),
    (2, 4, 2, 4, 2, 4, 4, 2),
    (4, 4, 4, 4, 4, 4, 4, 4),
    (0, 0, 4, 0, 0, 4, 4, 4),
)


def ground(term, values):
    if isinstance(term, str):
        return values[term]
    return tuple(ground(child, values) for child in term)


def make_rules():
    """Ground E1485 and its equationally proved dual on all triples."""
    rhs = load_equations()[1484][1]
    rules = []
    for name, term in (("h", rhs), ("hd", ((("y", "z"), "x"), ("x", "y")))):
        for x, y, z in product(range(8), repeat=3):
            rules.append((name, x, y, z, ground(term, dict(x=x, y=y, z=z))))
    return rules


class OrbitConflict(Exception):
    pass


def assign(table, i, j, value):
    """Propagate one cell around the three-cycle, detecting inconsistencies."""
    for _ in range(3):
        old = table[8 * i + j]
        if old is not None and old != value:
            raise OrbitConflict
        table[8 * i + j] = value
        i, j, value = CYCLE[i], CYCLE[j], CYCLE[value]


def search(rules):
    def visit(table):
        forced = []
        while True:
            needed = {}

            def evaluate(term):
                if isinstance(term, int):
                    return term
                i, j = map(evaluate, term)
                if i is None or j is None:
                    return None
                cell = 8 * i + j
                if table[cell] is None:
                    needed[cell] = needed.get(cell, 0) + 1
                return table[cell]

            force = None
            for index, (_, x, _, _, rhs) in enumerate(rules):
                i, j = map(evaluate, rhs)
                if i is None or j is None:
                    continue
                value = table[8 * i + j]
                if value is not None:
                    if value != x:
                        return dict(forced=forced, fail=index)
                else:
                    force = (index, i, j, x)
                    break
            if force is None:
                break
            forced.append(force)
            try:
                assign(table, *force[1:])
            except OrbitConflict:
                return dict(forced=forced, orbit_conflict=True)
        if not needed:
            raise RuntimeError(f"Found a target model: {table}")
        cell = max(needed, key=needed.get)
        i, j = divmod(cell, 8)
        branches = []
        for value in range(8):
            child = table.copy()
            try:
                assign(child, i, j, value)
                branches.append(visit(child))
            except OrbitConflict:
                branches.append(dict(forced=[], orbit_conflict=True))
        return dict(forced=forced, split=cell, branches=branches)

    table = [None] * 64
    assign(table, 0, 0, 0)
    return visit(table)


def render(tree, rules):
    lines = [
        "import Mathlib.Data.Fin.VecNotation",
        "import equational_theories.WeakCentralGroupoids", "",
        "/-! Generated by `scripts/definability_idempotent_check.py`.",
        "Every branch is checked by ordinary Lean equation rewrites and finite case splits.",
        "There are no native evaluation or solver axioms. -/", "",
        "set_option maxHeartbeats 8000000", "set_option maxRecDepth 10000", "",
        "namespace Definability.Idempotent1485", "",
        "def cycle : Fin 8 → Fin 8 := ![1, 2, 0, 5, 4, 7, 6, 3]", "",
        "theorem refute (f : Fin 8 → Fin 8 → Fin 8)",
        "    (h : ∀ x y z, f (f y x) (f x (f z y)) = x)",
        "    (ha : ∀ x y, f (cycle x) (cycle y) = cycle (f x y))",
        "    (h00 : f 0 0 = 0) : False := by",
        "  have hd (x y z : Fin 8) : f (f (f y z) x) (f x y) = x := by",
        "    letI : WeakCentralGroupoid (Fin 8) := { op := f, eqn := h }",
        "    exact WeakCentralGroupoid.dual_eqn x y z",
        "  have split (x y : Fin 8) : f x y = 0 ∨ f x y = 1 ∨ f x y = 2 ∨ f x y = 3 ∨",
        "      f x y = 4 ∨ f x y = 5 ∨ f x y = 6 ∨ f x y = 7 :=",
        "    (by decide : ∀ z : Fin 8, z = 0 ∨ z = 1 ∨ z = 2 ∨ z = 3 ∨",
        "      z = 4 ∨ z = 5 ∨ z = 6 ∨ z = 7) (f x y)",
    ]
    serial = 0

    def fresh():
        nonlocal serial
        serial += 1
        return f"e{serial}"

    def add(context, i, j, value, name, indent):
        for _ in range(3):
            old = context.get((i, j))
            if old:
                if old[0] != value:
                    lines.append(indent + f"exact (by decide : ({old[0]} : Fin 8) ≠ {value}) "
                                 f"({old[1]}.symm.trans {name})")
                    return False
            else:
                context[i, j] = (value, name)
            ni, nj, nv = CYCLE[i], CYCLE[j], CYCLE[value]
            old = context.get((ni, nj))
            if old and old[0] == nv:
                return True
            new_name = fresh()
            lines.append(indent + f"have {new_name} : f {ni} {nj} = {nv} := "
                         f"(ha {i} {j}).trans (congrArg cycle {name})")
            i, j, value, name = ni, nj, nv, new_name
        return True

    def evaluate(term, context, used):
        if isinstance(term, int):
            return term
        i, j = (evaluate(child, context, used) for child in term)
        value, name = context[i, j]
        if name not in used:
            used.append(name)
        return value

    def emit(node, context, indent):
        for index, i, j, value in node["forced"]:
            lemma, x, y, z, rhs = rules[index]
            used = []
            assert evaluate(rhs[0], context, used) == i
            assert evaluate(rhs[1], context, used) == j
            name = fresh()
            lines.append(indent + f"have {name} : f {i} {j} = {value} := "
                         f"by simpa only [{', '.join(used)}] using {lemma} {x} {y} {z}")
            if not add(context, i, j, value, name, indent):
                return
        if "fail" in node:
            lemma, x, y, z, rhs = rules[node["fail"]]
            used = []
            value = evaluate(rhs, context, used)
            lines.append(indent + f"exact (by decide : ({value} : Fin 8) ≠ {x})")
            lines.append(indent + f"  (by simpa only [{', '.join(used)}] using {lemma} {x} {y} {z})")
            return
        assert "split" in node, "The orbit contradiction must have been emitted above"
        i, j = divmod(node["split"], 8)
        name = fresh()
        lines.append(indent + f"rcases split {i} {j} with " + " | ".join([name] * 8))
        for value, branch in enumerate(node["branches"]):
            start = len(lines)
            child = context.copy()
            if add(child, i, j, value, name, indent + "  "):
                emit(branch, child, indent + "  ")
            lines[start] = indent + "· " + lines[start].lstrip()

    context = {(0, 0): (0, "h00")}
    add(context, 0, 0, 0, "h00", "  ")
    emit(tree, context, "  ")
    lines += ["", "end Definability.Idempotent1485", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--write", action="store_true", help="write the generated Lean proof")
    modes.add_argument("--check", action="store_true", help="check the generated Lean proof is current")
    args = parser.parse_args()
    assert satisfies(*load_equations()[1482], sum(SOURCE, ()), 8)
    assert SOURCE[0][0] == 0
    assert all(SOURCE[CYCLE[x]][CYCLE[y]] == CYCLE[SOURCE[x][y]]
               for x, y in product(range(8), repeat=2))
    rules = make_rules()
    tree = search(rules)
    proof = render(tree, rules)
    if args.write:
        OUTPUT.write_text(proof)
    elif args.check and OUTPUT.read_text() != proof:
        raise SystemExit(f"Stale generated proof: {OUTPUT.relative_to(ROOT)}")

    def stats(node):
        children = [stats(child) for child in node.get("branches", [])]
        return (1 + sum(c[0] for c in children),
                int(bool(children)) + sum(c[1] for c in children),
                0 if not children else 1 + max(c[2] for c in children))

    nodes, splits, depth = stats(tree)
    print(f"Source and orbit checked; complete refutation: {nodes} nodes, "
          f"{splits} splits, maximum split depth {depth}.")
    print("Lean must check the generated proof before this counts as a theorem.")


if __name__ == "__main__":
    main()
