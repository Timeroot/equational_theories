#!/usr/bin/env python3
"""Generate checked squaring-map symmetry certificates for sizes four and five.

Python chooses relabelings, but Lean checks the conjugation of EVERY squaring
map. Neither the representative list nor the witness-index array is trusted.
"""

import argparse
import json
from itertools import permutations, product, combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASE_DATA = ROOT / "data/spectrum/bv_cases.json"
# Integrated exclusions, each checked by Lean; not inferred from a solver answer.
PROVED_CASES = ((474, 4), (1286, 5))


def search_cases(law, n):
    """Choose small unsatisfiable subsets; these are re-proved by bv_decide."""
    import z3
    from spectrum_generate import load_equations, variables
    lhs, rhs = load_equations()[law - 1]
    vs = sorted(variables(lhs) | variables(rhs))
    width = (n - 1).bit_length()
    output = []
    for diagonal in squaring_classes(n)[2]:
        cells = [[z3.BitVecVal(diagonal[i], width) if i == j else
                  z3.BitVec(f"t_{i}_{j}", width) for j in range(n)] for i in range(n)]
        def select(values, index):
            v = values[-1]
            for i in reversed(range(n - 1)):
                v = z3.If(index == i, values[i], v)
            return z3.simplify(v)
        def op(x, y):
            return select([select(row, y) for row in cells], x)
        def term(t, a):
            return z3.BitVecVal(a[t], width) if isinstance(t, str) else op(term(t[0], a), term(t[1], a))
        constraints = {}
        for i in range(n):
            for j in range(n):
                if n != 2 ** width and i != j:
                    constraints[f"b_{i}_{j}"] = z3.ULT(cells[i][j], n)
            for j, k in combinations(range(n), 2):
                constraints[f"i_{i}_{j}_{k}"] = cells[i][j] != cells[i][k]
            if law == 474:
                constraints[f"u_{i}"] = op(z3.BitVecVal(i, width), cells[i][i]) == i
        for values in product(range(n), repeat=len(vs)):
            assignment = dict(zip(vs, values))
            constraints["e_" + "_".join(map(str, values))] = term(lhs, assignment) == term(rhs, assignment)
        solver = z3.Solver()
        solver.set(timeout=1000)
        for name, expression in constraints.items():
            solver.add(z3.Implies(z3.Bool(name), expression))
        if solver.check(*map(z3.Bool, constraints)) != z3.unsat:
            raise RuntimeError(f"No refutation found for E{law}, n={n}, diagonal={diagonal}")
        core = [str(k) for k in solver.unsat_core()]
        for name in core.copy():
            if solver.check(*[z3.Bool(k) for k in core if k != name]) == z3.unsat:
                core = [str(k) for k in solver.unsat_core()]
        output.append({"diagonal": list(diagonal), "constraints": sorted(core)})
        print(f"E{law}, size {n}: selected core {len(output)} with {len(core)} constraints", flush=True)
    return output


def squaring_classes(n):
    perms = list(permutations(range(n)))
    inverses = [tuple(p.index(x) for x in range(n)) for p in perms]
    representatives, witnesses = set(), [0] * (n ** n)
    for s in product(range(n), repeat=n):
        conjugates = [tuple(p[s[q[x]]] for x in range(n)) for p, q in zip(perms, inverses)]
        canonical = min(conjugates)
        representatives.add(canonical)
        witnesses[sum(s[i] * n ** i for i in range(n))] = conjugates.index(canonical)
    return perms, inverses, sorted(representatives), witnesses


def vec(xs):
    return "![" + ", ".join(map(str, xs)) + "]"


def symmetry_source():
    lines = ["import equational_theories.Spectrum.Symmetry", "import Mathlib.Tactic.FinCases", "",
        "/-! Generated by scripts/spectrum_bv.py. All relabeling witnesses are checked",
        "by Lean; the arrays are certificates, not assumptions. -/", "",
        "namespace Spectrum.Symmetry", ""]
    for n in [4, 5]:
        perms, inverses, reps, witnesses = squaring_classes(n)
        assert len(reps) == {4: 19, 5: 47}[n]
        lines += [f"def diagonals{n} : List (Fin {n} → Fin {n}) := [",
                  ",\n".join("  " + vec(r) for r in reps) + "]", "",
                  f"private def relabelings{n} : Array (Equiv.Perm (Fin {n})) := #["]
        lines += [",\n".join(f"  {{ toFun := {vec(p)}, invFun := {vec(q)},\n"
                  "    left_inv := by decide, right_inv := by decide }" for p, q in zip(perms, inverses)) + "]", "",
                  f"private def witness{n} : Array Nat := #["]
        lines += [",\n".join("  " + ", ".join(map(str, witnesses[i:i+25]))
                  for i in range(0, len(witnesses), 25)) + "]", "",
                  f"private def relabel{n} (s : Fin {n} → Fin {n}) : Equiv.Perm (Fin {n}) :=",
                  f"  relabelings{n}[witness{n}[" + " + ".join(f"{n**i} * (s {i}).val" for i in range(n)) +
                  "]!]!", ""]
        args = " ".join(f"a{i}" for i in range(n))
        svec = vec([f"a{i}" for i in range(n)])
        lines += ["@[spectrum_native]", f"theorem checked{n} : ∀ {args} : Fin {n},",
                  f"    conjugate (relabel{n} {svec}) {svec} ∈ diagonals{n} := by native_decide", "",
                  f"theorem covers{n} : Covers {n} diagonals{n} := by",
                  "  intro s", f"  refine ⟨relabel{n} s, ?_⟩",
                  f"  have hs : s = {vec([f's {i}' for i in range(n)])} := by",
                  "    funext x; fin_cases x <;> rfl", "  rw [hs]",
                  f"  exact checked{n} " + " ".join(f"(s {i})" for i in range(n)),
                  f"spectrum_assert covers{n} complete", ""]
    return "\n".join(lines + ["end Spectrum.Symmetry", ""])


def cases_source(law, n, cases):
    from spectrum_generate import load_equations, variables
    lhs, rhs = load_equations()[law - 1]
    vs = sorted(variables(lhs) | variables(rhs))
    assert [c["diagonal"] for c in cases] == [list(d) for d in squaring_classes(n)[2]]
    width, row_width = (n - 1).bit_length(), n * (n - 1).bit_length()
    args = " ".join("abcde"[:n])
    lines = ["import equational_theories.Spectrum.Generated.Squaring",
        "import equational_theories.Spectrum.SmallOrderLemmas", "",
        "/-! Generated by scripts/spectrum_bv.py. Each core is independently proved",
        "by bv_decide, then lifted to a magma using checked encoding lemmas.",
        "The 1-second timeout bounds SAT solving, not total Lean elaboration. -/", "",
        "set_option maxHeartbeats 4000000", "open Law Law.MagmaLaw Spectrum.BitTables",
        "namespace Spectrum.BitExclusion", ""]
    for index, case in enumerate(cases):
        diagonal, core = case["diagonal"], case["constraints"]
        label = f"{law}_{n}_{index}"
        diag = f"diagonal_{label}"
        pieces = "".join(f"if x = {i} then {v} else " for i, v in enumerate(diagonal[:-1])) + str(diagonal[-1])
        lines += [f"def {diag} (x : BitVec {width}) : BitVec {width} := {pieces}", ""]
        def term(t, assignment, lifted=False):
            if isinstance(t, str):
                v = assignment[t]
                return f"(bv{n} ({v} : Fin {n}))" if lifted else str(v)
            op = f"encoded{n} M {diag}" if lifted else f"op{n} {diag} {args}"
            return f"({op} {term(t[0], assignment, lifted)} {term(t[1], assignment, lifted)})"
        def op(i, j):
            return f"op{n} {diag} {args} {i} {j}"
        constraints = []
        for item in core:
            kind, *values = item.split("_")
            values = list(map(int, values))
            if kind == "e":
                a = dict(zip(vs, values))
                constraints.append(f"({term(lhs, a)} : BitVec {width}) = {term(rhs, a)}")
            elif kind == "i":
                i, j, k = values
                constraints.append(f"{op(i, j)} ≠ {op(i, k)}")
            elif kind == "u":
                i, = values
                constraints.append(f"{op(i, '(' + op(i, i) + ')')} = {i}")
            elif kind == "b":
                i, j = values
                constraints.append(f"{op(i, j)} < {n}")
            else:
                raise ValueError(item)
        lines += [f"def test_{label} ({args} : BitVec {row_width}) : Prop :=",
                  "  " + " ∧\n  ".join(constraints), "",
                  "@[spectrum_native]", f"theorem refute_{label} ({args} : BitVec {row_width}) : ¬ test_{label} {args} := by",
                  f"  unfold test_{label} op{n} {diag}" + (" clip5" if n == 5 else ""),
                  "  bv_decide (config := { timeout := 1, embeddedConstraintSubst := false })",
                  f"spectrum_assert refute_{label} complete", "",
                  f"theorem case_{label} (M : Magma (Fin {n})) (h : @Equation{law} (Fin {n}) M)",
                  f"    (hs : (fun x => M.op x x) = {vec(diagonal)}) : False := by",
                  f"  have hd (x : Fin {n}) : {diag} (bv{n} x) = bv{n} (M.op x x) := by",
                  f"    rw [show M.op x x = {vec(diagonal)} x from congrFun hs x]",
                  "    fin_cases x <;> rfl",
                  f"  have he := encoded{n}_eq M {diag} hd",
                  f"  apply refute_{label} " + " ".join(f"(rows{n} M {i})" for i in range(n)),
                  f"  unfold test_{label}"]
        if len(core) > 1:
            lines += ["  refine ⟨" + ", ".join("?_" for _ in core) + "⟩"]
        for item in core:
            kind, *values = item.split("_")
            values = list(map(int, values))
            statements = []
            def bop(i, j):
                return f"encoded{n} M {diag} (bv{n} ({i} : Fin {n})) (bv{n} ({j} : Fin {n}))"
            if kind == "e":
                a = dict(zip(vs, values))
                statements += [f"change {term(lhs, a, True)} = {term(rhs, a, True)}",
                               "simp only [he]",
                               f"exact congrArg bv{n} (h " + " ".join(map(str, values)) + ")"]
            elif kind == "i":
                i, j, k = values
                statements += [f"change {bop(i, j)} ≠ {bop(i, k)}", "simp only [he]", "intro hc",
                    f"exact (by decide : ({j} : Fin {n}) ≠ {k}) (left_injective_{law} M h {i} (bv{n}_injective hc))"]
            elif kind == "u":
                assert law == 474
                i, = values
                statements += [f"change encoded{n} M {diag} (bv{n} ({i} : Fin {n})) ({bop(i, i)}) = bv{n} ({i} : Fin {n})",
                               "simp only [he]", f"exact congrArg bv{n} (unary_474 M h {i})"]
            else:
                assert n == 5
                i, j = values
                statements += [f"change {bop(i, j)} < {n}", "rw [he]",
                               f"exact (by decide : ∀ z : Fin 5, bv5 z < 5) (M.op {i} {j})"]
            prefix = "  · " if len(core) > 1 else "  "
            lines += [prefix + statements[0]] + [("    " if len(core) > 1 else "  ") + s for s in statements[1:]]
        lines.append("")
    lines += [f"theorem not_order_{law}_{n} : ¬ Law{law}.HasModel {n} := by",
              "  intro hL", f"  obtain ⟨M, hM, hd⟩ := Symmetry.canonical_model Symmetry.covers{n} Law{law} hL",
              f"  have h := (@Law{law}.models_iff (Fin {n}) M).mp hM",
              f"  simp only [Symmetry.diagonals{n}, List.mem_cons, List.not_mem_nil, or_false] at hd",
              "  rcases hd with " + " | ".join(f"h{i}" for i in range(len(cases)))]
    lines += [f"  · exact case_{law}_{n}_{i} M h h{i}" for i in range(len(cases))]
    lines += [f"spectrum_assert not_order_{law}_{n} complete", "", "end Spectrum.BitExclusion", ""]
    return "\n".join(lines)


def certificate_files():
    """All BV certificates, also regenerated by the main spectrum generator."""
    cases_by_key = json.loads(CASE_DATA.read_text())
    expected = {f"{law}:{n}" for law, n in PROVED_CASES}
    if set(cases_by_key) != expected:
        raise ValueError(f"BV case cache must contain exactly {sorted(expected)}")
    output = ROOT / "equational_theories/Spectrum/Generated"
    files = {output / "Squaring.lean": symmetry_source()}
    for law, n in PROVED_CASES:
        files[output / f"BV{law}_{n}.lean"] = cases_source(law, n, cases_by_key[f"{law}:{n}"])
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--search", action="store_true", help="select new cores with Z3 and regenerate")
    args = parser.parse_args()
    if args.search:
        cases = {f"{law}:{n}": search_cases(law, n) for law, n in PROVED_CASES}
        CASE_DATA.write_text(json.dumps(cases, indent=2) + "\n")
    for path, content in certificate_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        elif not path.exists() or path.read_text() != content:
            path.write_text(content)
    if args.check:
        print("Squaring-map and bit-vector certificates are current.")


if __name__ == "__main__":
    main()
