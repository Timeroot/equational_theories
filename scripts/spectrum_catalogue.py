"""Generate the complete, proof-status-aware transcription of the spectrum note."""
import json
import re
from collections import Counter
from spectrum_bv import PROVED_CASES
from spectrum_note import (EXACT, ALIASES, EQUALITIES, FINITE, FAMILIES, EXCLUDED,
                           COFINITE, DISPUTED_COFINITE, CONJECTURES, NOTES, lean_set, lower)


def catalogue(root, records, emit, seeds, routes):
    cache = json.loads((root / "data/spectrum/witnesses.json").read_text())
    # Provenance categories live beside the actual Lean obligations, not in JSON.
    pending_kinds = dict(re.findall(r'^spectrum_pending (\w+) (\w+)',
        (root / "equational_theories/Spectrum/NotePending.lean").read_text(), re.M))
    kind_status = {"complete": "PROVED", "proofAvailable": "PROOF_AVAILABLE", "noteGap": "NOTE_GAP"}
    status_kind = {v: k for k, v in kind_status.items()}
    def evidence(names):
        kinds = [pending_kinds.get(name, "proofAvailable") for name in names]
        return kind_status["noteGap" if "noteGap" in kinds else "proofAvailable" if kinds else "complete"]
    exact_pending = {167: ["models_167", "orders_167"],
        895: ["orders_895"], 898: ["orders_898"]}
    family_pending = {115: "mendelsohn_115", 467: "odd_sums_467", 481: "loops_481",
        873: "mendelsohn_115", 667: "loops_667", 883: "loops_883",
        1486: "shifted_squares_1486", 1719: "mendelsohn_1719"}
    output = root / "equational_theories/Spectrum/Generated"
    witness_lines = ["import equational_theories.Spectrum.Generated.Modular",
                     "import equational_theories.Spectrum.Generated.CentralWitnesses",
                     "import equational_theories.Spectrum.Exact", "import Mathlib.Data.Fin.VecNotation", "",
                     "/-! Concrete witnesses selected by linear search, existing tables, or Z3.",
                     "All tables and equations are rechecked by the Lean kernel. -/", "",
                     "set_option maxRecDepth 16384", "set_option maxHeartbeats 4000000", "",
                     "open Law Law.MagmaLaw", "namespace Spectrum.NoteWitness", ""]
    central_lines = ["import equational_theories.Spectrum.Basic",
                     "import equational_theories.Equations.All", "import Mathlib.Data.Fin.VecNotation", "",
                     "/-! E1486 tables supplied by Matthew Bolan, 2024-11-25:",
                     "https://leanprover-community.github.io/archive/stream/458659-Equational/topic/Austin.20pairs.html#484348920",
                     "and #484345673 (order 21). Generated from data/spectrum/witnesses.json;",
                     "every identity is checked by kernel reduction, not trusted input.",
                     "Separated from the full note catalogue so definability proofs import only their witnesses. -/", "",
                     "set_option maxRecDepth 16384", "set_option maxHeartbeats 4000000", "",
                     "open Law Law.MagmaLaw", "namespace Spectrum.NoteWitness", ""]
    pending = ["import equational_theories.Spectrum.Shapes", "import equational_theories.Spectrum.Status",
               "import equational_theories.Equations.All", "",
               "/-! Explicit remaining finite proof obligations from the note. These are NOT",
               "search-based exclusions: `sorry` records the missing certificate/model.",
               "Generated by spectrum_generate.py; add witnesses to data/spectrum/witnesses.json",
               "or extend the certificate generator to discharge these obligations. -/", "",
               "namespace Spectrum.Pending", ""]
    positive_proofs, negative_proofs = {}, {}
    gaps = []
    for i, sizes in FINITE.items():
        for n in sizes:
            key = f"{i}:{n}"
            if n == 1:
                proof = f"Law{i}.hasModel_one"
            elif n == 2:
                proof = f"two_{i}"
            elif n in records[i - 1]["explicit_orders"]:
                proof = f"model_{i}_{n}"
            elif i in [1480, 1483, 1486] and int(n ** 0.5) ** 2 == n:
                proof = f"square_{i} {int(n ** 0.5)}"
            elif key in cache:
                table = cache[key]
                assert len(table) == n * n and all(0 <= x < n for x in table)
                rows = ["![" + ", ".join(map(str, table[k:k+n])) + "]" for k in range(0, n*n, n)]
                destination = central_lines if i == 1486 else witness_lines
                destination += ["@[implicit_reducible]", f"def table_{i}_{n} : Magma (Fin {n}) :=",
                                  "  ⟨fun x y => ![" + ",\n    ".join(rows) + "] x y⟩", "",
                                  f"theorem model_{i}_{n} : Law{i}.HasModel {n} :=",
                                  f"  ⟨table_{i}_{n}, (@Law{i}.models_iff (Fin {n}) table_{i}_{n}).mpr (by decide)⟩", ""]
                proof = f"NoteWitness.model_{i}_{n}"
            else:
                name = f"model_{i}_{n}"
                pending += [f"/-- Finite witness asserted in §3, not yet formalized. -/",
                            f"theorem {name} : Law{i}.HasModel {n} := by sorry",
                            f'spectrum_pending {name} proofAvailable "§3.1 finite lower bounds"',
                            '  "The note reports a model; its multiplication table is not bundled here. Recover a witness and check it in Lean."', ""]
                gaps.append(f"Spectrum.Pending.{name}")
                proof = f"Pending.{name}"
            positive_proofs[i, n] = proof
    neg_lines = ["import equational_theories.Spectrum.Generated.SmallOrder", "",
                 "/-! Compatibility names for the note's initial-segment exclusions. -/", "",
                 "namespace Spectrum.NoteExclusion", ""]
    for i, sizes in EXCLUDED.items():
        for n in sizes:
            if n in [2, 3] and records[i - 1]["excluded_orders"] == [n]:
                proof = f"not_{'two' if n == 2 else 'three'}_{i}"
            elif (i, n) == (1480, 3):
                proof = "not_order_1480_3"
            elif n == 3:
                neg_lines += [f"theorem not_three_{i} : ¬ Law{i}.HasModel 3 := not_order_{i}_3", ""]
                proof = f"NoteExclusion.not_three_{i}"
            else:
                b = routes[i, n]
                name = f"not_order_{b}_{n}"
                if (b, n) in PROVED_CASES or (b, n) in {(1485, 11), (1485, 13)}:
                    proof = f"(NegativeTransfer.route_{i}_{n}).not_hasModel {name}"
                elif name in pending_kinds:
                    proof = f"(NegativeTransfer.route_{i}_{n}).not_hasModel Pending.{name}"
                else:
                    if f"Spectrum.Pending.{name}" not in gaps:
                        pending += ["/-- Low-order exclusion reported in §3; the finite refutation is outstanding. -/",
                                    f"theorem {name} : ¬ Law{b}.HasModel {n} := by sorry",
                                    f'spectrum_pending {name} proofAvailable "§3.1 finite exclusions"',
                                    '  "The note reports a finite exclusion, but no replayable refutation is bundled here. Reconstruct an argument or obtain and check an ATP/SAT certificate."', ""]
                        gaps.append(f"Spectrum.Pending.{name}")
                    proof = f"(NegativeTransfer.route_{i}_{n}).not_hasModel Pending.{name}"
            negative_proofs[i, n] = proof
    witness_lines += ["end Spectrum.NoteWitness", ""]
    central_lines += ["end Spectrum.NoteWitness", ""]
    pending += ["end Spectrum.Pending", ""]
    neg_lines += ["end Spectrum.NoteExclusion", ""]
    emit(output / "NoteWitnesses.lean", "\n".join(witness_lines))
    emit(output / "CentralWitnesses.lean", "\n".join(central_lines))
    emit(output / "NoteObligations.lean", "\n".join(pending))
    emit(output / "NoteExclusions.lean", "\n".join(neg_lines))

    bounds = ["import equational_theories.Spectrum.Note", "import equational_theories.Spectrum.Generated",
              "import equational_theories.Spectrum.WeakCentralCardinality",
              "import equational_theories.Spectrum.Generated.NoteWitnesses",
              "import equational_theories.Spectrum.Generated.NoteObligations",
              "import equational_theories.Spectrum.Generated.NoteExclusions", "",
              "/-! Every lower bound, initial segment, and undisputed cofinite claim of §3.",
              "UNKNOWN exact spectra are intentionally represented by bounds, not equalities.",
              "Some statements depend on the explicitly named Pending obligations. -/", "",
              "open Law Law.MagmaLaw", "namespace Spectrum.Note", ""]
    for i, sizes in FINITE.items():
        status_comment = (f"-- Historical note bounds; the exact spectrum of E{i} is now proved."
                          if i in EXACT else
                          f"-- UNKNOWN: the exact spectrum of E{i} is not established in the note.")
        bounds += [status_comment,
                   f"theorem finite_{i} : ({lean_set(sizes)} : Set ℕ) ⊆ Law{i}.spectrum := by",
                   "  intro n hn", "  simp only [" +
                   ("Set.mem_insert_iff, " if len(sizes) > 1 else "") + "Set.mem_singleton_iff] at hn"]
        if len(sizes) == 1:
            bounds += ["  subst n", f"  exact ⟨by decide, {positive_proofs[i, 1]}⟩"]
        else:
            bounds += ["  rcases hn with " + " | ".join(["rfl"] * len(sizes))]
            bounds += [f"  · exact ⟨by decide, {positive_proofs[i, n]}⟩" for n in sizes]
        bounds.append("")
        if i in FAMILIES:
            bounds += [f"theorem family_{i} : ({FAMILIES[i]}) ⊆ Law{i}.spectrum := by"]
            if i in [115, 467, 481]:
                name = {115: "mendelsohn_115", 467: "odd_sums_467", 481: "loops_481"}[i]
                bounds += [f"  exact Pending.{name}"]
            elif i == 873:
                bounds += ["  exact Set.Subset.trans Pending.mendelsohn_115 ImplicationTransfer.path_115_873"]
            elif i in [667, 883, 1719]:
                exceptional = 6 if i == 1719 else 7
                base = f"Pending.mendelsohn_{i}" if i == 1719 else f"Pending.loops_{i}"
                bounds += ["  intro n hn", f"  by_cases he : n = {exceptional}",
                           f"  · subst n; exact ⟨by decide, {positive_proofs[i, exceptional]}⟩",
                           f"  · apply {base}", "    exact ⟨hn.1, hn.2.1, by simpa using he⟩"]
            elif i in [1480, 1483]:
                bounds += ["  rintro n ⟨hn, k, rfl⟩", f"  exact ⟨hn, square_{i} k⟩"]
            elif i == 1485:
                bounds += ["  rintro n (⟨hn, k, rfl⟩ | ⟨hn, k, rfl⟩)",
                           "  · exact ⟨hn, square_1485 k⟩", "  · exact ⟨hn, twice_square_1485 k⟩"]
            elif i == 1486:
                bounds += ["  apply Set.union_subset", "  · rintro n ⟨hn, k, rfl⟩",
                           "    exact ⟨hn, square_1486 k⟩", "  · exact Pending.shifted_squares_1486"]
            else:
                raise AssertionError(i)
            bounds += ["", f"theorem lower_{i} : ({lower(i)}) ⊆ Law{i}.spectrum :=",
                       f"  Set.union_subset finite_{i} family_{i}", ""]
        else:
            bounds += [f"theorem lower_{i} : ({lower(i)}) ⊆ Law{i}.spectrum := finite_{i}", ""]
        excluded = EXCLUDED[i]
        bounds += [f"theorem upper_{i} : Law{i}.spectrum ⊆ positiveExcept {lean_set(excluded)} := by",
                   "  intro n hn", "  refine ⟨hn.1, ?_⟩", "  intro he",
                   "  simp only [" + ("Finset.mem_insert, " if len(excluded) > 1 else "") + "Finset.mem_singleton] at he"]
        if len(excluded) == 1:
            bounds += ["  subst n", f"  exact {negative_proofs[i, excluded[0]]} hn.2"]
        else:
            bounds += ["  rcases he with " + " | ".join(["rfl"] * len(excluded))]
            bounds += [f"  · exact {negative_proofs[i, n]} hn.2" for n in excluded]
        bounds.append("")
        if i in COFINITE:
            bounds += [f"theorem cofinite_{i} : CofiniteSpectrum Law{i} := Pending.cofinite_{i}", ""]
    for i, base in ALIASES.items():
        if i in EXACT:
            continue
        bounds += [f"-- UNKNOWN exact spectrum; transferred from E{base}.",
                   f"theorem lower_{i} : ({lower(base)}) ⊆ Law{i}.spectrum := by",
                   f"  rw [{EQUALITIES[i]}]", f"  exact lower_{base}", "",
                   f"theorem upper_{i} : Law{i}.spectrum ⊆ positiveExcept {lean_set(EXCLUDED[base])} := by",
                   f"  rw [{EQUALITIES[i]}]", f"  exact upper_{base}", ""]
        if base in COFINITE:
            bounds += [f"theorem cofinite_{i} : CofiniteSpectrum Law{i} := by",
                       f"  unfold CofiniteSpectrum", f"  rw [{EQUALITIES[i]}]", f"  exact cofinite_{base}", ""]
    bounds += ["end Spectrum.Note", ""]
    emit(output / "NoteBounds.lean", "\n".join(bounds))

    lines = ["import equational_theories.Spectrum.Generated.NoteBounds", "",
             "/-!", "# Spectrum catalogue: coverage, evidence, and proof organization", "",
             "All E1–E4694 are covered. An exact formula stated in the note is NOT necessarily",
             "a completed proof here. Each theorem is followed by a `spectrum_assert` that",
             "checks its actual transitive dependencies (not a generator's claim):", "",
             "* `complete`: no sorry or undocumented axioms. Standard Lean axioms are allowed;",
             "  native_decide/bv_decide axioms require an explicitly tagged owner theorem.",
             "* `proofAvailable`: a mathematical argument, cited theorem, or reported finite",
             "  ATP/model result exists, but its proof is not integrated here. This does",
             "  NOT mean a replayable ATP certificate is currently available in this repo.",
             "* `noteGap`: at least one essential step is elided/unclear in the note and has",
             "  not been reconstructed. This is not a claim that the spectrum is open.",
             "* `openProblems`: exact spectra still UNKNOWN after the recorded supplements.",
             "  These have bounds, never an exact theorem (not even one using sorry).",
             "* `sourceConflicts`: contradictory source claims, not silently promoted to proofs.", "",
             "To see the exact missing steps and source sections for any declaration:",
             "`#spectrum_status Spectrum.Catalogue.exact_546`", "",
             "Proof layers:",
             "1. Basic/Definability/Linear/Constructions/Exact/Transfer: reusable mathematics.",
             "2. Generated.Linear*, Modular, Two, NoteWitnesses: checked positive witnesses.",
             "3. Generated.SmallOrder: native enumeration only at an exclusion basis;",
             "   NegativeTransfer: proved implication/duality/definability routes to that basis.",
             "   SmallExclusions: checked BV exclusions for E474 at size 4 and E1286 at size 5;",
             "   Squaring/Symmetry/BitTables: complete relabeling and magma-to-BV bridges.",
             "4. NotePending and Generated.NoteObligations: the ONLY sorry boundaries, each",
             "   annotated with evidence, source, and the precise missing formalization.",
             "5. Note/Generated.NoteBounds: assemble formulas; this file transfers them to all laws.", "",
             "Data is deliberately not a proof oracle: data/spectrum/witnesses.json and",
             "bv_cases.json are INPUT (candidate tables and SAT-core selections rechecked",
             "in Lean); catalogue.json is GENERATED OUTPUT. The integrated BV proofs and",
             "their total compilation timings are documented in docs/spectrum_bv.md.",
             "There is no separate JSON list of obligations: their provenance lives in Lean.",
             "See docs/spectrum_status.md and scripts/check_spectrum.lean for the full audit.", "-/", "",
             "open Law Law.MagmaLaw", "namespace Spectrum.Catalogue", ""]
    for record in records:
        i = record["equation"]
        rep = record.get("pdf_representative")
        base = ALIASES.get(rep, rep)
        record["mathematical_status"] = "EXACT" if record["full_spectrum"] or rep in EXACT else "UNKNOWN"
        record["conjectured_spectrum_formula"] = CONJECTURES.get(base)
        record["pdf_notes"] = NOTES.get(base)
        if record["mathematical_status"] == "EXACT":
            formula = "{n : ℕ | 0 < n}" if record["full_spectrum"] else EXACT[rep]
            if record["full_spectrum"]:
                proof = f"(hasFullSpectrum_iff_spectrum).mp full_{i}"
            elif rep == 2:
                proof = f"ImplicationTransfer.singleton_{i}"
            else:
                proof = f"ImplicationTransfer.spectrum_{i}_eq_{rep} |>.trans Note.exact_{rep}"
            proof_status = evidence(exact_pending.get(rep, []))
            lines += [f"theorem exact_{i} : Law{i}.spectrum = ({formula}) :=", f"  {proof}",
                      f"spectrum_assert exact_{i} {status_kind[proof_status]}", ""]
            record.update(exact_spectrum_formula=formula,
                          exact_spectrum_theorem=f"Spectrum.Catalogue.exact_{i}",
                          exact_proof_status=proof_status)
            if not record["full_spectrum"] and rep != 2:
                record["exact_spectrum"] = formula
        else:
            low, upper = lower(base), f"positiveExcept {lean_set(EXCLUDED[base])}"
            eq = f"ImplicationTransfer.spectrum_{i}_eq_{rep}"
            lower_pending = [positive_proofs[base, n].removeprefix("Pending.") for n in FINITE[base]
                             if positive_proofs[base, n].startswith("Pending.")]
            if base in family_pending:
                lower_pending.append(family_pending[base])
            upper_pending = [re.search(r'Pending\.(\w+)', negative_proofs[base, n])[1]
                             for n in EXCLUDED[base] if "Pending." in negative_proofs[base, n]]
            low_status, up_status = evidence(lower_pending), evidence(upper_pending)
            lines += [f"-- UNKNOWN exact spectrum (PDF representative E{rep}).",
                      f"theorem lower_{i} : ({low}) ⊆ Law{i}.spectrum := by",
                      f"  rw [{eq}]", f"  exact Note.lower_{rep}",
                      f"spectrum_assert lower_{i} {status_kind[low_status]}", "",
                      f"theorem upper_{i} : Law{i}.spectrum ⊆ ({upper}) := by",
                      f"  rw [{eq}]", f"  exact Note.upper_{rep}",
                      f"spectrum_assert upper_{i} {status_kind[up_status]}", ""]
            record.update(exact_spectrum="UNKNOWN", exact_spectrum_formula=None,
                          exact_spectrum_theorem=None, exact_proof_status="UNKNOWN",
                          lower_bound_formula=low, lower_bound_theorem=f"Spectrum.Catalogue.lower_{i}",
                          upper_bound_formula=upper, upper_bound_theorem=f"Spectrum.Catalogue.upper_{i}",
                          lower_bound_proof_status=low_status, upper_bound_proof_status=up_status,
                          pdf_explicit_orders=FINITE[base], pdf_excluded_orders=EXCLUDED[base],
                          cofinite_status="KNOWN" if base in COFINITE else "DISPUTED" if base in DISPUTED_COFINITE else "UNKNOWN")
            if base in COFINITE:
                cofinite_status = evidence([f"cofinite_{base}"])
                lines += [f"theorem cofinite_{i} : CofiniteSpectrum Law{i} := by",
                          "  unfold CofiniteSpectrum", f"  rw [{eq}]", f"  exact Note.cofinite_{rep}",
                          f"spectrum_assert cofinite_{i} {status_kind[cofinite_status]}", ""]
                record["cofinite_theorem"] = f"Spectrum.Catalogue.cofinite_{i}"
                record["cofinite_proof_status"] = cofinite_status
    lines += ["/-- Exact spectra still open after recorded supplements; independent of bound proofs. -/",
              "def openProblems : List Status.OpenIssue := ["]
    opened = [r for r in records if r["mathematical_status"] == "UNKNOWN"]
    lines += [f'  ⟨{r["equation"]}, .mathematicallyOpen, "Exact spectrum still UNKNOWN; note representative E{r["pdf_representative"]}."⟩' +
              ("," if k + 1 < len(opened) else "]") for k, r in enumerate(opened)]
    lines += ["", "/-- E1313's cofiniteness is asserted in §3.8 but left open in §3.1. -/",
              "def sourceConflicts : List Status.OpenIssue := [",
              '  ⟨1313, .sourceConflict, "Cofiniteness: §3.1 UNKNOWN versus §3.8 affirmative. No cofinite theorem asserted."⟩]', "",
              f"#guard openProblems.length == {len(opened)}", ""]
    lines += ["end Spectrum.Catalogue", ""]
    emit(root / "equational_theories/Spectrum/Catalogue.lean", "\n".join(lines))
    print("Complete note coverage:", dict(Counter(r["mathematical_status"] for r in records)))
    print("Exact proof status:", dict(Counter(r["exact_proof_status"] for r in records)))
    print("Remaining finite proof obligations:", len(gaps))

    doc = ["# Spectrum-note catalogue", "", "Generated from `scripts/spectrum_note.py`; all orders below are positive.",
           "The formulas are Lean-readable: `residues m R X` means residue in R modulo m, excluding X;",
           "`positiveExcept X` means all positive integers except X. The square-set definitions are in",
           "`Spectrum/Shapes.lean`. **A formula stated in the note is not necessarily a completed proof.**", "",
           "Proof codes (checked against Lean dependencies): PROVED = complete; PROOF_AVAILABLE =",
           "argument/citation/reported ATP result awaiting Lean; NOTE_GAP = a missing step in the note",
           "has not been reconstructed; UNKNOWN = the exact spectrum is left mathematically open.",
           "Reported ATP results do not imply that a certificate is bundled here.", "",
           "| Representative | Exact spectrum / UNKNOWN lower bound | Conjecture | Cofinite claim | Exact proof |",
           "| --- | --- | --- | --- | --- |"]
    from spectrum_generate import REPRESENTATIVES
    for rep in REPRESENTATIVES:
        record, base = records[rep - 1], ALIASES.get(rep, rep)
        formula = EXACT[rep] if rep in EXACT else "UNKNOWN; contains " + lower(base)
        doc.append(f"| {rep} | `{formula}` | `{CONJECTURES.get(base, '—')}` | "
                   f"{record.get('cofinite_status', '—')} | {record['exact_proof_status']} |")
    doc += ["", "## Draft ambiguities", ""]
    doc += [f"- E{i}: {note}" for i, note in NOTES.items()]
    doc += ["", "The JSON index covers all 4694 laws, not just these representatives. Every non-full law",
            "has a Lean-checked spectrum equality with its representative (or a singleton proof).",
            "Question-marked source claims require an independent proof before an exact theorem is emitted.", ""]
    emit(root / "docs/spectrum_catalogue.md", "\n".join(doc))
