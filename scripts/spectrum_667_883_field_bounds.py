#!/usr/bin/env python3
"""Supplement the checked E667/E883 bounds with finite-field transversal designs.

The original finite basis and arithmetic certificate are kept intact. These
small additional Lean modules prove every supplemental construction and the
new finite coverage calculation; Python is not trusted by either proof.
"""
import argparse
from math import gcd, isqrt
from pathlib import Path

from spectrum_63_idempotent_bounds import closure, CUTOFF, ORDINARY_EXCEPTIONS
from spectrum_667_883_bounds import positive_recipes

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'equational_theories/Spectrum'


def prime(n):
    return n > 1 and all(n % d for d in range(2, isqrt(n) + 1))


def constructions():
    old = closure(CUTOFF)
    designs = {q: ('cyclic', q) for q in range(1, CUTOFF) if gcd(q, 60) == 1}
    designs[36] = ('existing', 36)
    for p in range(2, CUTOFF):
        if not prime(p):
            continue
        q, e = p, 1
        while q < CUTOFF:
            if q >= 7 and q not in designs:
                designs[q] = ('field', p, e)
            q, e = q * p, e + 1
    for q in range(2, CUTOFF):
        if q not in designs:
            for a in range(2, isqrt(q) + 1):
                if q % a == 0 and a in designs and q // a in designs:
                    designs[q] = ('product', a, q // a)
                    break

    known = {n: ('old', n) for n in old}
    for n in range(2, CUTOFF):
        if n in known:
            continue
        for k in range(2, isqrt(n) + 1):
            if n % k == 0 and k in known and n // k in known:
                known[n] = ('prod', k, n // k)
                break
        if n in known:
            continue
        for k in range(2, isqrt(n - 1) + 1):
            if (n - 1) % k == 0:
                for a in (k, (n - 1) // k):
                    q = (n - 1) // a + 1
                    if a in known and q in known and q - 1 not in ORDINARY_EXCEPTIONS:
                        known[n] = ('singular', a, q)
                        break
            if n in known:
                break
        if n in known:
            continue
        for q in range((n + 7) // 8, n // 7 + 1):
            r = n - 7 * q
            if q in designs and q in known and r in known:
                known[n] = ('seven', q, r)
                break
    return old, designs, known


def finset(values):
    return '{' + ', '.join(map(str, values)) + '}'


def generate():
    old, designs, known = constructions()
    new = sorted(known.keys() - old.keys())
    cutoff = max(set(range(CUTOFF)) - known.keys()) + 1

    def td(q):
        tag, *args = designs[q]
        if tag == 'field':
            p, e = args
        elif tag == 'cyclic' and prime(q):
            p, e = q, 1
        elif tag == 'product':
            return f'({td(args[0])}.mul {td(args[1])})'
        else:
            raise AssertionError(('Unused design needs a proof recipe', q, designs[q]))
        return f'(prime_power_td (p := {p}) (e := {e}) (by decide) (by decide) (by decide))'

    def ref(n):
        if n in old:
            return f'(IdempotentFiniteBasis.model_of_bit (n := {n}) (by decide))'
        return f'c{n}'

    def proof(n):
        tag, *args = known[n]
        if tag == 'prod':
            return f'{ref(args[0])}.mul {ref(args[1])}'
        if tag == 'singular':
            a, q = args
            return (f'singular_idempotent_model {ref(a)} {ref(q)} '
                    '(FiniteBasis.model (by decide) (by decide))')
        if tag == 'seven':
            q, r = args
            if gcd(q, 60) == 1:
                return (f'seven_idempotent (by decide) (by decide) (by decide) '
                        f'{ref(q)} {ref(r)}')
            if q == 36:
                return f'Design36.design.idempotent_models (by decide) {ref(q)} {ref(r)} idem7 idem8'
            return f'{td(q)}.idempotent_models (by decide) {ref(q)} {ref(r)}'
        raise AssertionError((n, known[n]))

    lines = [
        'import equational_theories.Spectrum.Equation63.FieldDesign',
        'import equational_theories.Spectrum.Equation63.IdempotentBitmap',
        '',
        '/-! Generated by scripts/spectrum_667_883_field_bounds.py.',
        'Finite-field designs supplement the existing constructive basis. -/',
        'set_option maxRecDepth 65536',
        'set_option maxHeartbeats 0',
        'namespace Spectrum.E63.FieldBounds',
        '',
        'def extraOrders : Finset ℕ := ' + finset(new),
        '',
    ]
    for n in new:
        lines += [f'private theorem c{n} : Model (Fin {n}) true :=', f'  {proof(n)}', '']
    lines += [
        'theorem extra_model {n : ℕ} (hn : n ∈ extraOrders) : Model (Fin n) true := by',
        '  simp only [extraOrders, Finset.mem_insert, Finset.mem_singleton] at hn',
        '  rcases hn with ' + ' | '.join(['rfl'] * len(new)),
    ]
    lines += [f'  · exact c{n}' for n in new]
    lines += ['', 'end Spectrum.E63.FieldBounds', '']
    outputs = {DEST / 'Equation63/FieldBounds.lean': '\n'.join(lines)}
    lines = [
        'import equational_theories.Spectrum.Equation63.FieldBounds',
        'import equational_theories.Spectrum.Equation63.IdempotentTail',
        '',
        '/-! Generated by scripts/spectrum_667_883_field_bounds.py.',
        'The finite-field supplement strengthens the original idempotent tail. -/',
        'set_option maxRecDepth 65536',
        'set_option maxHeartbeats 0',
        'namespace Spectrum.E63.FieldBounds',
    ]
    lines += [
        '',
        'def remaining : Finset ℕ := IdempotentFiniteBasis.exceptions \\ extraOrders',
        '',
        'theorem model {n : ℕ} (hn : n ∉ remaining) : Model (Fin n) true := by',
        '  by_cases he : n ∈ extraOrders',
        '  · exact extra_model he',
        '  · apply idempotent_model_of_not_exception',
        '    intro h',
        '    exact hn (Finset.mem_sdiff.mpr ⟨h, he⟩)',
        '',
        f'private theorem bound : ∀ n ∈ remaining, n < {cutoff} := by decide +kernel',
        '',
        f'theorem all_large {{n : ℕ}} (hn : {cutoff} ≤ n) : Model (Fin n) true := by',
        '  apply model',
        '  intro h',
        '  have := bound n h',
        '  omega',
        '',
        'spectrum_assert model complete',
        'spectrum_assert all_large complete',
        '',
        'end Spectrum.E63.FieldBounds',
        '',
    ]
    outputs[DEST / 'Equation63/FieldTail.lean'] = '\n'.join(lines)
    lines = [
        'import equational_theories.Spectrum.Equation667883Bounds',
        'import equational_theories.Spectrum.Equation63.FieldTail',
        '',
        '/-! Generated by scripts/spectrum_667_883_field_bounds.py.',
        'Additional finite-field constructions and improved cofinite bounds. -/',
        'set_option maxRecDepth 65536',
        'set_option maxHeartbeats 0',
        'namespace Spectrum',
        'open Law Law.MagmaLaw',
        '',
    ]
    for law in (667, 883):
        positives = positive_recipes(law, known)
        remaining = sorted(set(range(1, CUTOFF)) - positives.keys())
        # Every new positive used here is itself an idempotent model. If future
        # additions need products beyond this list, give them explicit proofs.
        assert positives.keys() - positive_recipes(law, old).keys() <= set(new)
        lines += [
            f'namespace E{law}.FieldBounds',
            '',
            'def remaining : Finset ℕ := ' + finset(remaining),
            '',
            f'private theorem coverage : ∀ n ∈ E{law}.remaining,',
            '    n ∉ remaining → n ∈ E63.FieldBounds.extraOrders := by decide +kernel',
            '',
            f'theorem lower : positiveExcept remaining ⊆ Law{law}.spectrum := by',
            '  rintro n ⟨hn, he⟩',
            f'  by_cases hold : n ∈ E{law}.remaining',
            f'  · exact ⟨hn, (E63.FieldBounds.extra_model (coverage n hold he)).hasModel{law}⟩',
            f'  · exact E{law}.lower ⟨hn, hold⟩',
            '',
            f'theorem all_large {{n : ℕ}} (hn : {cutoff} ≤ n) : Law{law}.HasModel n :=',
            f'  (E63.FieldBounds.all_large hn).hasModel{law}',
            '',
            f'theorem cofinite : CofiniteSpectrum Law{law} :=',
            f'  ⟨{cutoff}, fun _ hn => ⟨by omega, all_large hn⟩⟩',
            '',
            'spectrum_assert lower complete',
            'spectrum_assert cofinite complete',
            '',
            f'end E{law}.FieldBounds',
            '',
        ]
    lines += ['end Spectrum', '']
    outputs[DEST / 'Equation667883FieldBounds.lean'] = '\n'.join(lines)
    return outputs


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            assert path.read_text() == content, f'Stale generated file: {path}'
        elif not path.exists() or path.read_text() != content:
            path.write_text(content)
