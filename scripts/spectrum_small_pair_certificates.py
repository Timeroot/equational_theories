#!/usr/bin/env python3
"""Regenerate or verify the small exclusions separating spectrum classes.

Lean proves the normalization and the soundness of this two-layer one-hot
encoding. With --solve, CaDiCaL supplies LRAT data, then Lean's trimmer removes
unused steps. Ordinary builds replay the saved data and never invoke a solver.
"""
import argparse
import gzip
from itertools import combinations, product
import json
from pathlib import Path
import subprocess
import tempfile
import time

from spectrum_63_ten_certificate import sha, TRIM

ROOT = Path(__file__).resolve().parent.parent
CASES = [(670, 7), (677, 8), (704, 9), (1279, 9), (1313, 8)]
DATA = ROOT / "data/spectrum/small_pair_refutations.json"
DEST = ROOT / "equational_theories/Spectrum/SmallPairs/Certificates"
WITNESSES = [(1313, 9)]


def clauses(law, n):
    assert law in (670, 677, 704, 1279, 1313)
    r = range(n)
    p = lambda x, y, z: 1 + (x * n + y) * n + z
    q = lambda x, y, z: 1 + n**3 + (x * n + y) * n + z
    cs = []

    def one(vs):
        cs.append(vs)
        cs.extend([-a, -b] for a, b in combinations(vs, 2))

    for x, y in product(r, repeat=2):
        one([p(x, y, z) for z in r])
        one([p(x, z, y) for z in r])
        if law in (704, 1279, 1313):
            one([p(z, x, y) for z in r])
    for x, y in product(r, repeat=2):
        one([q(x, y, z) for z in r])
        first = (x, y) if law == 670 else (y, x) if law in (677, 1313) else (x, x)
        right = x if law == 1313 else y
        for a, b in product(r, repeat=2):
            av, bv, cv = p(*first, a), p(a, right, b), q(x, y, b)
            cs.extend([[-av, -bv, cv], [-av, bv, -cv]])
        for a, b in product(r, repeat=2):
            last = (x, a) if law in (670, 677) else (y, a) if law == 704 else (a, y)
            av, bv, cv = q(x, y, a), p(*last, b), p(y, b, x)
            cs.extend([[-av, -bv, cv], [-av, bv, -cv]])
    for x in r:
        cs.append([-p(0, 0, 0), p(x, x, x)])
    for y, z in product(r, repeat=2):
        if y + 1 < z:
            cs.append([-p(0, y, z)])
    if law in (704, 1279):
        for y in r:
            one([p(x, x, y) for x in r])
    return [c for c in cs if not any(-a in c for a in c)]


def cnf_bytes(law, n):
    cs = clauses(law, n)
    return (
        f"p cnf {2*n**3} {len(cs)}\n"
        + "".join(" ".join(map(str, c)) + " 0\n" for c in cs)
    ).encode()


def render(record):
    law, n = record["law"], record["order"]
    return f"""import equational_theories.Spectrum.SmallPairs.Encoding
import equational_theories.Definability.IncludeGzip
import equational_theories.Spectrum.Status

/- Generated by scripts/spectrum_small_pair_certificates.py.
CNF SHA-256: {record['cnf_sha256']}
Expanded LRAT SHA-256: {record['proof_sha256']}
The certificate is checked by Lean, not trusted as a solver answer. -/
namespace Spectrum.SmallPairs.E{law}N{n}
open Std.Sat Std.Tactic.BVDecide LRAT

private def proof : Array IntAction :=
  (parseLRATProof (include_gzip_str
    "../../../../{record['certificate']}").toUTF8).toOption.getD #[]

@[spectrum_native]
theorem checked : check proof (Encoding.natFormula .e{law} {n}) = true := by
  native_decide

theorem unsat : (Encoding.natFormula .e{law} {n}).Unsat := check_sound proof _ checked
end Spectrum.SmallPairs.E{law}N{n}

namespace Spectrum
theorem not_order_{law}_{n} : ¬ Law{law}.HasModel {n} :=
  SmallPairs.Encoding.not_hasModel .e{law} SmallPairs.E{law}N{n}.unsat

spectrum_assert not_order_{law}_{n} complete
end Spectrum
"""


def render_witnesses():
    tables = json.loads((ROOT / "data/spectrum/witnesses.json").read_text())
    lines = [
        "import equational_theories.Spectrum.SmallPairs.Basic",
        "import equational_theories.Spectrum.Status",
        "import Mathlib.Data.Fin.VecNotation",
        "",
        "/-! Small positive witnesses. Generated from data/spectrum/witnesses.json",
        "by scripts/spectrum_small_pair_certificates.py. Every table is checked",
        "by kernel reduction, with no native computation or admitted proof. -/",
        "",
        "namespace Spectrum.SmallPairs",
        "",
    ]
    for law, n in WITNESSES:
        table = tables[f"{law}:{n}"]
        assert len(table) == n * n and all(0 <= x < n for x in table)
        rows = [
            "![" + ", ".join(map(str, table[i * n : (i + 1) * n])) + "]"
            for i in range(n)
        ]
        lines += [
            "@[implicit_reducible]",
            f"def table_{law}_{n} : Magma (Fin {n}) :=",
            "  ⟨fun x y => ![" + ",\n    ".join(rows) + "] x y⟩",
            "",
            f"theorem model_{law}_{n} : Law{law}.HasModel {n} :=",
            f"  ⟨table_{law}_{n}, (@Law{law}.models_iff _ table_{law}_{n}).mpr (by decide +kernel)⟩",
            f"spectrum_assert model_{law}_{n} complete",
            "",
        ]
    lines += ["end Spectrum.SmallPairs", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solve", action="store_true")
    parser.add_argument("--solver", default="cadical")
    parser.add_argument("--timeout", type=int, default=120)
    args = parser.parse_args()
    if args.solve:
        records = []
        for law, n in CASES:
            cnf = cnf_bytes(law, n)
            with tempfile.TemporaryDirectory(prefix=f"e{law}-{n}-") as tmp:
                tmp = Path(tmp)
                inp, proof = tmp / "input.cnf", tmp / "proof.lrat"
                inp.write_bytes(cnf)
                t = time.monotonic()
                result = subprocess.run(
                    [
                        args.solver,
                        "--quiet",
                        "--shrink=0",
                        "--lrat",
                        "--no-binary",
                        "-t",
                        str(args.timeout),
                        str(inp),
                        str(proof),
                    ],
                    capture_output=True,
                    text=True,
                )
                seconds = time.monotonic() - t
                if result.returncode != 20:
                    raise SystemExit(
                        f"E{law}/{n}: no UNSAT certificate: {result.stdout} {result.stderr}"
                    )
                trim = tmp / "Trim.lean"
                trim.write_text(TRIM)
                subprocess.run(
                    ["lake", "env", "lean", "--run", str(trim), str(proof)],
                    cwd=ROOT,
                    check=True,
                )
                payload = Path(str(proof) + ".trimmed").read_bytes()
                compressed = gzip.compress(payload, mtime=0)
                dest = ROOT / f"data/spectrum/small_pair_lrat/e{law}_{n}.lrat.gz"
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(compressed)
                record = dict(
                    law=law,
                    order=n,
                    theorem=f"Spectrum.not_order_{law}_{n}",
                    variables=2 * n**3,
                    clauses=len(clauses(law, n)),
                    cnf_sha256=sha(cnf),
                    proof_sha256=sha(payload),
                    compressed_sha256=sha(compressed),
                    proof_bytes=len(payload),
                    compressed_bytes=len(compressed),
                    search_seconds=round(seconds, 3),
                    certificate=str(dest.relative_to(ROOT)),
                    checking="Lean LRAT.check_sound and native_decide; no sorry",
                )
                records.append(record)
                print(
                    f"E{law}/{n}: {seconds:.3f}s search, {len(compressed):,} compressed bytes",
                    flush=True,
                )
        DATA.write_text(json.dumps(records, indent=2) + "\n")
    else:
        records = json.loads(DATA.read_text())
        assert [(r["law"], r["order"]) for r in records] == CASES
        for r in records:
            compressed = (ROOT / r["certificate"]).read_bytes()
            assert (
                sha(cnf_bytes(r["law"], r["order"])) == r["cnf_sha256"]
            ), "CNF changed: rerun --solve"
            assert (
                sha(compressed) == r["compressed_sha256"]
            ), "Compressed certificate changed"
            assert (
                sha(gzip.decompress(compressed)) == r["proof_sha256"]
            ), "LRAT proof changed"
    DEST.mkdir(parents=True, exist_ok=True)
    for r in records:
        (DEST / f"E{r['law']}N{r['order']}.lean").write_text(render(r))
    (DEST.parent / "Witnesses.lean").write_text(render_witnesses())
    print(f"Verified and rendered {len(records)} finite exclusions.")


if __name__ == "__main__":
    main()
