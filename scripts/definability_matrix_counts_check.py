#!/usr/bin/env python3
"""Check matrix-affine counts by complete table evaluation and regenerate Lean."""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from spectrum_generate import load_equations, variables

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_matrix_counts.json"
OUTPUT = ROOT / "equational_theories/Definability/Generated/MatrixAffineCount.lean"


def matrix_tables(prime):
    vectors = np.array(list(itertools.product(range(prime), repeat=2)), dtype=np.int64)
    matrices = np.array(
        list(itertools.product(range(prime), repeat=4)), dtype=np.int64
    ).reshape(-1, 2, 2)
    images = np.einsum("mij,xj->mxi", matrices, vectors)
    outputs = (
        images[:, None, None, :, None, :]
        + images[None, :, None, None, :, :]
        + vectors[None, None, :, None, None, :]
    ) % prime
    # Fixed labels for the vectors (x0,x1); counts do not depend on this choice.
    return (
        (outputs[..., 0] * prime + outputs[..., 1])
        .astype(np.uint8)
        .reshape(-1, prime**2, prime**2)
    )


def table_counts(equations, ids, tables):
    """Test every assignment, discarding a table immediately after a failure."""
    n = tables.shape[1]
    result = {}
    for law in ids:
        lhs, rhs = equations[law - 1]
        names = sorted(variables(lhs) | variables(rhs))
        assignments = np.array(
            list(itertools.product(range(n), repeat=len(names))), dtype=np.uint8
        ).T
        active = np.arange(len(tables))
        for start in range(0, assignments.shape[1], 16):
            if not len(active):
                break
            batch = assignments[:, start : start + 16]
            index = active[:, None]
            cache = {v: batch[i][None, :] for i, v in enumerate(names)}

            def evaluate(term):
                if term not in cache:
                    cache[term] = tables[index, evaluate(term[0]), evaluate(term[1])]
                return cache[term]

            equality = np.broadcast_to(
                evaluate(lhs) == evaluate(rhs), (len(active), batch.shape[1])
            )
            active = active[np.all(equality, axis=1)]
        result[law] = len(active)
    return result


def render(entries):
    lines = [
        "import equational_theories.Definability.MatrixAffineCounting",
        "",
        "/-! Generated by scripts/definability_matrix_counts_check.py.",
        "Count all matrix-affine operations on a two-dimensional vector space. -/",
        "",
        "open Law Law.MagmaLaw Magma.MatrixAffine",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for e in entries:
        s, t, q = e["source"], e["target"], e["prime"]
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_matrixAffineCount"
        lines += [
            f"/-- {e['source_count']} source parameters, but only {e['target_count']} target parameters. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            f"  apply not_termStructuralFromFin_of_cloneFamily_count (op (n := {q})) op_injective",
            "    (unit, 0, 0) (0, unit, 0) comp op_fst op_snd op_comp",
            f"    (fun p : P {q} => @Equation{s} (V {q}) ⟨op p⟩)",
            f"    (fun p : P {q} => @Equation{t} (V {q}) ⟨op p⟩)",
            "  · intro p hp",
            f"    exact (@Law{s}.models_iff (V {q}) ⟨op p⟩).mpr hp",
            "  · intro p hp",
            f"    exact (@Law{t}.models_iff (V {q}) ⟨op p⟩).mp hp",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    entries = data["candidates"]
    equations = load_equations()
    for q in sorted({e["prime"] for e in entries}):
        batch = [e for e in entries if e["prime"] == q]
        tables = matrix_tables(q)
        assert len(tables) == q**10
        assert len(np.unique(tables.reshape(len(tables), -1), axis=0)) == len(tables)
        ids = sorted({e[k] for e in batch for k in ("source", "target")})
        counts = table_counts(equations, ids, tables)
        for e in batch:
            assert counts[e["source"]] == e["source_count"]
            assert counts[e["target"]] == e["target_count"]
            assert e["source_count"] > e["target_count"]
        print(
            f"Checked all {len(tables):,} affine tables over F_{q}^2 for {len(ids)} laws."
        )
    text = render(entries)
    if args.write:
        OUTPUT.write_text(text)
    else:
        assert OUTPUT.read_text() == text, "regenerate with --write"
    print(f"Reproduced {len(entries)} matrix-affine certificates.")


if __name__ == "__main__":
    main()
