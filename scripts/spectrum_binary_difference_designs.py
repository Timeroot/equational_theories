#!/usr/bin/env python3
"""Reconstruct and check the difference matrices for TD(8,40) and TD(8,160).

These are additive developments over Z/5 x GF(2^c), using the coefficient
matrices transcribed in the JSON files. Lean independently checks every
retained row difference, without relying on the finite-field reconstruction.
"""
import argparse
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def reconstruct(cert):
    polynomial = cert["field_polynomial"]
    c = polynomial.bit_length() - 1
    size = 1 << c

    def mul(a, b):
        result = 0
        while b:
            if b & 1:
                result ^= a
            a <<= 1
            if a & size:
                a ^= polynomial
            b >>= 1
        return result

    powers = [1]
    for _ in range(size - 2):
        powers.append(mul(powers[-1], 2))
    assert len(set(powers)) == size - 1

    def power(e):
        return 0 if e is None else powers[e]

    columns = list(zip(*cert["original_matrix"]))
    rows = [
        [[a, power(e) ^ mul(power(y), v)] for v in range(size // 2) for a, e in column]
        for column, y in zip(columns, cert["Y"])
    ][:7]
    n = 5 * size
    assert len(rows) == 7 and all(len(row) == n for row in rows)
    for row, other in itertools.combinations(rows, 2):
        differences = {((a - b) % 5, u ^ v) for (a, u), (b, v) in zip(row, other)}
        assert len(differences) == n
    return c, rows


def lean_source(n, c, rows):
    size = 1 << c
    entries = [size * a + b for row in rows for a, b in row]
    literal = ",\n".join(
        "  " + ", ".join(map(str, entries[i : i + 32]))
        for i in range(0, len(entries), 32)
    )
    return f"""import equational_theories.Spectrum.Equation63.DifferenceMatrix
import equational_theories.Spectrum.Equation63.FieldDesign
import equational_theories.Spectrum.Status
import Mathlib.Data.ZMod.Basic

/-! Seven difference rows over Z/5 × (Z/2)^{c}.
Each row difference is a permutation; development gives TD(8,{n}).
Generated by scripts/spectrum_binary_difference_designs.py. The original
coefficients and provenance are in data/spectrum/td{n}_difference_matrix.json.
The finite certificate is checked independently of its field construction. -/

namespace Spectrum.E63.TD{n}

abbrev Q := ZMod 5 × (Fin {c} → ZMod 2)

private def entries : Array Nat := #[
{literal}
]

def encode (x : Q) : ℕ :=
  {size}*x.1.val + ((List.finRange {c}).map (fun i => (x.2 i).val * 2^i.val)).sum

def decode (a : ℕ) : Q :=
  ((a / {size} : ℕ), fun i => if a.testBit i.val then 1 else 0)

def matrix (x : Q) (i : Fin 7) : Q := decode entries[{n}*i.val + encode x]!

@[spectrum_native]
theorem differences : ∀ i j : Fin 7, i ≠ j →
    Function.Injective (fun x : Q => matrix x i - matrix x j) := by
  native_decide

theorem exists_td : HasTD {n} := by
  let D : Transversal Groups (Fin {n}) (Q × Q) := (differenceDesign matrix differences).relabel
    (Fintype.equivFinOfCardEq (by simp [Q]))
  exact ⟨D.reindex (Fintype.equivFinOfCardEq (by simp [Q])).symm⟩

spectrum_assert exists_td complete

end Spectrum.E63.TD{n}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for n in (40, 160):
        path = ROOT / f"data/spectrum/td{n}_difference_matrix.json"
        cert = json.loads(path.read_text())
        c, rows = reconstruct(cert)
        if "difference_rows" in cert:
            assert cert["difference_rows"] == rows
        elif args.check:
            raise AssertionError(f"Missing difference_rows: {path}")
        else:
            cert["difference_rows"] = rows
            path.write_text(json.dumps(cert, indent=2) + "\n")
        dest = ROOT / f"equational_theories/Spectrum/Equation63/TD{n}.lean"
        text = lean_source(n, c, rows)
        if args.check:
            assert dest.read_text() == text, f"Stale generated file: {dest}"
        else:
            dest.write_text(text)
        print(f"TD(8,{n}): all 21 row differences independently verified")


if __name__ == "__main__":
    main()
