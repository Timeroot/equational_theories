#!/usr/bin/env python3
"""Replay the E1483 constant-row untwisting proofs as kernel-checked equalities.

Uses the existing checked-rewrite generator's term parser and matcher. Every
external proof step becomes an explicit Lean equality; no ATP result is trusted.
"""
import argparse
import json
from pathlib import Path

from definability_1483_constant_check import (
    match, parse, paths, render, replace, sections, sub, variables,
)

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data/spectrum/1483_constant_untwist_proofs.json'
OUT = ROOT / 'equational_theories/Spectrum/Equation1483/ConstantUntwist.lean'


def axiom_proof(block):
    l, r = block['lhs'], block['rhs']
    if l == parse('f(X,zero)'):
        return 'constant_column h zero one hzero v_X'
    if l == parse('f(one,f(X,one))'):
        return 'left_inverse h zero one hzero v_X'
    if l == parse('f(f(one,X),one)'):
        return 'right_inverse h zero one hzero v_X'
    if l == parse('f(f(X,Y),f(Y,f(X,Z)))'):
        return '(h v_Y v_X v_Z).symm'
    if l == parse('f(f(f(X,Y),Z),f(Z,Y))'):
        return 'CentralDual.dual h v_Z v_Y v_X'
    if l == parse('f(one,f(one,f(X,Y)))'):
        return '(CentralConstant.left_square_hom h zero one hzero v_X v_Y).symm'
    if r == 'X' and l == parse('f(one,f(one,f(one,f(one,f(one,f(one,X))))))'):
        return 'CentralConstant.left_six h zero one hzero v_X'
    raise ValueError(('unrecognized axiom', l, r))


def generate(name, trace):
    blocks = sections(trace)
    goal = next(b for b in blocks if b['kind'] == 'goal')
    params = 'x y z' if name == 'untwist_eqn' else 'x y'
    out = [f'theorem {name} (h : Equation1483 G) (zero one : G)',
           f'    (hzero : ∀ t : G, zero ◇ t = one) ({params} : G) :',
           f'    {render(goal["lhs"], set())} = {render(goal["rhs"], set())} := by']
    known = {}
    for b in blocks:
        bound = sorted(variables(b['lhs']) | variables(b['rhs']))
        b['bound'] = bound
        known[b['kind'], b['num']] = b
        nm = f'{b["kind"]}_{b["num"]}'
        if b['kind'] != 'goal':
            args = '(' + ' '.join('v_' + v for v in bound) + ' : G) ' if bound else ''
            out.append(f'  have {nm} {args}: {render(b["lhs"], bound)} = {render(b["rhs"], bound)} := by')
        if b['kind'] == 'axiom':
            out.append('    exact ' + axiom_proof(b))
            continue
        indent = '  ' if b['kind'] == 'goal' else '    '
        assert b['initial'] == b['lhs']
        out.append(indent + 'calc')
        prev = b['initial']
        for j, (kind, no, rev, nxt) in enumerate(b['steps']):
            lemma = known[kind, no]
            l, r = (lemma['rhs'], lemma['lhs']) if rev else (lemma['lhs'], lemma['rhs'])
            found = None
            for path in paths(prev):
                try:
                    pt, nt = sub(prev, path), sub(nxt, path)
                except (IndexError, TypeError):
                    continue
                env = {}
                if match(l, pt, env) and match(r, nt, env) and replace(prev, path, nt) == nxt:
                    found = path, env
                    break
            assert found, (name, nm, j, kind, no)
            path, env = found
            app = f'{kind}_{no}' + ''.join(' ' + render(env.get(v, 'zero'), bound) for v in lemma['bound'])
            app = '(' + app + ')' + ('.symm' if rev else '')
            if path:
                app = f'congrArg (fun hole : G => {render(replace(prev, path, "hole"), bound)}) {app}'
            out.append(indent + '  ' + (render(prev, bound) if j == 0 else '_') +
                       ' = ' + render(nxt, bound) + ' := ' + app)
            prev = nxt
        assert prev == b['rhs']
    out += ['', f"/-- info: 'Spectrum.E1483.Constant.{name}' does not depend on any axioms -/",
            '#guard_msgs in', f'#print axioms {name}', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    traces = json.loads(DATA.read_text())
    text = '''import equational_theories.Spectrum.Equation1483.ConstantBasic

/-! Generated by scripts/spectrum_1483_constant.py. External proof traces are
replayed using explicit equality transitivity and congruence only. -/

set_option maxRecDepth 12000
set_option maxHeartbeats 2000000

namespace Spectrum.E1483.Constant
variable {G : Type*} [Magma G]

'''
    text += '\n'.join(generate(name, trace) for name, trace in traces.items())
    text += '\nend Spectrum.E1483.Constant\n'
    if args.write:
        OUT.write_text(text)
    else:
        assert OUT.read_text() == text, f'{OUT} is stale'


if __name__ == '__main__':
    main()
