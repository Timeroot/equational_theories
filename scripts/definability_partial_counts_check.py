#!/usr/bin/env python3
"""Check and reproduce the broader finite linear-count certificates.

Python verifies the saved coefficient data and deterministic Lean text. Only
the separately compiled Lean declarations establish definability facts.
"""

import argparse
from functools import lru_cache
import json
from pathlib import Path

from definability_linear_counts import linear_models
from spectrum_generate import load_equations


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_partial_linear_counts.json"
GENERATED = ROOT / "equational_theories/Definability/Generated"


def render(entries):
    lines = [
        "import equational_theories.Definability.LinearCounting",
        "import Mathlib.Tactic.ReduceModChar",
        "",
        "/-! Generated by scripts/definability_partial_counts_check.py.",
        "Finite linear-model counts obstruct mutual term recovery.",
        "The product magmas themselves are never enumerated. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for entry in entries:
        s, t, n = entry["source"], entry["target"], entry["modulus"]
        factors = entry["factors"]
        k = len(factors)
        a, b = (", ".join(str(p[i]) for p in factors) for i in (0, 1))
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_partialLinearCount"
        tactic = "decide" if n <= 7 else "native_decide"
        lines += [
            f"/-- {k} distinct linear source factors over `ZMod {n}`, but only",
            f"{entry['target_count']} target coefficient pairs. -/",
            f"theorem {name} :",
            f"    ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            "  apply not_termStructuralFromFin_of_linear_count",
            f"    (![{a}] : Fin {k} → ZMod {n}) (![{b}] : Fin {k} → ZMod {n})",
            "  · decide",
            "  · intro i",
            f"    apply (@Law{s}.models_iff (ZMod {n}) (lin _ _)).mpr",
            f"    fin_cases i <;> norm_num [Equation{s}, lin_op] <;> intros <;> ring_nf <;> reduce_mod_char",
            f"  · {tactic}",
            "",
        ]
        axioms = ["propext", "Classical.choice", "Quot.sound"]
        if tactic == "native_decide":
            axioms += [f"{name}._native.native_decide.ax_1_{i}" for i in (1,)]
        lines += [
            f"/-- info: '{name}' depends on axioms: [{', '.join(axioms)}] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    equations = load_equations()

    @lru_cache(None)
    def models(law, modulus):
        return linear_models(equations[law - 1], modulus)

    entries = data["candidates"]
    for entry in entries:
        s, t, n = entry["source"], entry["target"], entry["modulus"]
        source, target = models(s, n), models(t, n)
        factors = list(map(tuple, entry["factors"]))
        assert len(source) == entry["source_count"]
        assert len(target) == entry["target_count"]
        assert len(set(factors)) == len(factors) == len(target) + 1
        assert set(factors) <= set(source)
    selected = data["selected_indices"]
    assert len(set(selected)) == len(selected)
    assert set().union(*(set(c) for _, c in data["coverage"])) == set(
        range(len(entries))
    )
    initial = [i for i in selected if entries[i]["modulus"] <= 100]
    extended = [i for i in selected if entries[i]["modulus"] > 100]
    parts = [initial[part::3] for part in range(3)] + [extended]
    for part, indices in enumerate(parts):
        path = GENERATED / f"PartialLinearCount{part}.lean"
        text = render([entries[i] for i in indices])
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f"regenerate {path} with --write"
    print(
        f"Verified {len(entries)} count certificates; {len(selected)} Lean generators reproduced."
    )


if __name__ == "__main__":
    main()
