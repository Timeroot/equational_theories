#!/usr/bin/env python3
"""Replayable positive bounds from idempotent E63, loops, and products.

The generated Lean file proves the finite coverage calculation by kernel
reduction. No failure of this construction is interpreted as nonexistence.
"""
import argparse
from math import isqrt
from pathlib import Path
from spectrum_63_idempotent_bounds import closure, CUTOFF

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'equational_theories/Spectrum/Equation667883Bounds.lean'


def positive_recipes(law, idem):
    known = {n: ('idem', n) for n in idem if 0 < n < CUTOFF}
    for n in range(1, CUTOFF):
        if n % 3:
            known[n] = ('loops', n)
    exponent = 2 if law == 667 else 4
    for k in range(1, isqrt(CUTOFF) + 1):
        if k ** exponent < CUTOFF:
            known[k ** exponent] = ('power', k)
    for n in range(1, CUTOFF):
        if n not in known:
            for k in range(2, isqrt(n) + 1):
                if n % k == 0 and k in known and n // k in known:
                    known[n] = ('mul', k, n // k)
                    break
    return known


def generate():
    idem = closure(CUTOFF)
    lines = [
        'import equational_theories.Spectrum.Equation667883',
        'import equational_theories.Spectrum.Equation63.IdempotentTail',
        '',
        '/-! Generated by scripts/spectrum_667_883_bounds.py. The remaining',
        'sets contain both excluded orders and genuinely unresolved orders.',
        'All positive claims have complete Lean proofs. -/',
        'set_option maxRecDepth 65536',
        'set_option maxHeartbeats 0',
        'namespace Spectrum',
        'open Law Law.MagmaLaw',
        '',
    ]
    for law in (667, 883):
        known = positive_recipes(law, idem)
        remaining = sorted(set(range(1, CUTOFF)) - known.keys())
        supplements = sorted(n for n in known if n not in idem and n % 3 == 0)

        def proof(n):
            tag, *args = known[n]
            if tag == 'idem':
                return f'(E63.idempotent_model_of_not_exception (n := {n}) (by decide)).hasModel{law}'
            if tag == 'loops':
                return f'(non_three (n := {n}) (by decide) (by decide))'
            if tag == 'power':
                return f'({"square" if law == 667 else "fourth"}_model {args[0]})'
            if tag == 'mul':
                return f'({proof(args[0])}.mul {proof(args[1])})'
            raise AssertionError(tag)

        lines += [f'namespace E{law}', '',
                  'def remaining : Finset ℕ := {' + ', '.join(map(str, remaining)) + '}', '',
                  'private def supplements : Finset ℕ := {' + ', '.join(map(str, supplements)) + '}', '']
        for n in supplements:
            lines += [f'private theorem c{n} : Law{law}.HasModel {n} := {proof(n)}']
        lines += ['',
                  'private theorem supplement_model {n : ℕ} (hn : n ∈ supplements) :',
                  f'    Law{law}.HasModel n := by',
                  '  simp only [supplements, Finset.mem_insert, Finset.mem_singleton] at hn',
                  '  rcases hn with ' + ' | '.join(['rfl'] * len(supplements))]
        lines += [f'  · exact c{n}' for n in supplements]
        lines += ['',
                  'private theorem coverage : ∀ n ∈ E63.IdempotentFiniteBasis.exceptions,',
                  '    n % 3 = 0 → n ∉ remaining → n ∈ supplements := by decide +kernel', '',
                  f'theorem lower : positiveExcept remaining ⊆ Law{law}.spectrum := by',
                  '  rintro n ⟨hn, he⟩',
                  '  refine ⟨hn, ?_⟩',
                  '  by_cases hm : n % 3 = 0',
                  '  · by_cases hi : n ∈ E63.IdempotentFiniteBasis.exceptions',
                  '    · exact supplement_model (coverage n hi hm he)',
                  f'    · exact (E63.idempotent_model_of_not_exception hi).hasModel{law}',
                  '  · exact non_three hn hm', '',
                  f'theorem all_large {{n : ℕ}} (hn : {CUTOFF} ≤ n) : Law{law}.HasModel n :=',
                  f'  (E63.idempotent_all_large hn).hasModel{law}', '',
                  f'theorem cofinite : CofiniteSpectrum Law{law} :=',
                  f'  ⟨{CUTOFF}, fun _ hn => ⟨by omega, all_large hn⟩⟩', '',
                  'spectrum_assert lower complete',
                  'spectrum_assert cofinite complete', '',
                  f'end E{law}', '']
    lines += ['end Spectrum', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    content = generate()
    if args.check:
        assert DEST.read_text() == content, f'Stale generated file: {DEST}'
    else:
        DEST.write_text(content)
