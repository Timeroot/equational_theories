#!/usr/bin/env python3
"""Reproduce the E63 order-ten certificate; ordinary Lean builds only replay it.

With --solve, run CaDiCaL once and trim its LRAT proof using Lean's trimmer.
Without --solve, verify the saved hashes and regenerate the small replay module.
The mathematical encoding and all symmetry reductions are proved in
Spectrum/Equation63/OrderTen/{Basic,Normalization,Encoding}.lean.
"""
import argparse
import gzip
import hashlib
from itertools import combinations, product
import json
from pathlib import Path
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data/spectrum/63_order10_refutation.json"
PROOF = ROOT / "data/spectrum/63_ten_lrat/exclusion.lrat.gz"
LEAN = ROOT / "equational_theories/Spectrum/Equation63/OrderTen/Certificate.lean"
TRIM = """import Lean.Elab.Tactic.BVDecide
open Std.Tactic.BVDecide.LRAT Lean.Elab.Tactic.BVDecide.LRAT
def main (args : List String) : IO Unit := do
  for file in args do
    let proof ← loadLRATProof file
    let trimmed ← IO.ofExcept (trim proof)
    dumpLRATProof (file ++ ".trimmed") trimmed false
"""


def clauses(n=10):
    r = range(n)
    p = lambda x, y, z: 1 + (x * n + y) * n + z
    cs = []
    for x, y in product(r, repeat=2):
        for vs in ([p(x, y, z) for z in r], [p(x, z, y) for z in r],
                   [p(z, x, y) for z in r]):
            cs.append(vs)
            cs.extend([-a, -b] for a, b in combinations(vs, 2))
    for y, x, a, b in product(r, repeat=4):
        av, bv, cv = p(y, x, a), p(y, a, b), p(b, y, x)
        cs.extend([[-av, -bv, cv], [-av, bv, -cv], [av, -bv, -cv]])
    for x, y, z in product(r, repeat=3):
        cs.append([-p(x, x, y), -p(x, y, z), p(x, z, x)])
        if y != z:
            cs.append([-p(x, y, z), -p(x, z, y)])
    for x in r:
        cs.append([-p(0, 0, 0), p(x, x, x)])
    for y, z in product(r, repeat=2):
        if y + 1 < z:
            cs.append([-p(0, y, z)])
    return [c for c in cs if not any(-l in c for l in c)]


def cnf_bytes():
    cs = clauses()
    return (f"p cnf 1000 {len(cs)}\n" +
            "".join(" ".join(map(str, c)) + " 0\n" for c in cs)).encode()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def render(record):
    return f'''import equational_theories.Spectrum.Equation63.OrderTen.Encoding
import equational_theories.Definability.IncludeGzip
import equational_theories.Spectrum.Status

/- Generated by scripts/spectrum_63_ten_certificate.py.
CNF SHA-256: {record["cnf_sha256"]}
Expanded LRAT SHA-256: {record["proof_sha256"]}
The external solver supplies data only. Lean's verified LRAT checker checks
the certificate using native_decide, under the spectrum_native trust policy.
No solver is invoked during a Lean build. -/

namespace Spectrum.E63.OrderTen
open Std.Sat Std.Tactic.BVDecide LRAT

private def refutation : Array IntAction :=
  (parseLRATProof (include_gzip_str
    "../../../../data/spectrum/63_ten_lrat/exclusion.lrat.gz").toUTF8).toOption.getD #[]

@[spectrum_native]
theorem checked : check refutation Encoding.natFormula = true := by
  native_decide

theorem unsat : Encoding.natFormula.Unsat := check_sound refutation _ checked

spectrum_assert unsat complete
end Spectrum.E63.OrderTen
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solve", action="store_true")
    parser.add_argument("--solver", default="cadical")
    parser.add_argument("--timeout", type=int, default=120)
    args = parser.parse_args()
    cnf = cnf_bytes()
    if args.solve:
        with tempfile.TemporaryDirectory(prefix="e63-ten-") as work:
            work = Path(work)
            inp, proof = work / "input.cnf", work / "proof.lrat"
            inp.write_bytes(cnf)
            start = time.monotonic()
            result = subprocess.run([args.solver, "--quiet", "--shrink=0", "--lrat",
                                     "--no-binary", "-t", str(args.timeout), str(inp), str(proof)],
                                    check=False, capture_output=True, text=True)
            seconds = time.monotonic() - start
            if result.returncode != 20:
                raise SystemExit(f"Expected UNSAT (exit 20), got {result.returncode}: {result.stdout} {result.stderr}")
            trim = work / "Trim.lean"
            trim.write_text(TRIM)
            subprocess.run(["lake", "env", "lean", "--run", str(trim), str(proof)],
                           cwd=ROOT, check=True)
            payload = Path(str(proof) + ".trimmed").read_bytes()
            compressed = gzip.compress(payload, mtime=0)
            PROOF.parent.mkdir(parents=True, exist_ok=True)
            PROOF.write_bytes(compressed)
            record = {
                "law": 63, "order": 10,
                "theorem": "Spectrum.not_order_63_10",
                "encoding": "E229 Latin table; conditional diagonal and chain labelling",
                "variables": 1000, "clauses": len(clauses()),
                "cnf_sha256": sha(cnf), "proof_sha256": sha(payload),
                "compressed_sha256": sha(compressed),
                "proof_bytes": len(payload), "compressed_bytes": len(compressed),
                "solver": subprocess.check_output([args.solver, "--version"], text=True).strip(),
                "search_seconds": round(seconds, 3),
                "certificate": str(PROOF.relative_to(ROOT)),
                "checking": "Lean LRAT.check_sound and native_decide; no sorry",
            }
            DATA.write_text(json.dumps(record, indent=2) + "\n")
    else:
        record = json.loads(DATA.read_text())
        compressed = PROOF.read_bytes()
        assert sha(cnf) == record["cnf_sha256"], "Encoding changed; regenerate with --solve"
        assert sha(compressed) == record["compressed_sha256"], "Compressed certificate changed"
        assert sha(gzip.decompress(compressed)) == record["proof_sha256"], "LRAT certificate changed"
    LEAN.write_text(render(record))
    print(f"E63/10: {record['clauses']} clauses, {record['compressed_bytes']:,} compressed bytes; replay module generated.")


if __name__ == "__main__":
    main()
