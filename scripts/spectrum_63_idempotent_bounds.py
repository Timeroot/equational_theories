#!/usr/bin/env python3
"""Generate the checked finite basis and arithmetic certificate for idempotent E63.

Only already formalized constructions are used: affine and cubic models,
the homogeneous seeds of orders31 and41 and the order-255 field-design consequence,
products, singular products, and TD(8,q) for gcd(q,60)=1 or q=25,27,36.
Every generated claim is rechecked in Lean; Python is not trusted by the proof.
"""
import argparse
from math import gcd, isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'equational_theories/Spectrum/Equation63'
CUTOFF = 1480
SMALL = 2086
LIMIT = 8 * (CUTOFF + 42)
ORDINARY_EXCEPTIONS = {2, 6, 10, 14, 18, 26, 30, 38, 42, 90, 158}


def closure(limit):
    known = {0: ['seed', 0], 1: ['seed', 1], 8: ['seed', 8],
             27: ['seed', 27], 31: ['seed', 31], 32: ['seed', 32],
             41: ['seed', 41], 255: ['seed', 255]}
    for n in range(2, limit):
        if n not in known:
            k = round(n ** (1 / 3))
            if k ** 3 == n:
                known[n] = ['cube', k]
        if n not in known:
            for k in range(2, isqrt(n) + 1):
                if n % k == 0 and k in known and n // k in known:
                    known[n] = ['prod', k, n // k]
                    break
        if n not in known:
            for k in range(2, isqrt(n - 1) + 1):
                if (n - 1) % k == 0:
                    for index in [k, (n - 1) // k]:
                        q = (n - 1) // index + 1
                        if index in known and q in known and q - 1 not in ORDINARY_EXCEPTIONS:
                            known[n] = ['singular', index, q, q - 1]
                            break
                if n in known:
                    break
        if n not in known:
            for q in range((n + 7) // 8, n // 7 + 1):
                r = n - 7 * q
                if q in known and r in known and (gcd(q, 60) == 1 or q in [25, 27, 36]):
                    known[n] = ['seven', q, r]
                    break
        if n not in known:
            b = next((b for b in range(1, n) if (b * b * b - b + 1) % n == 0), None)
            if b is not None:
                known[n] = ['affine', b]
    return known


def proof(recipe):
    tag, *args = recipe
    if tag == 'seed':
        return f'idem{args[0]}'
    if tag == 'cube':
        return f'cubic_idempotent {args[0]}'
    if tag == 'affine':
        return f'modular_idem {{n}} {args[0]} (by decide)'
    if tag == 'prod':
        return f'c{args[0]}.mul c{args[1]}'
    if tag == 'singular':
        k, q, m = args
        assert m < 1608
        return (f'singular_idempotent_model c{k} c{q} '
                '(FiniteBasis.model (by decide) (by decide))')
    if tag == 'seven':
        q, r = args
        if gcd(q, 60) == 1:
            return f'seven_idempotent (by decide) (by decide) (by decide) c{q} c{r}'
        assert q in [25, 27, 36]
        return f'Design{q}.design.idempotent_models (by decide) c{q} c{r} idem7 idem8'
    raise AssertionError(recipe)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='Verify the generated Lean sources without rewriting them.')
    args = parser.parse_args()

    def output(name, text):
        path = DEST / name
        if args.check:
            assert path.read_text() == text, f'Generated source differs: {path}'
        elif not path.exists() or path.read_text() != text:
            path.write_text(text)

    known = closure(SMALL)
    missing = sorted(set(range(SMALL)) - known.keys())
    assert max(missing) + 1 == CUTOFF
    lines = [
        'import equational_theories.Spectrum.Equation63.IdempotentSeeds',
        'import equational_theories.Spectrum.Equation63.Homogeneous31',
        'import equational_theories.Spectrum.Equation63.Homogeneous41',
        'import equational_theories.Spectrum.Equation63.FiniteBasis',
        '',
        '/-! Generated by scripts/spectrum_63_idempotent_bounds.py. Every entry',
        'uses a proved idempotent construction; coverage is checked by the kernel. -/',
        'set_option maxRecDepth 65536',
        'set_option maxHeartbeats 0',
        'namespace Spectrum.E63.IdempotentFiniteBasis',
        '',
    ]
    for n in sorted(known):
        p = proof(known[n]).format(n=n)
        lines.append(f'private theorem c{n} : Model (Fin {n}) true := {p}')
    lines += [
        '',
        '/-- Orders not supplied by this finite construction certificate. These',
        'are possible exceptions, not nonexistence claims. -/',
        'def exceptions : Finset ℕ := {' + ', '.join(map(str, missing)) + '}',
        '',
        f'theorem exceptions_lt : ∀ n ∈ exceptions, n < {CUTOFF} := by decide +kernel',
        '',
        'private def known : List ℕ := [' + ', '.join(map(str, sorted(known))) + ']',
        '',
        'private theorem models : List.Forall (fun n => Model (Fin n) true) known :=',
        '  ⟨' + ', '.join(f'c{n}' for n in sorted(known)) + '⟩',
        '',
        f'private theorem known_eq : known = (List.range {SMALL}).filter',
        '    (fun n => decide (n ∉ exceptions)) := by decide +kernel',
        '',
        f'theorem model {{n : ℕ}} (hn : n < {SMALL}) (he : n ∉ exceptions) :',
        '    Model (Fin n) true := by',
        '  apply (List.forall_iff_forall_mem.mp models) n',
        '  rw [known_eq, List.mem_filter]',
        '  exact ⟨List.mem_range.mpr hn, by simpa using he⟩',
        '',
        'end Spectrum.E63.IdempotentFiniteBasis',
        '',
    ]
    output('IdempotentFiniteBasis.lean', '\n'.join(lines))

    # Each image covers all available r <= q in one integer operation. Choose
    # a deterministic small cover of the required interval; Lean verifies both
    # the admissibility of each q and the coverage, independently of this search.
    bitmap = sum(1 << n for n in known)
    images = {q: (bitmap % (1 << (q + 1))) << (7 * q)
              for q in sorted(known) if q > 0 and gcd(q, 60) == 1}
    uncovered = ((1 << (LIMIT - SMALL)) - 1) << SMALL
    groups = []
    while uncovered:
        q = max(images, key=lambda q: (images[q] & uncovered).bit_count())
        assert images[q] & uncovered, 'The seven-group images do not cover the interval'
        groups.append(q)
        uncovered &= ~images[q]
    groups.sort()
    lines = [
        'import equational_theories.Spectrum.Equation63.IdempotentFiniteBasis',
        'import equational_theories.Spectrum.Equation63.ArithmeticCertificate',
        '',
        '/-! Generated by scripts/spectrum_63_idempotent_bounds.py. A checked',
        'bitmap provides inexpensive access to the finite basis, avoiding',
        'repeated reduction of its exception set at each seed lookup. -/',
        'set_option maxRecDepth 65536',
        'namespace Spectrum.E63.IdempotentFiniteBasis',
        'open ArithmeticCertificate',
        '',
        f'def knownBits : ℕ := {hex(bitmap)}',
        '',
        f'private theorem known_bounded : knownBits % 2^{SMALL} = knownBits :=',
        '  by decide +kernel',
        '',
        'private theorem exceptions_unset : ∀ n ∈ exceptions,',
        '    knownBits.testBit n = false := by decide +kernel',
        '',
        'theorem known_of_bit {n : ℕ} (h : knownBits.testBit n = true) :',
        f'    n < {SMALL} ∧ n ∉ exceptions := by',
        '  refine ⟨bit_lt known_bounded h, ?_⟩',
        '  intro hn',
        '  have := exceptions_unset n hn',
        '  simp_all',
        '',
        'theorem model_of_bit {n : ℕ} (h : knownBits.testBit n = true) :',
        '    Model (Fin n) true :=',
        '  model (known_of_bit h).1 (known_of_bit h).2',
        '',
        'end Spectrum.E63.IdempotentFiniteBasis',
        '',
    ]
    output('IdempotentBitmap.lean', '\n'.join(lines))
    lines = [
        'import equational_theories.Spectrum.Equation63.IdempotentBitmap',
        '',
        '/-! Generated by scripts/spectrum_63_idempotent_bounds.py. Each group',
        'size supplies all available remainders by a single bitmap shift. The',
        'kernel checks coverage of the full interval. -/',
        'set_option maxRecDepth 65536',
        'namespace Spectrum.E63.IdempotentArithmetic',
        'open ArithmeticCertificate IdempotentFiniteBasis',
        '',
        'private def groups : List ℕ := [' + ', '.join(map(str, groups)) + ']',
        '',
        f'private theorem coverage : (cover knownBits groups >>> {SMALL}) %',
        f'    2^{LIMIT-SMALL} = 2^{LIMIT-SMALL}-1 := by decide +kernel',
        '',
        f'theorem decomposition (n : Fin {LIMIT}) (hn : {SMALL} ≤ n.val) :',
        '    ∃ q r : ℕ, 0 < q ∧ q.Coprime 60 ∧ r ≤ q ∧',
        f'      q < {SMALL} ∧ r < {SMALL} ∧',
        '      q ∉ IdempotentFiniteBasis.exceptions ∧',
        '      r ∉ IdempotentFiniteBasis.exceptions ∧ 7*q+r = n.val := by',
        '  obtain ⟨q, r, hq, hc, hrq, hqb, hrb, he⟩ :=',
        '    cover_sound (interval_covered coverage hn n.isLt)',
        '  obtain ⟨hqs, hqe⟩ := known_of_bit hqb',
        '  obtain ⟨hrs, hre⟩ := known_of_bit hrb',
        '  exact ⟨q, r, hq, hc, hrq, hqs, hrs, hqe, hre, he⟩',
        '',
        'end Spectrum.E63.IdempotentArithmetic',
        '',
    ]
    output('IdempotentArithmetic.lean', '\n'.join(lines))
    print(f'{len(known)} small models; {len(missing)} possible exceptions; '
          f'{len(groups)} bitmap images cover {LIMIT-SMALL} orders; tail cutoff {CUTOFF}.')


if __name__ == '__main__':
    main()
