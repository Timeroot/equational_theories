#!/usr/bin/env python3
"""Recount translation-equivariant tables and reproduce Lean count certificates."""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from definability_matrix_counts_check import table_counts
from spectrum_generate import load_equations

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_translation_counts.json"
GENERATED = ROOT / "equational_theories/Definability/Generated"


def translation_tables(n):
    parameters = np.array(list(itertools.product(range(n), repeat=n)), dtype=np.uint8)
    x = np.arange(n)[:, None]
    y = np.arange(n)[None, :]
    return ((x[None, :, :] + parameters[:, (y - x) % n]) % n).astype(np.uint8)


def render(entries):
    lines = [
        "import equational_theories.Definability.TranslationCounting",
        "",
        "/-! Generated by scripts/definability_translation_counts_check.py. -/",
        "",
        "open Law Law.MagmaLaw Magma.Translation",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for e in entries:
        s, t, n = e["source"], e["target"], e["order"]
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_translationCount"
        lines += [
            f"/-- {e['source_count']} source operations, but only {e['target_count']} target operations,",
            f"among all operations commuting with cyclic translations on `ZMod {n}`. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            f"  apply not_termStructuralFromFin_of_cloneFamily_count (op (n := {n})) op_injective",
            "    (fun _ => 0) id comp op_fst op_snd op_comp",
            f"    (fun f : ZMod {n} → ZMod {n} => @Equation{s} (ZMod {n}) ⟨op f⟩)",
            f"    (fun f : ZMod {n} → ZMod {n} => @Equation{t} (ZMod {n}) ⟨op f⟩)",
            "  · intro f hf",
            f"    exact (@Law{s}.models_iff (ZMod {n}) ⟨op f⟩).mpr hf",
            "  · intro f hf",
            f"    exact (@Law{t}.models_iff (ZMod {n}) ⟨op f⟩).mp hf",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    entries = data["candidates"]
    equations = load_equations()
    for n in sorted({e["order"] for e in entries}):
        batch = [e for e in entries if e["order"] == n]
        tables = translation_tables(n)
        assert len(tables) == n**n
        # The first row recovers the complete parameter, proving distinctness here.
        assert len(np.unique(tables[:, 0, :], axis=0)) == len(tables)
        ids = sorted({e[k] for e in batch for k in ("source", "target")})
        counts = table_counts(equations, ids, tables)
        for e in batch:
            assert counts[e["source"]] == e["source_count"]
            assert counts[e["target"]] == e["target_count"]
            assert e["source_count"] > e["target_count"]
        print(
            f"Checked all {len(tables):,} translation-equivariant tables of order {n}, on every assignment."
        )
    selected = data["selected_indices"]
    assert len(set(selected)) == len(selected)
    assert sorted(i for part in data["parts"] for i in part) == sorted(selected)
    assert set().union(*(set(c) for _, c in data["coverage"])) == set(
        range(len(entries))
    )
    for part, indices in enumerate(data["parts"]):
        path = GENERATED / f"TranslationCount{part}.lean"
        text = render([entries[i] for i in indices])
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f"regenerate {path} with --write"
    print(
        f"Reproduced {len(selected)} certificates covering {len(entries)} candidate cells."
    )


if __name__ == "__main__":
    main()
