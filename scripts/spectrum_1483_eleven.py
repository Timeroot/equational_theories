#!/usr/bin/env python3
"""Audit the compact E1483 order-eleven certificates and reproduce their CNFs.

The independent generator checks hashes and the complete case partition. Lean
proves the normalization, defines the same formulas, and checks reconstructed
LRAT proofs. This script is not the logical certificate checker.
"""
import argparse
import hashlib
from itertools import product
import json
import lzma
from pathlib import Path

from definability_1483_sat_check import CASES, cnf_clauses as legacy_clauses

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data/spectrum/1483_order11.json"
DEST = ROOT / "equational_theories/Spectrum/Equation1483/OrderEleven/Certificates"


def name(k, zero):
    return f"Rank{k}{'Inside' if zero else 'Outside'}"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def clauses(k, zero):
    p = lambda x, y, z: 1 + (x * 11 + y) * 11 + z
    row = lambda x, z: 1 + ((11 + x) * 11 + z) * 11
    col = lambda x, z: 1 + ((33 + x) * 11 + z) * 11
    # Replace the old tail sorting with simultaneous image sorting. These are
    # exactly the old sorting clauses, and no other input clauses are removed.
    old_sort = {(-p(0, y, z), -p(0, y + 1, w))
                for y in range(k + 1, 10) for z in range(k + 1) for w in range(z)}
    cs = [c for c in legacy_clauses(k, zero) if tuple(c) not in old_sort]
    for a, b in product(range(11), repeat=2):
        cs.extend([[-row(a, b), col(b, a)], [-col(b, a), row(a, b)]])
    for a, b, z in product(range(11), repeat=3):
        cs.extend([[-p(a, b, z), row(z, b)], [-p(a, b, z), col(z, a)]])
    for y in range(k if zero else k + 1, 10):
        c, d = col(0, y), col(0, y + 1)
        cs.append([c, -d])
        for z, w in product(range(k + 1), repeat=2):
            if w < z:
                cs.append([c, d, -p(0, y, z), -p(0, y + 1, w)])
            if w <= z:
                cs.append([-c, -d, -p(0, y, z), -p(0, y + 1, w)])
    cs.extend([-p(0, 1, z)] for z in range(3, 11))
    return cs


def cnf_bytes(k, zero):
    cs = clauses(k, zero)
    return (f"p cnf 14641 {len(cs)}\n" +
            "".join(" ".join(map(str, c)) + " 0\n" for c in cs)).encode()


def render(rec):
    case = name(rec["rank"], rec["zero_in_image"])
    zero = str(rec["zero_in_image"]).lower()
    formula = f"ImageEncoding.smallNat {rec['rank']} {zero}"
    return f'''import equational_theories.Spectrum.Equation1483.OrderEleven.ImageEncoding
import equational_theories.Spectrum.Status
import SpectrumCertificateData

/- Generated by scripts/spectrum_1483_eleven.py.
CNF SHA-256: {rec['cnf_sha256']}
Compact payload SHA-256: {rec['proof_sha256']} -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
namespace Spectrum.E1483.OrderEleven.Certificates.{case}
open Std.Sat Std.Tactic.BVDecide LRAT Spectrum.CertificateData

private def refutation : Array IntAction :=
  CompactRup.reconstruct (include_binary_xz "../../../../../{rec['certificate']}")
    ({formula})

@[spectrum_native]
theorem checked : check refutation ({formula}) = true := by native_decide

theorem unsat : ({formula}).Unsat := check_sound refutation _ checked
spectrum_assert unsat complete
end Spectrum.E1483.OrderEleven.Certificates.{case}
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="rewrite generated Lean wrappers")
    ap.add_argument("--export-cnf", type=Path)
    ap.add_argument("--check-lean-cnf", type=Path, help="compare independent and Lean exports")
    args = ap.parse_args()
    meta = json.loads(DATA.read_text())
    rows = meta["cases"]
    assert len(rows) == len(CASES)
    assert {(r["rank"], r["zero_in_image"]) for r in rows} == set(CASES)
    for r in rows:
        case = name(r["rank"], r["zero_in_image"])
        cnf = cnf_bytes(r["rank"], r["zero_in_image"])
        assert sha(cnf) == r["cnf_sha256"], (case, "CNF hash")
        assert len(cnf.splitlines()) - 1 == r["clauses"]
        packed = (ROOT / r["certificate"]).read_bytes()
        assert len(packed) == r["compressed_bytes"]
        assert sha(packed) == r["compressed_sha256"], (case, "compressed hash")
        raw = lzma.decompress(packed)
        assert len(raw) == r["proof_bytes"] and sha(raw) == r["proof_sha256"]
        # Check the input count/mask before Lean reconstructs and checks proof steps.
        initial = shift = pos = 0
        while True:
            b = raw[pos]
            pos += 1
            initial |= (b & 127) << shift
            if b < 128:
                break
            shift += 7
            assert shift < 70
        assert initial == 2 * (r["clauses"] + 1) and raw[pos] == ord('m')
        mask = raw[pos + 1:pos + 1 + initial // 2]
        assert len(mask) == initial // 2 and mask[0] == 0
        assert all(b in (0, 1) for b in mask)
        assert sum(mask) == r["selected_input_clauses"]
        if args.export_cnf:
            args.export_cnf.mkdir(parents=True, exist_ok=True)
            (args.export_cnf / (case + ".cnf")).write_bytes(cnf)
        if args.check_lean_cnf:
            assert (args.check_lean_cnf / (case + ".cnf")).read_bytes() == cnf, case
        path = DEST / (case + ".lean")
        if args.write:
            DEST.mkdir(parents=True, exist_ok=True)
            path.write_text(render(r))
        else:
            assert path.read_text() == render(r), path
        print(f"{case}: {r['compressed_bytes']:,} bytes; hashes and formula checked.")
    print(f"All {len(rows)} cases checked; {sum(r['compressed_bytes'] for r in rows):,} bytes.")


if __name__ == "__main__":
    main()
