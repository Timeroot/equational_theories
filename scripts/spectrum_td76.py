#!/usr/bin/env python3
"""Reconstruct and certify the PG(2,9)-based transversal design of order76."""
from itertools import combinations
import argparse
import gzip
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def gf8mul(a,b):
 r=0
 while b:
  if b&1:r^=a
  a<<=1
  if a&8:a^=11
  b>>=1
 return r

def gf9add(a,b):return (a%3+b%3)%3+3*((a//3+b//3)%3)
def gf9mul(a,b):return ((a%3)*(b%3)-(a//3)*(b//3))%3+3*(((a%3)*(b//3)+(a//3)*(b%3))%3)

def oa(q):
 if q==7:return [[b]+[(a+i*b)%7 for i in range(7)] for a in range(7) for b in range(7)]
 if q==8:return [[a^gf8mul(i,b) for i in range(8)] for a in range(8) for b in range(8)]
 if q==9:return [[gf9add(a,gf9mul(i,b)) for i in range(8)] for a in range(9) for b in range(9)]
 raise ValueError(q)

def build():
 data=json.loads((ROOT/"data/spectrum/td76_pbd.json").read_text())
 B=data["base_block"]
 oval=data["oval"];remove=set(B+oval)
 PBD=[[x for x in [(b+i)%91 for b in B] if x not in remove] for i in range(91)]
 PBD.remove([])
 # Check the retained PBD independently.
 pairs=[tuple(sorted(pair)) for row in PBD for pair in combinations(row,2)]
 assert len(pairs)==76*75//2==len(set(pairs))
 seven=[r for r in PBD if len(r)==7];other=[r for r in PBD if len(r)!=7]
 assert set(map(len,other))<={8,9}
 crit=data["critical_points"]
 assert len(seven)==len(crit)
 for x,row in zip(crit,seven):
  assert x in row;row.sort(key=lambda a:a!=x)
 # This is the key diagonal accounting condition.
 counts={x:0 for x in range(91) if x not in remove}
 for row in seven:
  for x in row[1:]:counts[x]+=1
 assert all(c<=1 for c in counts.values())
 rows=[]
 for row in other:
  for r in oa(len(row)):
   if len(set(r))!=1:rows.append([row[x] for x in r])
 for row in seven:
  for r in oa(7):
   if r!=[0]*8:rows.append([row[x] for x in r])
 for x,count in counts.items():
  if count==0:rows.append([x]*8)
 labels={x:i for i,x in enumerate(x for x in range(91) if x not in remove)}
 rows=[[labels[x] for x in row] for row in rows]
 assert len(rows)==76*76
 for i,j in combinations(range(8),2):assert len({(r[i],r[j]) for r in rows})==76*76

 return rows


def generate():
 rows=build()
 raw=''.join(chr(256+x) for row in rows for x in row).encode()
 compressed=gzip.compress(raw,mtime=0)
 code='''import equational_theories.Spectrum.Equation63.TableDesign
import equational_theories.Definability.IncludeGzip
import equational_theories.Spectrum.Status

/-! Generated by scripts/spectrum_td76.py from the PG(2,9) construction
recorded in Sage's OA_8_76. The numerical design is verified in Lean by sorting
all pair images; no pair of blocks is compared against every other block. -/
namespace Spectrum.E63.Design76

private def index : Groups → Fin 8
  | none => 0
  | some i => ⟨i.val+1,by omega⟩

private def entries : Array Char := (include_gzip_str
  "../../../../data/spectrum/td76_coordinates.txt.gz").toList.toArray

def coord (t : Fin (76*76)) (i : Groups) : Fin 76 :=
  ⟨(entries[8*t.val+(index i).val]!.toNat-256)%76,Nat.mod_lt _ (by decide)⟩

@[spectrum_native] theorem checked : TableDesign.Checked coord := by
  unfold TableDesign.Checked
  native_decide

theorem hasTD : HasTD 76 := ⟨TableDesign.design coord checked⟩

spectrum_assert hasTD complete

end Spectrum.E63.Design76
'''
 return {ROOT/'data/spectrum/td76_coordinates.txt.gz':compressed,
         ROOT/'equational_theories/Spectrum/Equation63/Designs/N76.lean':code.encode()}

if __name__=='__main__':
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for path,data in generate().items():
  if args.check:assert path.read_bytes()==data,f'Stale generated file: {path}'
  else:path.write_bytes(data)
