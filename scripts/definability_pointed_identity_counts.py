#!/usr/bin/env python3
"""Check local counts for pointed-block FO-structural separations.

Python selects candidates; the exported results are independently checked in
Lean by PointedIdentityCounting and its small local-count modules. With --scan,
search the current open structural/all board instead of checking the saved data.
"""
import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from definability_counting_upgrades_check import model_indices
from definability_regular_block_counts import group
from spectrum_generate import load_equations, variables

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/definability_pointed_identity_counts.json'


def local_tables(name):
    mul = np.array(group(name))
    n = len(mul)
    params = np.array(list(itertools.product(range(n + 1), repeat=n + 2)))
    tables = np.zeros((len(params), n + 1, n + 1), dtype=np.uint8)
    scale = np.concatenate([mul, np.full((n, 1), n)], axis=1)
    inv = [next(b for b in range(n) if mul[a, b] == 0) for a in range(n)]
    for a in range(n):
        for b in range(n):
            tables[:, a, b] = scale[a, params[:, mul[inv[a], b]]]
        tables[:, a, n] = scale[a, params[:, n]]
        tables[:, n, a] = scale[a, params[:, n + 1]]
    tables[:, n, n] = n
    return params, tables


def counts(equations, name, sources, targets):
    params, tables = local_tables(name)
    n = tables.shape[1] - 1
    row = np.arange(len(params))

    def evaluate(term):
        if isinstance(term, str):
            return np.zeros(len(params), dtype=int)
        return tables[row, evaluate(term[0]), evaluate(term[1])]

    lower = {}
    for a in sources:
        left, right = equations[a - 1]
        assert left == 'x' and right[0] == 'x' and variables(right[1]) == {'y'}
        lower[a] = int(((params[:, n] == 0) & (evaluate(right[1]) == n)).sum())
    upper = {}
    for b in targets:
        assert (variables(equations[b - 1][0]) | variables(equations[b - 1][1])) <= {'x', 'y', 'z'}
        upper[b] = len(model_indices(equations, tables, b))
    return lower, upper


def emit_lean(equations, entries):
    """Emit the small arithmetic lemmas and a nonredundant catalogue."""
    out = ROOT / 'equational_theories/Definability'
    groups = sorted({x['group'] for x in entries})
    catalogue = [f'import equational_theories.Definability.PointedIdentityCounts{g}' for g in groups]
    catalogue += ['', '/-! FO-structural negatives on arbitrary carriers, by pointed-block',
                  'amplification and compactness. The local groups are counting devices;',
                  'these theorems do not assert finite FO-structural counterexamples. -/',
                  '', 'open Law Law.MagmaLaw', '']
    if 'C4' in groups:
        catalogue += ['local instance : Fact (1 < 4) := ⟨by decide⟩', '']

    def term(t):
        return '(.Leaf 0)' if isinstance(t, str) else f'(.Fork {term(t[0])} {term(t[1])})'

    for g in groups:
        selected = [x for x in entries if x['group'] == g]
        sources = {x['source']: x['source_count'] for x in selected}
        targets = {x['target']: x['target_count'] for x in selected}
        tactic = 'decide +kernel' if g == 'C2' else 'native_decide'
        lines = ['import equational_theories.Definability.PointedIdentityCounting', '',
                 '/-! Local counts, generated by `scripts/definability_pointed_identity_counts.py`.',
                 ('The C2 counts are evaluated by the kernel.' if g == 'C2' else
                  'These larger counts use native_decide; the amplification theorem is symbolic.'),
                 '-/', 'set_option maxRecDepth 100000',
                 'set_option maxHeartbeats 40000000', '', 'open Law Law.MagmaLaw',
                 f'namespace PointedIdentityCounting.{g}', '']
        if g == 'C4':
            lines += ['local instance : Fact (1 < 4) := ⟨by decide⟩', '']
        lines += [f'abbrev H := Multiplicative (ZMod {g[1:]})', '']
        for a, count in sorted(sources.items()):
            lines += [f'abbrev term{a} : FreeMagma ℕ := {term(equations[a-1][1][1])}',
                      f'theorem source{a} : sourceCount (H := H) term{a} = {count} := by {tactic}', '']
        for b, count in sorted(targets.items()):
            lines += [f'theorem target{b} : targetCount (H := H) Law{b} = {count} := by {tactic}', '']
        lines += [f'end PointedIdentityCounting.{g}', '']
        (out / f'PointedIdentityCounts{g}.lean').write_text('\n'.join(lines))
    for x in entries:
        a, b, g = x['source'], x['target'], x['group']
        ns = f'PointedIdentityCounting.{g}'
        name = f'Equation{b}_not_StructuralFrom_Equation{a}_pointedIdentity{g}'
        catalogue += [f'theorem {name} :', f'    ¬ Law{b}.StructuralFrom Law{a} :=',
                      f'  PointedIdentityCounting.not_structural (H := {ns}.H) (t := {ns}.term{a})',
                      f'    (by rw [{ns}.target{b}]; decide)',
                      f'    (by rw [{ns}.target{b}, {ns}.source{a}]; decide)', '']
        if g == 'C2':
            catalogue += [f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
                          '#guard_msgs (whitespace := lax) in', f'#print axioms {name}', '']
    (out / 'PointedIdentityCountingCatalogue.lean').write_text('\n'.join(catalogue))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scan', action='store_true')
    parser.add_argument('--emit-lean', action='store_true')
    args = parser.parse_args()
    equations = load_equations()
    if args.scan:
        board = json.loads((ROOT / 'docs/definability_open/snapshot.json').read_text())['boards']['structural/all']
        sources = [int(a) for a in board['classes'] if equations[int(a)-1][0] == 'x'
                   and isinstance(equations[int(a)-1][1], tuple)
                   and equations[int(a)-1][1][0] == 'x'
                   and variables(equations[int(a)-1][1][1]) == {'y'}]
        pairs = [(a, b) for a in sources for bs in board['open_rows'].get(str(a), {}).values()
                 for b in bs if (variables(equations[b-1][0]) | variables(equations[b-1][1])) <= {'x', 'y', 'z'}]
        result = []
        for name in ['C2', 'C3', 'C4', 'V4']:
            lower, upper = counts(equations, name, sources, sorted({b for _, b in pairs}))
            result.extend(dict(group=name, source=a, target=b, source_count=lower[a], target_count=upper[b])
                          for a, b in pairs if 0 < upper[b] < lower[a])
        print(json.dumps(result, indent=2))
    else:
        data = json.loads(DATA.read_text())
        if args.emit_lean:
            emit_lean(equations, data['certificates'])
            return
        for name in sorted({x['group'] for x in data['certificates']}):
            entries = [x for x in data['certificates'] if x['group'] == name]
            lower, upper = counts(equations, name, sorted({x['source'] for x in entries}),
                                  sorted({x['target'] for x in entries}))
            for x in entries:
                assert lower[x['source']] == x['source_count'], x
                assert upper[x['target']] == x['target_count'], x
                assert 0 < x['target_count'] < x['source_count'], x
            print(f'{name}: checked {len(entries)} local-count certificates')


if __name__ == '__main__':
    main()
