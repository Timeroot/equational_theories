#!/usr/bin/env python3
"""Generate and reproduce the homogeneous E1516 order-29 LRAT certificates.

The solver supplies proof data only. Encoding.lean proves that a normalized
operation satisfies this CNF, and the generated Lean modules check every LRAT
step before applying check_sound. A solver's UNSAT status alone is never used.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import gzip
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / '.cache/fo1516-formal'
DEST = ROOT / 'equational_theories/Definability/Homogeneous1516/Cases'
DATA = ROOT / 'data/definability/1516_homogeneous_lrat'
MANIFEST = DATA / 'manifest.json'
CASES = (2, 4, 7, 12)  # The multiplier 28 = -1 is excluded algebraically.


def cnf(s):
    p = 29
    F = lambda x, y: 1+p*x+y
    C = lambda c: 842+c
    inv = lambda x: pow(x, -1, p)
    cs = []
    for x in range(p):
        cs.append([F(x, y) for y in range(p)])
        cs.extend([-F(x, y), -F(x, z)] for y in range(p) for z in range(y+1, p))
    for y in range(p):
        cs.append([F(x, y) for x in range(p)])
        cs.extend([-F(x, y), -F(z, y)] for x in range(p) for z in range(x+1, p))
    cs.extend([[C(c) for c in range(p)], [-C(0)]])
    cs.extend([-C(c), -C(d)] for c in range(p) for d in range(c+1, p))
    cs.extend([[F(1, s)], [-F(0, 0)]])
    cs.extend([-C(c), F(c*c*inv(s) % p, 0)] for c in range(1, p))
    cs.extend([-C(c), -F(0, u), F(u, inv(c))] for c in range(1, p) for u in range(p))
    cs.extend([-F(t, u), -F(u, v), F(inv(s*t % p)*v % p, inv(s*t % p))]
              for t in range(1, p) for u in range(p) for v in range(p))
    cs.extend([-C(c), -F(t, c*t % p)] for t in range(1, p) for c in range(1, p))
    cs.extend([-F(t, a), -F(u, a*u*inv(t) % p)]
              for t in range(1, p) for u in range(1, t) for a in range(p))
    return [c for c in cs if not any(-x in c for x in c)]


def cnf_bytes(s):
    cs = cnf(s)
    return (f'p cnf 870 {len(cs)}\n' + ''.join(' '.join(map(str, c))+' 0\n' for c in cs)).encode()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def render(record):
    s = record['multiplier']
    return f'''import equational_theories.Definability.Homogeneous1516.Encoding
import equational_theories.Definability.IncludeGzip
import equational_theories.Spectrum.Status

/- Generated by scripts/fo_1516_certificates.py.
CNF SHA-256: {record['cnf_sha256']}
Expanded LRAT SHA-256: {record['proof_sha256']} -/
set_option maxRecDepth 20000
set_option maxHeartbeats 10000000
namespace Definability.Homogeneous1516.Refutation
open Std.Sat Std.Tactic.BVDecide LRAT

private def proof{s} : Array IntAction :=
  (parseLRATProof (include_gzip_str "../../../../data/definability/1516_homogeneous_lrat/s{s}.lrat.gz").toUTF8).toOption.getD #[]

@[spectrum_native]
theorem check{s} : check proof{s} (Encoding.natFormula {s}) = true := by
  native_decide

theorem unsat{s} : (Encoding.natFormula {s}).Unsat :=
  check_sound proof{s} _ check{s}

end Definability.Homogeneous1516.Refutation
'''


def solve(s, solver, seconds):
    data = cnf_bytes(s)
    source = WORK / f's{s}.cnf'
    proof = WORK / f's{s}.lrat'
    source.write_bytes(data)
    with (WORK / f's{s}.solver.log').open('w') as log:
        result = subprocess.run([solver, '--quiet', '--shrink=0', '--lrat', '--no-binary',
                                 '-t', str(seconds), str(source), str(proof)], stdout=log,
                                stderr=subprocess.STDOUT, cwd=ROOT)
    if result.returncode != 20:
        raise RuntimeError(f'Multiplier {s}: solver did not produce an UNSAT result; inspect log')
    raw = proof.read_bytes()
    compressed = gzip.compress(raw, mtime=0)
    (DATA / f's{s}.lrat.gz').write_bytes(compressed)
    record = dict(multiplier=s, clauses=len(cnf(s)), cnf_sha256=sha(data),
                  proof_sha256=sha(raw), proof_bytes=len(raw),
                  compressed_sha256=sha(compressed), compressed_bytes=len(compressed))
    (DEST / f'S{s}.lean').write_text(render(record))
    print(f'Multiplier {s}: proof generated ({len(raw):,} bytes; gzip {len(compressed):,}). '
          'Lean replay still required.', flush=True)
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--solve', action='store_true')
    parser.add_argument('--solver', default='/usr/local/bin/cadical')
    parser.add_argument('--seconds', type=int, default=600)
    parser.add_argument('--jobs', type=int, default=2)
    parser.add_argument('--export-cnf', type=Path)
    args = parser.parse_args()
    for p in (WORK, DATA, DEST):
        p.mkdir(parents=True, exist_ok=True)
    if args.solve:
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            records = list(pool.map(lambda s: solve(s, args.solver, args.seconds), CASES))
        MANIFEST.write_text(json.dumps(dict(prime=29, law=1516, cases=records), indent=2)+'\n')
    else:
        records = json.loads(MANIFEST.read_text())['cases']
        assert [r['multiplier'] for r in records] == list(CASES)
        for r in records:
            s = r['multiplier']
            data = cnf_bytes(s)
            compressed = (DATA / f's{s}.lrat.gz').read_bytes()
            raw = gzip.decompress(compressed)
            assert (sha(data), len(cnf(s))) == (r['cnf_sha256'], r['clauses'])
            assert (sha(raw), len(raw)) == (r['proof_sha256'], r['proof_bytes'])
            assert (sha(compressed), len(compressed)) == (r['compressed_sha256'], r['compressed_bytes'])
            assert (DEST / f'S{s}.lean').read_text() == render(r)
        print('All four encodings, proof hashes, and generated Lean sources match.')
    if args.export_cnf:
        args.export_cnf.mkdir(parents=True, exist_ok=True)
        for s in CASES:
            (args.export_cnf / f's{s}.cnf').write_bytes(cnf_bytes(s))


if __name__ == '__main__':
    main()
