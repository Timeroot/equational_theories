#!/usr/bin/env python3
"""Audit or reproduce the small-order exclusions found during the positive-model searches.

Most CNFs use the unrestricted Lean SmallOrders encoding. E1279 order twelve
is delegated to its smaller squaring-permutation decomposition. The search
requires no extra assumption of idempotence or commutativity. Ordinary builds
only replay the compact RUP certificates; no external solver is trusted.
"""

import argparse
import json
import lzma
from pathlib import Path
import resource
import subprocess
import sys
import time

from spectrum_63_ten_certificate import ROOT, TRIM, sha
from spectrum_small_orders import clauses, cnf_bytes, render, variables

MANIFEST = ROOT / "data/spectrum/positive_target_exclusions_20261011.json"


CASES = [(1076, 9), (1076, 11), (704, 12), (1516, 12)]


def wrapper(record):
    return render(record).replace(
        "Generated by scripts/spectrum_small_orders.py.",
        "Generated by scripts/spectrum_positive_target_exclusions.py.",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solve", action="store_true")
    parser.add_argument("--only", type=int, nargs="+", help="Regenerate only these laws")
    parser.add_argument("--write", action="store_true", help="Refresh Lean wrappers")
    parser.add_argument("--seconds", type=int, default=600)
    args = parser.parse_args()
    if args.only and not args.solve:
        parser.error("--only requires --solve")
    if args.seconds <= 0:
        parser.error("--seconds must be positive")
    delegated = [sys.executable, str(ROOT / "scripts/spectrum_1279_twelve.py")]
    if args.solve and (not args.only or 1279 in args.only):
        delegated += ["--solve", "--seconds", str(args.seconds)]
    elif args.write:
        delegated += ["--write"]
    subprocess.run(delegated, cwd=ROOT, check=True)
    if args.solve:
        work = ROOT / ".cache/positive-target-exclusions"
        work.mkdir(parents=True, exist_ok=True)
        trim = work / "TrimBinary.lean"
        trim.write_text(TRIM.replace('".trimmed"', '".trimmed.bin"').replace(
            "trimmed false", "trimmed true"))
        packer = work / "compact-rup"
        subprocess.run(["g++", "-O3", "-std=c++17",
                        str(ROOT / "scripts/spectrum_compact_rup.cpp"),
                        "-o", str(packer)], check=True)
        records = []
        previous = {(r["law"], r["order"]): r for r in json.loads(MANIFEST.read_text())} if MANIFEST.exists() else {}
        for law, n in CASES:
            if args.only and law not in args.only:
                records.append(previous[law, n])
                continue
            cnf = cnf_bytes(law, n)
            stem = work / f"e{law}_{n}"
            stem.with_suffix(".cnf").write_bytes(cnf)
            proof = stem.with_suffix(".lrat")

            def limit_proof():
                resource.setrlimit(resource.RLIMIT_FSIZE, (1024**3, 1024**3))

            start = time.monotonic()
            with stem.with_suffix(".log").open("w") as log:
                result = subprocess.run(
                    ["cadical", "--lrat", "-t", str(args.seconds),
                     str(stem.with_suffix(".cnf")), str(proof)],
                    stdout=log, stderr=subprocess.STDOUT,
                    timeout=args.seconds + 20, preexec_fn=limit_proof)
            if result.returncode != 20:
                raise SystemExit(f"E{law}/{n}: no complete refutation; nothing installed")
            elapsed = time.monotonic() - start
            subprocess.run(["lake", "env", "lean", "--run", str(trim), str(proof)],
                           cwd=ROOT, check=True)
            compact = stem.with_suffix(".rup")
            with Path(str(proof) + ".trimmed.bin").open("rb") as inp:
                subprocess.run([str(packer), "--input-mask", str(compact)],
                               stdin=inp, check=True)
            payload = compact.read_bytes()
            compressed = lzma.compress(payload, preset=6)
            if len(compressed) > 10 * 1024**2:
                raise SystemExit(f"E{law}/{n}: compressed proof exceeds the 10 MiB cap")
            dest = ROOT / f"data/spectrum/positive_target_rup/e{law}_{n}.rup.xz"
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(compressed)
            records.append(dict(
                law=law, order=n, theorem=f"Spectrum.not_order_{law}_{n}",
                variables=variables(law, n), clauses=len(clauses(law, n)),
                cnf_sha256=sha(cnf), proof_sha256=sha(payload),
                compressed_sha256=sha(compressed), proof_bytes=len(payload),
                compressed_bytes=len(compressed), search_seconds=round(elapsed, 3),
                certificate=str(dest.relative_to(ROOT)), format="compact-rup-xz",
                checking="Lean LRAT.check_sound with registered native_decide; no sorry"))
        MANIFEST.write_text(json.dumps(records, indent=2) + "\n")
    records = json.loads(MANIFEST.read_text())
    assert [(r["law"], r["order"]) for r in records] == CASES
    for r in records:
        compressed = (ROOT / r["certificate"]).read_bytes()
        payload = lzma.decompress(compressed)
        assert sha(cnf_bytes(r["law"], r["order"])) == r["cnf_sha256"]
        assert sha(compressed) == r["compressed_sha256"]
        assert sha(payload) == r["proof_sha256"]
        assert len(compressed) == r["compressed_bytes"]
        assert len(payload) == r["proof_bytes"]
        dest = ROOT / f"equational_theories/Spectrum/SmallOrders/Certificates/E{r['law']}N{r['order']}.lean"
        if args.write or args.solve:
            dest.write_text(wrapper(r))
        else:
            assert dest.read_text() == wrapper(r), f"Stale wrapper: {dest}"
        print(f"E{r['law']}/{r['order']}: hashes and wrapper match; "
              f"{len(compressed):,} compressed bytes")


if __name__ == "__main__":
    main()
