#!/usr/bin/env python3
"""Recount higher-arity relation certificates and reproduce their Lean source."""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from definability_matrix_counts_check import table_counts
from spectrum_generate import load_equations

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_finite_relation_counts.json"
OUTPUT = ROOT / "equational_theories/Definability/Generated/FiniteRelationCount.lean"


def relation_tables(arity, code):
    tables = np.array(
        list(itertools.product(range(3), repeat=9)), dtype=np.uint8
    ).reshape(-1, 3, 3)
    tuples = list(itertools.product(range(3), repeat=arity))
    membership = np.array([bool(code >> i & 1) for i in range(len(tuples))])
    relation = [row for i, row in enumerate(tuples) if membership[i]]
    active = np.arange(len(tables))
    for x in relation:
        for y in relation:
            outputs = np.zeros(len(active), dtype=np.int64)
            for i in range(arity):
                outputs = 3 * outputs + tables[active, x[i], y[i]]
            active = active[membership[outputs]]
    return tables[active], relation


def render(entries):
    lines = [
        "import equational_theories.Definability.FiniteRelationCounting",
        "",
        "/-! Generated by scripts/definability_finite_relation_counts_check.py. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for e in entries:
        source, target, arity = e["source"], e["target"], e["arity"]
        name = f"Equation{target}_not_termStructuralFromFin_Equation{source}_finiteRelationCount"
        code = " + ".join(f"{3 ** (arity - 1 - i)} * (v {i}).val" for i in range(arity))
        lines += [
            f"/-- {e['source_count']} source operations and {e['target_count']} target operations preserve this relation. -/",
            f"theorem {name} : ¬ Law{target}.TermStructuralFromFin Law{source} := by",
            f"  let R : (Fin {arity} → Fin 3) → Prop := fun v =>",
            f"    Nat.testBit {e['relation_code']} ({code}) = true",
            f"  apply not_termStructuralFromFin_of_cloneFamily_count (@FiniteRelationCounting.op (Fin 3) (Fin {arity}) R)",
            "    (FiniteRelationCounting.op_injective R) (FiniteRelationCounting.fst R)",
            "    (FiniteRelationCounting.snd R) FiniteRelationCounting.comp",
            "    (FiniteRelationCounting.op_fst R) (FiniteRelationCounting.op_snd R)",
            "    FiniteRelationCounting.op_comp",
            f"    (fun p : FiniteRelationCounting.P R => @Equation{source} (Fin 3) ⟨FiniteRelationCounting.op p⟩)",
            f"    (fun p : FiniteRelationCounting.P R => @Equation{target} (Fin 3) ⟨FiniteRelationCounting.op p⟩)",
            "  · intro p hp",
            f"    exact (@Law{source}.models_iff (Fin 3) ⟨FiniteRelationCounting.op p⟩).mpr hp",
            "  · intro p hp",
            f"    exact (@Law{target}.models_iff (Fin 3) ⟨FiniteRelationCounting.op p⟩).mp hp",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def check_file(data_path, output_path, write=False):
    entries = json.loads(data_path.read_text())["candidates"]
    equations = load_equations()
    for e in entries:
        tables, relation = relation_tables(e["arity"], e["relation_code"])
        assert [list(row) for row in relation] == e["relation"]
        assert len(tables) == e["family_count"]
        counts = table_counts(equations, [e["source"], e["target"]], tables)
        assert counts[e["source"]] == e["source_count"]
        assert counts[e["target"]] == e["target_count"]
        assert e["source_count"] > e["target_count"]
        print(
            f"Checked E{e['source']} → E{e['target']}: {e['source_count']} > {e['target_count']}."
        )
    rendered = render(entries)
    if write:
        output_path.write_text(rendered)
    else:
        assert output_path.read_text() == rendered, "regenerate with --write"
    print(f"Reproduced {len(entries)} higher-arity relation certificates.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--only", help="check only data filenames containing this text")
    args = parser.parse_args()
    sources = [(DATA, OUTPUT)]
    higher = ROOT / "data/definability_higher_relation_counts.json"
    if higher.exists():
        sources.append((higher, OUTPUT.with_name("HigherRelationCount.lean")))
    selected = [(data, output) for data, output in sources
                if not args.only or args.only in data.name]
    if not selected:
        parser.error("no matching relation certificate file")
    for data, output in selected:
        check_file(data, output, args.write)


if __name__ == "__main__":
    main()
