#!/usr/bin/env python3
"""Recount all three-element operations and reproduce the model-count proofs."""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from spectrum_generate import load_equations, variables


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_table_counts.json"
OUTPUT = ROOT / "equational_theories/Definability/Generated/PartialTableCount.lean"


def count_models(equations, ids, n):
    """Evaluate every variable assignment on every labeled n-element table."""
    tables = np.array(
        list(itertools.product(range(n), repeat=n * n)), dtype=np.uint8
    ).reshape(-1, n, n)
    index = np.arange(len(tables))[:, None]
    counts = {}
    for law in ids:
        lhs, rhs = equations[law - 1]
        names = sorted(variables(lhs) | variables(rhs))
        assignments = np.array(
            list(itertools.product(range(n), repeat=len(names))), dtype=np.uint8
        ).T
        cache = {v: assignments[i][None, :] for i, v in enumerate(names)}

        def evaluate(term):
            if term not in cache:
                cache[term] = tables[index, evaluate(term[0]), evaluate(term[1])]
            return cache[term]

        equality = np.broadcast_to(
            evaluate(lhs) == evaluate(rhs), (len(tables), assignments.shape[1])
        )
        counts[law] = int(np.all(equality, axis=1).sum())
    return counts


def render(entries, n):
    lines = [
        "import equational_theories.Definability.ModelCounting",
        "",
        "/-! Generated by scripts/definability_table_counts_check.py.",
        "All labeled operations on Fin 3 are counted; products are not enumerated. -/",
        "",
        "open Law Law.MagmaLaw",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for entry in entries:
        s, t = entry["source"], entry["target"]
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_tableCount"
        lines += [
            f"/-- {entry['source_count']} labeled source tables, but only",
            f"{entry['target_count']} target tables, on a carrier of size {n}. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            "  apply not_termStructuralFromFin_of_table_count",
            f"    (fun f : Fin {n} → Fin {n} → Fin {n} => @Equation{s} (Fin {n}) ⟨f⟩)",
            f"    (fun f : Fin {n} → Fin {n} → Fin {n} => @Equation{t} (Fin {n}) ⟨f⟩)",
            "  · intro f hf",
            f"    exact (@Law{s}.models_iff (Fin {n}) ⟨f⟩).mpr hf",
            "  · intro f hf",
            f"    exact (@Law{t}.models_iff (Fin {n}) ⟨f⟩).mp hf",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    n, entries = data["order"], data["candidates"]
    assert n == 3
    ids = sorted({entry[key] for entry in entries for key in ("source", "target")})
    counts = count_models(load_equations(), ids, n)
    for entry in entries:
        assert counts[entry["source"]] == entry["source_count"]
        assert counts[entry["target"]] == entry["target_count"]
        assert entry["source_count"] > entry["target_count"]
    text = render(entries, n)
    if args.write:
        OUTPUT.write_text(text)
    else:
        assert OUTPUT.read_text() == text, "regenerate with --write"
    print(
        f"All {n ** (n * n):,} labeled tables checked for {len(ids)} laws; {len(entries)} inequalities verified."
    )


if __name__ == "__main__":
    main()
