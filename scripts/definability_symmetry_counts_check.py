#!/usr/bin/env python3
"""Recount operation tables with unary symmetries and reproduce Lean proofs."""

import argparse
import itertools
import json
from pathlib import Path

import numpy as np

from definability_matrix_counts_check import table_counts
from spectrum_generate import load_equations

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_symmetry_counts.json"
GENERATED = ROOT / "equational_theories/Definability/Generated"


def permutation_tables(permutation):
    n = len(permutation)
    seen, orbits, choices = set(), [], []
    for x, y in itertools.product(range(n), repeat=2):
        if (x, y) in seen:
            continue
        orbit, u, v = [], x, y
        while (u, v) not in seen:
            seen.add((u, v))
            orbit.append((u, v))
            u, v = permutation[u], permutation[v]
        orbits.append(orbit)
        allowed = []
        for z in range(n):
            w = z
            for _ in orbit:
                w = permutation[w]
            if w == z:
                allowed.append(z)
        choices.append(allowed)
    parameters = np.array(list(itertools.product(*choices)), dtype=np.uint8)
    tables = np.empty((len(parameters), n, n), dtype=np.uint8)
    perm = np.array(permutation)
    for i, orbit in enumerate(orbits):
        values = parameters[:, i]
        for x, y in orbit:
            tables[:, x, y] = values
            values = perm[values]
    assert np.all(tables[:, perm[:, None], perm[None, :]] == perm[tables])
    return tables


def unary_tables(unary):
    n = len(unary)
    tables = np.array(
        list(itertools.product(range(n), repeat=n * n)), dtype=np.uint8
    ).reshape(-1, n, n)
    u = np.array(unary)
    return tables[np.all(tables[:, u[:, None], u[None, :]] == u[tables], axis=(1, 2))]


def render(entries):
    lines = [
        "import equational_theories.Definability.FixedPointCycleCounting",
        "import equational_theories.Definability.FreeOrbitCounting",
        "import equational_theories.Definability.UnaryMapCounting",
        "",
        "/-! Generated by scripts/definability_symmetry_counts_check.py. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    if any(e["kind"] == "fixed_points_orbit" for e in entries):
        lines.insert(
            0, "import equational_theories.Definability.FixedPointsOrbitCounting"
        )
    if any(e["kind"] == "unary_family" for e in entries):
        lines.insert(
            0, "import equational_theories.Definability.UnaryMapFamilyCounting"
        )
    for e in entries:
        s, t = e["source"], e["target"]
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_symmetryCount"
        lines += [
            f"/-- {e['source_count']} compatible source operations, but only {e['target_count']} target operations. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
        ]
        if e["kind"] in ("unary", "unary_family"):
            if e["kind"] == "unary":
                ns, utype, explicit = "UnaryMap", "Fin 3 → Fin 3", "(Fin 3) u"
                values = ", ".join(map(str, e["unary"]))
            else:
                size = len(e["unaries"])
                ns, utype, explicit = (
                    "UnaryMapFamily",
                    f"Fin {size} → Fin 3 → Fin 3",
                    f"(Fin 3) (Fin {size}) u",
                )
                values = ", ".join(
                    "![" + ", ".join(map(str, u)) + "]" for u in e["unaries"]
                )
            lines += [
                f"  let u : {utype} := ![{values}]",
                f"  apply not_termStructuralFromFin_of_cloneFamily_count (@{ns}.op {explicit})",
                f"    ({ns}.op_injective u) ({ns}.fst u) ({ns}.snd u) {ns}.comp",
                f"    ({ns}.op_fst u) ({ns}.op_snd u) {ns}.op_comp",
            ]
            parameter, carrier, op = f"{ns}.P u", "Fin 3", f"{ns}.op"
        else:
            if e["kind"] == "fixed_cycle":
                ns, args, type_args = (
                    "FixedPointCycle",
                    f"(n := {len(e['permutation']) - 1})",
                    str(len(e["permutation"]) - 1),
                )
            elif e["kind"] == "fixed_points_orbit":
                ns, args, type_args = (
                    "FixedPointsOrbit",
                    "(K := Fin 2) (n := 2)",
                    "(Fin 2) 2",
                )
            else:
                assert e["permutation"] == [1, 0, 3, 2]
                ns, args, type_args = "FreeOrbit", "(n := 2) (k := 2)", "2 2"
            lines += [
                f"  apply not_termStructuralFromFin_of_cloneFamily_count ({ns}.op {args}) {ns}.op_injective",
                f"    {ns}.fst {ns}.snd {ns}.comp {ns}.op_fst {ns}.op_snd {ns}.op_comp",
            ]
            parameter, carrier, op = (
                f"{ns}.P {type_args}",
                f"{ns}.A {type_args}",
                f"{ns}.op",
            )
        lines += [
            f"    (fun p : {parameter} => @Equation{s} ({carrier}) ⟨{op} p⟩)",
            f"    (fun p : {parameter} => @Equation{t} ({carrier}) ⟨{op} p⟩)",
            "  · intro p hp",
            f"    exact (@Law{s}.models_iff ({carrier}) ⟨{op} p⟩).mpr hp",
            "  · intro p hp",
            f"    exact (@Law{t}.models_iff ({carrier}) ⟨{op} p⟩).mp hp",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    entries = data["candidates"]
    equations = load_equations()

    def family_key(e):
        return e["kind"], json.dumps(
            e.get("unaries", e.get("unary", e.get("permutation")))
        )

    for kind, encoded in sorted({family_key(e) for e in entries}):
        unary = json.loads(encoded)
        batch = [e for e in entries if family_key(e) == (kind, encoded)]
        if kind == "unary_family":
            tables = unary_tables(unary[0])
            for u in map(np.array, unary[1:]):
                tables = tables[
                    np.all(tables[:, u[:, None], u[None, :]] == u[tables], axis=(1, 2))
                ]
        else:
            tables = (
                unary_tables(unary) if kind == "unary" else permutation_tables(unary)
            )
        assert len(np.unique(tables.reshape(len(tables), -1), axis=0)) == len(tables)
        ids = sorted({e[k] for e in batch for k in ("source", "target")})
        counts = table_counts(equations, ids, tables)
        for e in batch:
            assert counts[e["source"]] == e["source_count"]
            assert counts[e["target"]] == e["target_count"]
            assert e["source_count"] > e["target_count"]
        print(f"Checked {len(tables):,} compatible tables for unary map {unary}.")
    selected = data["selected_indices"]
    assert len(set(selected)) == len(selected)
    assert sorted(i for part in data["parts"] for i in part) == sorted(selected)
    assert set().union(*(set(c) for _, c in data["coverage"])) == set(
        range(len(entries))
    )
    for part, indices in enumerate(data["parts"]):
        path = GENERATED / f"SymmetryCount{part}.lean"
        text = render([entries[i] for i in indices])
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f"regenerate {path} with --write"
    print(
        f"Reproduced {len(selected)} certificates covering {len(entries)} candidate cells."
    )


if __name__ == "__main__":
    main()
