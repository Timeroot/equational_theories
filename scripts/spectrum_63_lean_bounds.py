#!/usr/bin/env python3
"""Generate a kernel-checked finite basis for the E63 cofinite induction.

Arithmetic discovery is untrusted: the emitted Lean invokes proved construction
rules and checks coverage of the complete finite interval. No UNSAT certificate
is used by the positive construction.
"""
from math import gcd
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXCEPTIONS = [2, 6, 10, 14, 18, 26, 30, 38, 42, 90, 158]
SPECIAL = [
    22,
    29,
    34,
    41,
    46,
    47,
    58,
    62,
    70,
    71,
    74,
    106,
    110,
    114,
    118,
    179,
    190,
    194,
    197,
    202,
    254,
    257,
    269,
]
TABLES = [46, 47, 62, 74, 114, 118]


def main():
    known = {0, 1}
    proofs = {0: "Law63.hasModel_zero", 1: "Law63.hasModel_one"}
    for n in range(2, 1608):
        root = next((b for b in range(n) if (b**5 + b**4 + 1) % n == 0), None)
        ab = next(
            (
                (a, n // a)
                for a in sorted(known)
                if 1 < a < n and n % a == 0 and n // a in known
            ),
            None,
        )
        qr = next(
            (
                (q, n - 7 * q)
                for q in sorted(known)
                if q > 1
                and gcd(q, 60) == 1
                and 0 <= n - 7 * q <= q
                and n - 7 * q in known
            ),
            None,
        )
        if n == 4:
            proof = "pointed4.hasModel"
        elif n == 8:
            proof = "pointed8.hasModel"
        elif ab:
            a, b = ab
            proof = f"c{a}.mul c{b}"
        elif root is not None:
            proof = f"modular {n} {root} (by decide)"
        elif qr:
            q, r = qr
            proof = f"seven (by decide) (by decide) (by decide) c{q} c{r}"
        elif n in SPECIAL:
            proof = f"model{n}"
        else:
            assert n in EXCEPTIONS, f"Unconstructed order {n}"
            continue
        known.add(n)
        proofs[n] = proof
    assert set(range(1608)) - known == set(EXCEPTIONS)
    lines = ["import equational_theories.Spectrum.Equation63.Construction"]
    lines += [
        f"import equational_theories.Spectrum.Equation63.Witnesses.N{n}" for n in TABLES
    ]
    lines += [
        "import Mathlib.Data.List.Basic",
        "",
        "/-! Generated by scripts/spectrum_63_lean_bounds.py. Each entry applies a",
        "proved construction; coverage of 0..1607 is checked by kernel reduction. -/",
        "set_option maxRecDepth 65536",
        "set_option maxHeartbeats 0",
        "namespace Spectrum.E63.FiniteBasis",
        "open Law Law.MagmaLaw",
        "",
    ]
    for n, proof in proofs.items():
        lines += [f"private theorem c{n} : Law63.HasModel {n} := {proof}"]
    literal = ", ".join(map(str, sorted(known)))
    lines += [
        "",
        f"private def known : List ℕ := [{literal}]",
        "",
        "private theorem models : List.Forall Law63.HasModel known :=",
        "  ⟨" + ", ".join(f"c{n}" for n in sorted(known)) + "⟩",
        "",
        "private theorem known_eq : known = (List.range 1608).filter",
        "    (fun n => decide (n ∉ ({"
        + ", ".join(map(str, EXCEPTIONS))
        + "} : Finset ℕ))) :=",
        "  by decide +kernel",
        "",
        "private theorem coverage (n : Fin 1608)",
        "    (he : n.val ∉ ({"
        + ", ".join(map(str, EXCEPTIONS))
        + "} : Finset ℕ)) : n.val ∈ known := by",
        "  rw [known_eq, List.mem_filter]",
        "  exact ⟨List.mem_range.mpr n.isLt, by simpa using he⟩",
        "",
        "theorem model {n : ℕ} (hn : n < 1608)",
        "    (he : n ∉ ({"
        + ", ".join(map(str, EXCEPTIONS))
        + "} : Finset ℕ)) : Law63.HasModel n :=",
        "  (List.forall_iff_forall_mem.mp models) n (coverage ⟨n,hn⟩ he)",
        "",
        "end Spectrum.E63.FiniteBasis",
        "",
    ]
    (ROOT / "equational_theories/Spectrum/Equation63/FiniteBasis.lean").write_text(
        "\n".join(lines)
    )
    print(
        f"Generated {len(known)} proved construction entries; {len(EXCEPTIONS)} exceptions."
    )


if __name__ == "__main__":
    main()
