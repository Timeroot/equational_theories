#!/usr/bin/env python3
"""Independently recompute saved affine triples and reproduce Lean certificates."""

import argparse
from functools import lru_cache
import json
from pathlib import Path

from definability_affine_counts import affine_models
from spectrum_generate import load_equations

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/definability_affine_counts.json"
GENERATED = ROOT / "equational_theories/Definability/Generated"


def render_family(entries):
    lines = [
        "import equational_theories.Definability.AffineFamilyCounting",
        "",
        "/-! Generated by scripts/definability_affine_counts_check.py.",
        "Count full source families to avoid large explicit factor arrays. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 2000000",
        "",
    ]
    for e in entries:
        s, t, n = e["source"], e["target"], e["modulus"]
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_affineCount"
        lines += [
            f"/-- {e['source_count']} affine source operations, but only {e['target_count']} target triples. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            f"  apply not_termStructuralFromFin_of_cloneFamily_count (AffineFamily.op (R := ZMod {n})) AffineFamily.op_injective",
            "    (1, 0, 0) (0, 1, 0) AffineFamily.comp AffineFamily.op_fst AffineFamily.op_snd AffineFamily.op_comp",
            f"    (fun p : AffineFamily.P (ZMod {n}) => @Equation{s} (ZMod {n}) ⟨AffineFamily.op p⟩)",
            f"    (fun p : AffineFamily.P (ZMod {n}) => AffineTest Law{t} p.1 p.2.1 p.2.2)",
            "  · intro p hp",
            f"    exact (@Law{s}.models_iff (ZMod {n}) ⟨AffineFamily.op p⟩).mpr hp",
            "  · intro p hp",
            "    exact affineTest_of_satisfies hp",
            "  · native_decide",
            "",
            f"/-- info: '{name}' depends on axioms: [propext, Classical.choice, Quot.sound,",
            f"{name}._native.native_decide.ax_1_1] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def render(entries):
    if any(e.get("full_family") for e in entries):
        assert all(e.get("full_family") for e in entries)
        return render_family(entries)
    lines = [
        "import equational_theories.Definability.AffineCounting",
        "import Mathlib.Tactic.ReduceModChar",
        "",
        "/-! Generated by scripts/definability_affine_counts_check.py.",
        "Source identities are proved algebraically; only target triples are counted. -/",
        "",
        "open Law Law.MagmaLaw Magma",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 4000000",
        "set_option linter.unnecessarySeqFocus false",
        "",
    ]
    for entry in entries:
        s, t, n = entry["source"], entry["target"], entry["modulus"]
        factors = entry["factors"]
        k = len(factors)
        a, b, c = (", ".join(str(p[i]) for p in factors) for i in range(3))
        name = f"Equation{t}_not_termStructuralFromFin_Equation{s}_affineCount"
        tactic = "decide" if n <= 5 else "native_decide"
        lines += [
            f"/-- {k} distinct affine source factors over `ZMod {n}`, but only",
            f"{entry['target_count']} target coefficient triples. -/",
            f"theorem {name} : ¬ Law{t}.TermStructuralFromFin Law{s} := by",
            "  apply not_termStructuralFromFin_of_affine_count",
            f"    (![{a}] : Fin {k} → ZMod {n})",
            f"    (![{b}] : Fin {k} → ZMod {n})",
            f"    (![{c}] : Fin {k} → ZMod {n})",
            "  · native_decide" if entry.get("native_injective") else "  · decide",
            "  · intro i",
            f"    apply (@Law{s}.models_iff (ZMod {n}) (aff _ _ _)).mpr",
            (
                "    revert i\n    native_decide"
                if entry.get("native_source")
                else f"    fin_cases i <;> norm_num [Equation{s}, aff_op] <;> intros <;> ring_nf <;> reduce_mod_char"
            ),
            f"  · {tactic}",
            "",
        ]
        axioms = ["propext", "Classical.choice", "Quot.sound"]
        native_count = int(entry.get("native_injective", False)) + int(
            tactic == "native_decide"
        )
        axioms += [
            f"{name}._native.native_decide.ax_1_{i}" for i in range(1, native_count + 1)
        ]
        lines += [
            f"/-- info: '{name}' depends on axioms: [{', '.join(axioms)}] -/",
            "#guard_msgs (whitespace := lax) in",
            f"#print axioms {name}",
            "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    equations = load_equations()

    @lru_cache(None)
    def models(law, n):
        return affine_models(equations[law - 1], n)

    entries = data["candidates"]
    for entry in entries:
        s, t, n = entry["source"], entry["target"], entry["modulus"]
        source, target = models(s, n), models(t, n)
        factors = list(map(tuple, entry["factors"]))
        assert len(source) == entry["source_count"]
        assert len(target) == entry["target_count"]
        assert len(set(factors)) == len(factors) == len(target) + 1
        assert set(factors) <= set(source)
    selected = data["selected_indices"]
    assert len(set(selected)) == len(selected)
    assert set().union(*(set(c) for _, c in data["coverage"])) == set(
        range(len(entries))
    )
    for part, indices in enumerate(data["parts"]):
        path = GENERATED / f"AffineCount{part}.lean"
        text = render([entries[i] for i in indices])
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f"regenerate {path} with --write"
    assert sorted(i for part in data["parts"] for i in part) == sorted(selected)
    print(
        f"Verified {len(entries)} affine counts; {len(selected)} Lean certificates reproduced."
    )


if __name__ == "__main__":
    main()
